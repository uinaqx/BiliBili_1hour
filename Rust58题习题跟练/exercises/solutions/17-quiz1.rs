// ============================================================================
// 第 17 题 · quiz1 —— 综合小测：买苹果的阶梯价格
// ----------------------------------------------------------------------------
// 题目类型：test（让 #[test] 测试通过就算过关）
// 课件位置：第 2 章 2.1 变量 + 2.2.3 函数 + 第 4 章 4.1 if 表达式（综合）
// 难度：★★★☆☆
// 前置知识：variables1~6、functions1~5、if1~3（本题是它们的综合运用）
// ============================================================================
//
// 【题目要求】
// Mary 在买苹果，价格规则是：
//   - 每个苹果 2 rustbuck（“锈币”，一种虚构货币）；
//   - 如果购买数量 **超过 40 个**，则每个苹果只要 1 rustbuck。
// 写一个函数，根据购买数量算出总价，让 verify_test 测试通过。
// 原题不给提示（No hints this time ;)）。
//
// 原题代码（未完成，仅供对照）：
//     // Put your function here!
//     // fn calculate_price_of_apples {
//
//     // Don't modify this function!
//     #[test]
//     fn verify_test() {
//         let price1 = calculate_price_of_apples(35);
//         let price2 = calculate_price_of_apples(40);
//         let price3 = calculate_price_of_apples(41);
//         let price4 = calculate_price_of_apples(65);
//
//         assert_eq!(70, price1);
//         assert_eq!(80, price2);
//         assert_eq!(41, price3);
//         assert_eq!(65, price4);
//     }
//
// 【解题思路】
// 1. 先从测试反推需求（这是工程里最常用的读题方式）：
//      calculate_price_of_apples(35) == 70   → 35 × 2 = 70，未打折
//      calculate_price_of_apples(40) == 80   → 40 × 2 = 80，未打折
//      calculate_price_of_apples(41) == 41   → 41 × 1 = 41，已打折
//      calculate_price_of_apples(65) == 65   → 65 × 1 = 65，已打折
// 2. 临界点在 40 与 41 之间：数量 **大于 40** 才打折。
//    （注意：40 个还是 2 元一个，说明规则是“超过 40”，不是“满 40”）
// 3. 函数签名：接收一个数量（整数 i32），返回总价（整数 i32）。
// 4. 函数体用 if 表达式：数量 > 40 → quantity * 1（直接写 quantity）；
//    否则 → quantity * 2。
// 5. 最后一行不带分号，if 表达式的值就是返回值。
//
// ============================================================================
//                              知 识 铺 垫
// ============================================================================
//
// ● 函数定义的完整形式（复习 functions1~5）
//     fn 函数名(参数名: 类型, ...) -> 返回类型 {
//         函数体
//     }
//   - 参数类型**必须**写，不能省；
//   - 返回类型写在 -> 后面；不写 -> 表示返回 ()（空元组，类似 void）；
//   - 最后一行是表达式且不带分号 → 它的值就是返回值。
//   如果写成 `-> i32` 却忘了返回值，会报 E0308（expected i32, found ()）。
//
// ● 为什么函数名可以不加 pub？
//   本题的测试函数和它写在**同一个文件、同一个模块**里，
//   直接调用即可；pub 是给“模块外部”用的。
//   （if1~if3 里加了 pub，是因为那样写更通用，并不是强制要求。）
//
// ● 算术运算符
//     +  -  *  /  %
//   本题用乘法：quantity * 2。
//   Rust 的整数乘法：i32 × i32 结果还是 i32。
//   如果两个整数相除，结果会**向下取整**：7 / 2 == 3（这一点以后要小心）。
//
// ● 比较运算符（结果一定是 bool）
//     >  大于      <  小于
//     >= 大于等于  <= 小于等于
//     == 等于      != 不等于
//   注意 = 是赋值，== 才是比较，不要写混。
//
// ● if 是表达式（复习 if1~if3）
//     if 条件 { 值1 } else { 值2 }
//   两个分支必须是同一类型。本题两支都是 i32，整个 if 的类型就是 i32。
//
// ● 边界条件（off-by-one）是编程里最常见的坑之一
//   “超过 40 个” → quantity > 40
//   “满 40 个”   → quantity >= 40
//   测试里 40 个仍然是 80 元，所以必须用 > 40；写成 >= 40 会让 price2 变成 40，
//   测试就会失败。写代码前先想清楚边界，比事后调试省事得多。
//
// ● 关于 #[test] 与 --test
//   原题把 verify_test 写在文件最外层（不在 mod tests 里），也照样是测试函数。
//   文件里没有 main，所以必须用 `rustc --test` 编译，会生成一个自动的测试入口。
//
// ============================================================================
//                              参 考 答 案
// ============================================================================

// 计算买 quantity 个苹果的总价（单位：rustbuck）
// quantity 用 i32：测试里传的是 35、40、41、65 这类整数
fn calculate_price_of_apples(quantity: i32) -> i32 {
    // if 是表达式：条件为真取上面分支的值，否则取下面分支的值
    // 规则：数量“超过 40”才打折（40 个不打折，所以用 > 而不是 >=）
    if quantity > 40 {
        quantity // 每个 1 rustbuck，总价就是 quantity × 1，可直接写 quantity
    } else {
        quantity * 2 // 每个 2 rustbuck，总价 = quantity × 2
    }
    // 这个 if 表达式的值（i32）就是函数返回值，所以不需要写 return
}

// ---------------------------------------------------------------------------
// 原题自带、要求“不要修改”的测试。此处一字未改。
// ---------------------------------------------------------------------------
#[test]
fn verify_test() {
    // 35 个：35 × 2 = 70
    let price1 = calculate_price_of_apples(35);
    // 40 个：正好 40，不打折，40 × 2 = 80
    let price2 = calculate_price_of_apples(40);
    // 41 个：超过 40，每个 1 元，总价 41
    let price3 = calculate_price_of_apples(41);
    // 65 个：超过 40，总价 65
    let price4 = calculate_price_of_apples(65);

    // assert_eq!(期望值, 实际值)：不相等就 panic，测试判为失败
    assert_eq!(70, price1);
    assert_eq!(80, price2);
    assert_eq!(41, price3);
    assert_eq!(65, price4);
}

// ============================================================================
//                            逐 行 解 析
// ============================================================================
//
// fn calculate_price_of_apples(quantity: i32) -> i32
//   ├─ fn                ：定义函数
//   ├─ calculate_price_of_apples ：函数名（蛇形命名 snake_case）
//   ├─ quantity: i32     ：参数名 + 类型（Rust 强制写类型）
//   └─ -> i32            ：返回 32 位有符号整数
//
// if quantity > 40 {
//   ├─ quantity > 40     ：比较运算，得到 bool（true / false）
//   └─ quantity          ：打折分支的值（每个 1 元，总价 = quantity × 1）
// } else {
//     quantity * 2       ：不打折分支的值（每个 2 元）
// }
//
// 四个测试输入走过的分支：
//   35 → 35 > 40 为假 → else → 35 * 2 = 70  ✓
//   40 → 40 > 40 为假 → else → 40 * 2 = 80  ✓（关键边界！）
//   41 → 41 > 40 为真 → quantity → 41       ✓
//   65 → 65 > 40 为真 → quantity → 65       ✓
//
// ============================================================================
//                          常 见 错 误 与 提 示
// ============================================================================
//
// 1. 把“超过 40”写成 >= 40：
//        if quantity >= 40 { quantity } else { quantity * 2 }
//    → 编译通过，但 price2 期望 80、实际 40：
//      assertion `left == right` failed:  left: 80, right: 40
//
// 2. 忘了写返回类型或参数类型：
//        fn calculate_price_of_apples(quantity) -> i32
//    → error: expected type, found parameter `quantity`
//    （函数参数必须写类型，只有局部变量可以靠推断）
//
// 3. 用了 return 但漏分号，或在表达式后多写分号：
//        if quantity > 40 { return quantity; } else { return quantity * 2; }
//    这种写法其实是对的（带 return 的语句），但要注意 return 后面必须是同类型值。
//    而若在最后写成 `if ... { quantity };`（加了分号），
//    函数返回值就变成 ()，与 -> i32 不符：
//    → error[E0308]: mismatched types
//
// 4. 忘记写 else：
//        if quantity > 40 { quantity }
//    → error[E0317]: `if` may be missing an `else` clause
//
// 5. 用浮点乘法导致类型不符：
//        quantity * 2.0
//    → error[E0308]: expected `i32`, found floating-point number
//
// 6. 把函数名写错（测试里调用的是 calculate_price_of_apples）：
//        fn price_of_apples(quantity: i32) -> i32
//    → error[E0425]: cannot find function `calculate_price_of_apples`
//
// 7. 直接 `rustc quiz1.rs`（没有 main）：
//    → error[E0601]: `main` function not found in crate
//    必须加 --test。
//
// ============================================================================
//                          小 结
// ============================================================================
//
// 本题把第 2 章和第 4 章的知识点串了起来：
//   1. 函数：fn 名字(参数: 类型) -> 返回类型 { ... }；
//   2. 变量：let 绑定 + 类型推断（测试里的 price1 自动是 i32）；
//   3. if 表达式：分支产生值，最后一行不带分号即为返回值；
//   4. 业务逻辑：先读测试反推需求，再注意 40/41 这个边界。
//
// 一句话记忆：**先看测试定边界（> 40 而不是 >= 40），再用 if 表达式返回价格。**
