// ============================================================================
// 第 58 题 · lifetimes3 —— 结构体持有引用：字段里也得写清“租期”
// ----------------------------------------------------------------------------
// 题目类型：compile（把代码改到能编译通过就算过关）
// 课件位置：第 6 章 · 6.2 生命周期（结构体中的生命周期标注）
// 难度：★★★★☆
// 前置知识：第 56、57 题 lifetimes1~2、结构体（structs1）
// ============================================================================
//
// 【题目要求】
// Book 结构体的两个字段都是 `&str`（借用），但结构体没有声明生命周期，
// 导致编译失败。请补上生命周期标注，让代码编译通过并正常运行。
//
// 原题代码（未完成，仅供对照）：
//     struct Book {
//         author: &str,        // ← 借用，但缺少生命周期
//         title: &str,
//     }
//
//     fn main() {
//         let name = String::from("Jill Smith");
//         let title = String::from("Fish Flying");
//         let book = Book { author: &name, title: &title };
//         println!("{} by {}", book.title, book.author);
//     }
//
// 编译器会报：
//     error[E0106]: missing lifetime specifier
//     help: consider introducing a named lifetime parameter
//
// 【解题思路】
// 1. 结构体里只要**存了引用**，就必须告诉编译器“这些引用能活多久”，
//    否则编译器无法检查 book 会不会比它借的数据活得更久。
// 2. 写法：在结构体名后加 `<'a>`，每个引用字段都标上 `&'a`：
//        struct Book<'a> {
//            author: &'a str,
//            title: &'a str,
//        }
// 3. 含义：“Book 的实例不能比 author、title 指向的数据活得更久”。
//    一旦 book 要活过 name/title，编译器就会拦住。
// 4. main 完全不用改 —— `&name`（&String）会自动强制转换成 `&str`
//    （这叫“解引用强制转换”），并填上合适的 'a。
//
// ============================================================================
//                              知 识 铺 垫
// ============================================================================
//
// ● 为什么结构体要管生命周期？
//   前两题的生命周期是写在**函数签名**上的（参数与返回值的关系）。
//   结构体的问题是另一类：结构体**自己持有了引用**。
//        struct Book<'a> { author: &'a str }
//   一旦你造出一个 `book`，它就“抱着”别人数据的地址。
//   如果数据的主人（name）先被释放，book 就成了悬垂引用 —— 必须拦住。
//   所以编译器要求你把这种依赖关系写在类型里。
//
// ● 打个比方：借书卡
//   结构体 `Book` 就像一张“借书登记卡”，字段里记的是“书在谁手里（地址）”，
//   而不是书本身。卡片上必须写明租期 'a：
//   “只要书还在，这张卡就有效；书还回去了，卡片作废。”
//   生命周期标注就是卡片上的租期条款。
//
// ● 为什么两个字段都用同一个 'a？
//   因为 Book 的实例是一个整体，它不能比**任何一个**借用字段活得更久，
//   所以 'a 取两者中较短的那个（和第 57 题的“取交集”是同一个道理）。
//   如果你想更精细，可以写两个：
//        struct Book<'a, 'b> { author: &'a str, title: &'b str }
//   但本题没必要，一个 'a 更简洁。
//
// ● 结构体方法里的生命周期
//   如果给 Book 写 impl，通常也要带上生命周期：
//        impl<'a> Book<'a> {
//            fn info(&self) -> &'a str { self.author }   // 返回的引用跟字段同寿命
//        }
//   注意 `&self` 和 `'a` 是两回事：`&self` 是“借用这个结构体”，
//   `'a` 是“结构体内部引用字段的租期”。
//
// ● `&name`（&String）怎么能塞进 `&str` 字段？
//   这叫“解引用强制转换（deref coercion）”：
//   String 实现了 Deref<Target = str>，所以在需要 &str 的地方可以传 &String。
//   编译器会自动把 &String 转成 &str，不用写 `&name[..]` 或 `name.as_str()`。
//   （函数传参、结构体字段初始化都属于这种“强制转换点”。）
//
// ● 什么时候可以完全不写生命周期？
//   如果结构体字段全是“拥有所有权”的类型（String、i32、Vec<T> ……），
//   就不需要生命周期参数 —— 因为它不借任何东西。
//   只有字段里出现 `&` 或 `&mut` 时才需要。
//
// ● 'static 字段
//       struct Config { name: &'static str }
//   表示“这个引用活到程序结束”，字符串字面量可以直接放进去。
//   但本题的 name/title 是 String（运行时创建），不是 'static。
//
// ============================================================================
//                              参 考 答 案
// ============================================================================

// 在结构体名后声明生命周期参数 'a
// 两个引用字段都标注为 &'a str，表示它们的租期同为 'a
struct Book<'a> {
    // 作者名：借用一段字符串
    author: &'a str,
    // 书名：借用另一段字符串
    // （两个字段可以来自不同变量，但都必须至少活到 'a）
    title: &'a str,
}

fn main() {
    // name 是拥有所有权的 String，活到 main 结束
    let name = String::from("Jill Smith");

    // title 同理
    let title = String::from("Fish Flying");

    // 造一个 Book：
    //   &name  —— 类型是 &String，通过解引用强制转换变成 &str
    //   &title —— 同理
    // 编译器由此推断 'a = “name、title、book 三者共存的那段区间”
    let book = Book {
        author: &name,
        title: &title,
    };

    // 读取 book 的字段并打印
    // 字段本身就是 &str，可以直接显示；book 依然只是“借用”，没有拿走 name/title
    println!("{} by {}", book.title, book.author);
}

// ============================================================================
//                            详 细 解 析
// ============================================================================
//
// 1）不写生命周期时，编译器到底在抱怨什么？
//    `struct Book { author: &str }` —— 编译器看到“一个存引用的结构体”，
//    但不知道这个引用能活多久。它无法判断
//        let b;
//        {
//            let s = String::from("x");
//            b = Book { author: &s };
//        }
//        println!("{}", b.author);   // 危险！
//    这种代码该不该拒绝？没有标注就无法回答，所以直接报 E0106 让你写清楚。
//
// 2）加了 <'a> 之后，上面那段危险代码会怎样？
//    会报 error[E0597]: `s` does not live long enough
//    —— 因为 'a 被推断成“s 的寿命”，而 b 用到了 'a 之后。
//    这正是标注的价值：让编译器有依据地拦住悬垂引用。
//
// 3）'a 在 `let book = Book { ... }` 处被推断成多长？
//    取 name、title、book 三者寿命的交集（较短者）。
//    本例三个变量都在 main 里，活到 main 结束，所以 'a 覆盖整个 main 剩余部分。
//
// 4）book 会不会“拿走” name 的所有权？
//    不会。`&name` 只是借用，book 里存的是一个地址 + 长度。
//    main 结束后，释放顺序大致是 book（无堆内存）、title、name，
//    没有任何双重释放风险。
//
// 5）如果想让 Book 拥有字符串，怎么写？
//        struct Book {
//            author: String,
//            title: String,
//        }
//        let book = Book { author: name, title: title };   // 移动进去
//    这样就不需要生命周期参数了 —— 因为没有借用。
//    两种设计各有取舍：
//        存 &str   —— 轻量、零拷贝，但调用者要保证数据活得够久（本题）；
//        存 String —— 自包含、好传好存，但要复制/移动数据。
//
// 6）打印语句为什么写 `book.title, book.author` 而不是反过来？
//    格式串是 `"{} by {}"`，即“书名 by 作者”，所以第一个参数是 title。
//    输出：Fish Flying by Jill Smith。
//
// 7）能不能在类型标注处只写 `Book`？
//        let book: Book = ...;
//    → error[E0106] / 提示需要生命周期实参。应该写 `Book<'_>`：
//        let book: Book<'_> = Book { ... };
//    `'_` 是“匿名生命周期”，意思是“你帮我推断”，写起来最省事。
//    本题靠类型推断，连标注都不用写。
//
// ============================================================================
//                          常 见 错 误 与 提 示
// ============================================================================
//
// 1. 只在字段上写 'a，忘了在结构体名后声明：
//        struct Book { author: &'a str, title: &'a str }
//    → error[E0261]: use of undeclared lifetime name `'a`
//
// 2. 声明了 <'a> 但字段没标：
//        struct Book<'a> { author: &str, title: &str }
//    → error[E0106]: missing lifetime specifier（字段仍然缺标注）
//      外加 warning: lifetime parameter `'a` never used
//
// 3. 把 & 去掉，改成 String：
//        struct Book { author: String, ... }
//    → 语法能过，但 main 里 `Book { author: &name }` 会报 E0308
//      （expected `String`, found `&String`），必须改成 author: name（移动）
//
// 4. 试图在字段上写 'static：
//        struct Book { author: &'static str }
//    → error[E0597]: `name` does not live long enough
//      （String 的借用不是 'static，'static 要求数据永生）
//
// 5. 在 impl 里漏了生命周期：
//        impl Book { fn info(&self) -> &str { self.author } }
//    → error[E0107]: missing generics for struct `Book`
//      正确写法：`impl<'a> Book<'a>`
//
// 6. 以为 `&name` 会自动变成 String：
//    → 不会。&String 只能强制转换成 &str，不能变成拥有所有权的 String。
//
// ============================================================================
//                          小 结
// ============================================================================
//
// 本题你需要记住：
//   1. 结构体字段里只要有 `&`，结构体就必须带生命周期参数 `<'a>`；
//   2. 每个引用字段都要标 `&'a`（或分别标 'a、'b），不能只标一个地方；
//   3. 标注的含义是“实例不能比借来的数据活得更久”，编译器据此拦截悬垂引用；
//   4. `&String` 会自动强制转换成 `&str`，所以 main 里不用改；
//   5. 想摆脱生命周期，就让结构体“拥有数据”（字段用 String 而不是 &str）。
//
// 一句话记忆：**结构体里存了借来的东西，就得在类型上写清租期；要么借、要么拥有，二选一。**
//
