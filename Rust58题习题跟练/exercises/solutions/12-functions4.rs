// ============================================================================
// 第 12 题 · functions4 —— 函数要返回值，就得写清返回类型
// ----------------------------------------------------------------------------
// 题目类型：compile（把代码改到能编译通过就算过关）
// 课件位置：第 2 章 · 2.2.3 函数（返回类型 `-> i32`、if 作为表达式）
// 难度：★★☆☆☆
// 前置知识：functions1~3（函数、参数）、variables2（i32、if/else）
// ============================================================================
//
// 【题目要求】
// 这是一家商店的打折规则：价格是偶数减 10，是奇数减 3。
// main 里用 `sale_price(original_price)` 把返回值打印出来，
// 但 sale_price 的返回类型漏写了。
//
// 原题代码（未完成，仅供对照）：
//     fn main() {
//         let original_price = 51;
//         println!("Your sale price is {}", sale_price(original_price));
//     }
//
//     fn sale_price(price: i32) -> {
//         if is_even(price) {
//             price - 10
//         } else {
//             price - 3
//         }
//     }
//
//     fn is_even(num: i32) -> bool {
//         num % 2 == 0
//     }
//
// 编译会报错：
//     error: expected type, found `{`
//      --> functions4.rs:18:30
//       |
//    18 | fn sale_price(price: i32) -> {
//       |                               ^ expected type
//     （`->` 后面本该跟一个类型，却遇到了 `{`）
//
// 【解题思路】
// 1. `->` 的意思是“这个函数会返回一个值，返回类型是……”。
//    箭头后面必须跟一个具体类型，不能空着。
// 2. 看函数体：不管走 if 还是 else，最后算出来的都是 `price - 10` 或
//    `price - 3`，都是 i32。所以返回类型就是 i32。
// 3. 补成：
//        fn sale_price(price: i32) -> i32 {
// 4. 顺便理解函数体：`if ... { a } else { b }` 在这里是一个“表达式”，
//    它会产出一个值；这个值没有分号，正好作为函数的返回值。
//
// ============================================================================
//                              知 识 铺 垫
// ============================================================================
//
// ● 返回类型怎么写
//       fn 函数名(参数) -> 类型 { 函数体 }
//                        ^^
//                       减号 + 大于号，读作“返回”
//   例：
//       fn is_even(num: i32) -> bool { ... }   // 返回 bool
//       fn sale_price(price: i32) -> i32 { ... } // 返回 i32
//   没有返回值就整个省略 `-> 类型`（等价于返回 `()`）。
//
// ● 返回值从哪来？—— 函数体最后一个“表达式”
//   Rust 的函数体是一段代码块，代码块的值 = 最后一个**不带分号**的表达式。
//       fn square(n: i32) -> i32 {
//           n * n        // ← 没有分号 → 这就是返回值
//       }
//   如果写成 `n * n;`（带分号），它就变成“语句”，值被丢掉，
//   函数实际返回 `()`，就会报类型不匹配（functions5 专门练这个）。
//
// ● 表达式 vs 语句
//   表达式（expression）：能算出一个值。例如 1 + 2、x == 10、if ... { } else { }。
//   语句（statement）：只做事，不产生值（类型是 ()）。例如 `let x = 3;`、
//   带分号的 `x + 1;`、`println!(...);`。
//   Rust 里“分号”常常就是“把表达式变成语句”的开关。
//
// ● if 也是表达式
//       let y = if x > 0 { 1 } else { -1 };
//   这是合法的：整个 if 会产出一个值赋给 y。
//   但要求两个分支的类型一致（这里都是整数），否则报 E0308。
//   本题两个分支分别是 `price - 10` 和 `price - 3`，都是 i32，所以没问题。
//
// ● 也可以显式写 return
//       fn sale_price(price: i32) -> i32 {
//           if is_even(price) {
//               return price - 10;
//           }
//           price - 3
//       }
//   `return 值;` 会立刻结束函数并把值交回去。
//   但 Rust 的惯用风格是“最后一行表达式即返回值”，更简洁，少写 return。
//
// ● 取余 `%` 和比较 `==`
//       num % 2 == 0
//   `%` 是取余数：51 % 2 = 1，4 % 2 = 0。
//   `==` 判断相等，结果是 bool。
//   所以 is_even 的意思是“除以 2 余 0 就是偶数”，返回 true/false。
//   注意运算顺序：先算 %，再算 ==（和数学一样，算术优先于比较）。
//
// ● 本题的执行流程
//   51 是奇数 → is_even(51) 返回 false → 走 else → 51 - 3 = 48 → 返回 48
//   所以打印 Your sale price is 48。
//
// ============================================================================
//                              参 考 答 案
// ============================================================================

fn main() {
    // 原价 51，类型推断为 i32
    let original_price = 51;

    // sale_price(original_price) 会返回打折后的价格（i32），
    // 直接被 {} 接住并打印
    println!("Your sale price is {}", sale_price(original_price));
}

// 关键改动：`->` 后面补上返回类型 i32
//   fn sale_price(price: i32) -> i32
//                              ^^^ 返回一个 32 位整数
fn sale_price(price: i32) -> i32 {
    // if 在这里是“表达式”：它会算出一个值，作为整个函数的返回值
    // is_even(price) 返回 bool，作为分支条件
    if is_even(price) {
        // 偶数分支：price - 10，**没有分号**，所以这个值会被返回
        price - 10
    } else {
        // 奇数分支：price - 3，同样没有分号
        price - 3
    }
}

// 这个函数原题就写好了，用来判断偶数
// 返回类型 bool 表示 true（是偶数）/ false（不是偶数）
fn is_even(num: i32) -> bool {
    // num % 2 求余数；== 0 判断余数是否为 0；
    // 整个表达式的结果是 bool，正好作为返回值（同样没有分号）
    num % 2 == 0
}

// ============================================================================
//                            逐 行 解 析
// ============================================================================
//
// fn sale_price(price: i32) -> i32 {
//   ├─ fn            ：定义函数
//   ├─ sale_price    ：函数名
//   ├─ price: i32    ：形参，接收原价
//   ├─ -> i32        ：返回类型，**必须写**（原题就是这里缺了）
//   └─ { ... }       ：函数体；最后一个表达式的值就是返回值
//
// if is_even(price) { price - 10 } else { price - 3 }
//   ├─ is_even(price) ：调用另一个函数，得到 true/false
//   ├─ price - 10     ：true 时算出的值（无分号 → 参与返回）
//   └─ price - 3      ：false 时算出的值（无分号 → 参与返回）
//
// fn is_even(num: i32) -> bool { num % 2 == 0 }
//   ├─ num % 2   ：取余，偶数得 0，奇数得 1
//   ├─ == 0      ：比较，得到 bool
//   └─ 无分号    ：bool 作为返回值
//
// main 中：
//   original_price = 51 → is_even(51) = false → price - 3 = 48
//   → 打印 Your sale price is 48
//
// ============================================================================
//                          常 见 错 误 与 提 示
// ============================================================================
//
// 1. `->` 后面空着（= 原题状态）：
//        fn sale_price(price: i32) -> {
//    → error: expected type, found `{`
//
// 2. 返回类型写成 (), 但函数体返回了 i32：
//        fn sale_price(price: i32) { price - 3 }
//    → error[E0308]: mismatched types
//      （期望 ()，实际是 i32；而且还会警告这个表达式的值没被使用）
//
// 3. 在返回值后面加了分号：
//        price - 3;
//    → error[E0308]: mismatched types（期望 i32，实际是 ()）
//    这是新手最常踩的坑，记住：**要返回的表达式不能带分号**。
//
// 4. 两个分支类型不一致：
//        if c { 1 } else { "two" }
//    → error[E0308]: `if` and `else` have incompatible types
//
// 5. 忘了写返回类型但函数体有值：
//        fn sale_price(price: i32) {
//            price - 3
//        }
//    → error[E0308]: mismatched types（函数默认返回 ()）
//
// 6. 把 return 写在表达式位置又加分号：
//        return price - 3;
//    → 这个其实是对的（return 本身是语句），但风格上不如省略 return 简洁。
// ============================================================================
//                          小 结
// ============================================================================
//
// 本题你需要记住：
//   1. 有返回值的函数必须写 `-> 类型`；
//   2. 函数体最后一个不带分号的表达式就是返回值；
//   3. 加了分号就变成语句，值被丢弃，返回类型会变成 ()；
//   4. if / else 是表达式，可以产出值，两个分支类型必须一致；
//   5. `%` 取余、`==` 比较得到 bool，bool 正是 if 条件需要的类型。
//
// 一句话记忆：**箭头写类型，末尾不带分号的那个表达式就是“交作业”。**
//
