// ============================================================================
// 第 15 题 · if2 —— 多个条件分支，返回类型必须一致
// ----------------------------------------------------------------------------
// 题目类型：test（让 #[test] 测试通过就算过关）
// 课件位置：第 4 章 · 4.1 if / else if / else（各分支返回值类型必须一致）
// 难度：★★☆☆☆
// 前置知识：if 是表达式（第 14 题 if1）、&str 字符串切片（第 3 章 3.1）
// ============================================================================
//
// 【题目要求】
// 两步：
//   Step 1：让代码编译通过（原题 else 分支返回了数字 1，类型不对）；
//   Step 2：让 bar_for_fuzz 和 default_to_baz 两个测试也通过
//           （原文注释说“测试不用改”，意思是只改函数体）。
// 原题代码（未完成，仅供对照）：
//     pub fn foo_if_fizz(fizzish: &str) -> &str {
//         if fizzish == "fizz" {
//             "foo"
//         } else {
//             1
//         }
//     }
//
//     #[cfg(test)]
//     mod tests {
//         use super::*;
//
//         #[test]
//         fn foo_for_fizz() {
//             assert_eq!(foo_if_fizz("fizz"), "foo")
//         }
//
//         #[test]
//         fn bar_for_fuzz() {
//             assert_eq!(foo_if_fizz("fuzz"), "bar")
//         }
//
//         #[test]
//         fn default_to_baz() {
//             assert_eq!(foo_if_fizz("literally anything"), "baz")
//         }
//     }
//
// 编译会报错：
//     error[E0308]: `if` and `else` have incompatible types
//     expected `&str`, found integer
//
// 【解题思路】
// 1. 函数签名要求返回 &str（字符串切片，“一段文本的引用”）。
// 2. 第一个分支返回 "foo"，类型是 &str，没问题；
//    但 else 分支写的是 `1`，那是整数 i32，两个分支类型不一致 → 编译报错。
// 3. 从测试倒推需求：
//      foo_if_fizz("fizz")  → "foo"
//      foo_if_fizz("fuzz")  → "bar"
//      foo_if_fizz("其它任何东西") → "baz"
// 4. 于是需要三个分支：if → "foo"，else if → "bar"，else → "baz"。
//    三个分支都是 &str，类型统一，编译通过，测试全过。
//
// ============================================================================
//                              知 识 铺 垫
// ============================================================================
//
// ● &str 是什么？
//   str 是“字符串切片”类型，表示一段 UTF-8 文本。
//   它的大小在编译期未知，所以日常都写成引用 &str（借来的一段文本）。
//   字符串字面量 "foo" 的类型就是 &'static str（静态存储、全程序有效）。
//   对比：String 是“拥有所有权的可增长字符串”（第 3 章 3.1 会细讲）。
//   本题只读、不修改，用 &str 最合适，也不涉及所有权转移。
//
// ● 字符串比较用 ==
//   fizzish == "fizz" 会逐个字符比较内容（不是比较内存地址）。
//   所以参数是 &str、右边是 &str，两边类型一致，可以比较。
//
// ● if / else if / else 链
//   从上往下依次判断，命中第一个为真的分支就执行它，后面的全部跳过。
//     if 条件1 { ... }
//     else if 条件2 { ... }
//     else if 条件3 { ... }
//     else { ... }          ← 兜底，可以省略（但省略后 if 表达式没有值）
//   注意不要写成 C 里的 `else if` 漏写 if 之类的形式。
//
// ● “所有分支类型一致”这条规则
//   编译器把每个分支都看作“候选值”，它们必须能统一成同一个类型，
//   这个统一后的类型就是整个 if 表达式的类型。
//   本题统一后的类型必须是 &str，才能对上 `-> &str`。
//
// ● 为什么把字符串字面量直接返回是合法的？
//   字面量 "foo" 存放在程序的只读数据区，生命周期是 'static（整个程序），
//   而返回类型 &str 的生命周期被省略规则绑到输入参数 fizzish 上，
//   'static 比参数活得更久，所以可以安全返回，不会出现悬垂引用。
//
// ● 测试函数的返回值
//   注意原题测试写成 `assert_eq!(...)` 末尾没有分号 —— 这没问题，
//   assert_eq! 宏在断言成立时返回 ()，函数返回类型也是 ()，正好匹配。
//
// ============================================================================
//                              参 考 答 案
// ============================================================================

// fizzish: &str  —— 借来的一段文本，函数不会拿走它的所有权
// -> &str        —— 返回一段文本的引用；由于只传入了一个引用参数，
//                   Rust 的生命周期省略规则会把返回值绑定到该参数上
pub fn foo_if_fizz(fizzish: &str) -> &str {
    // 分支 1：输入正好是 "fizz" → 返回 "foo"
    if fizzish == "fizz" {
        "foo" // 字符串字面量，类型 &'static str，可以安全返回
    } else if fizzish == "fuzz" {
        // 分支 2：新增的判断，让 bar_for_fuzz 测试通过 → 返回 "bar"
        "bar"
    } else {
        // 分支 3：兜底分支，其它任何输入都返回 "baz"
        // （原来这里写的是数字 1，类型不对，正是编译错误的根源）
        "baz"
    }
}

// ---------------------------------------------------------------------------
// 下面这段是原题自带的测试代码，完全没有改动。
// ---------------------------------------------------------------------------
#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn foo_for_fizz() {
        assert_eq!(foo_if_fizz("fizz"), "foo")
    }

    #[test]
    fn bar_for_fuzz() {
        assert_eq!(foo_if_fizz("fuzz"), "bar")
    }

    #[test]
    fn default_to_baz() {
        assert_eq!(foo_if_fizz("literally anything"), "baz")
    }
}

// ============================================================================
//                            逐 行 解 析
// ============================================================================
//
// if fizzish == "fizz" { "foo" }
//   ├─ fizzish        ：&str 参数
//   ├─ ==             ：按内容比较两个 &str
//   └─ "foo"          ：分支的值，&str
//
// else if fizzish == "fuzz" { "bar" }
//   ├─ 只有第一个条件为假时才会判断这一行
//   └─ 值 "bar"，类型同样是 &str
//
// else { "baz" }
//   └─ 兜底，保证 if 表达式在任何输入下都有值
//
// 三个分支都是 &str → 整个 if 表达式类型是 &str → 与 -> &str 匹配 → 编译通过。
//
// ============================================================================
//                          常 见 错 误 与 提 示
// ============================================================================
//
// 1. 不删掉 else 里的 1（原题错误状态）：
//    → error[E0308]: `if` and `else` have incompatible types
//      expected `&str`, found integer
//
// 2. 把 "bar" 写成 String：
//        else if fizzish == "fuzz" { String::from("bar") }
//    → error[E0308]: expected `&str`, found `String`
//    （String 拥有所有权，与 &str 不是同一类型；可加 .as_str() 或直接写字面量）
//
// 3. 只改 else 不新增 else if：
//        else { "baz" }
//    → 编译通过，但 bar_for_fuzz 测试失败：
//      assertion `left == right` failed:  left: "baz", right: "bar"
//
// 4. 条件顺序写反：
//        if fizzish == "fuzz" { "foo" } ...
//    → 逻辑与测试期望不符，测试失败。
//
// 5. 用 = 代替 ==：
//        if fizzish = "fizz" {
//    → error[E0308]: mismatched types，expected `bool`, found `&str`
//    （= 是赋值，== 才是比较；Rust 不允许把赋值当条件）
//
// 6. 漏写 --test：
//        rustc if2.rs
//    → error[E0601]: `main` function not found in crate
//
// ============================================================================
//                          小 结
// ============================================================================
//
// 本题你需要记住：
//   1. if / else if / else 是从上往下的“多路选择”；
//   2. 所有分支的值的类型必须一致，也和函数返回类型一致；
//   3. "文本" 字面量类型是 &str，String 是另一种类型，不能混用；
//   4. 字符串比较用 ==，按内容比较。
//
// 一句话记忆：**if 链上每个分支都得“交出同一种类型”的值。**
//
