// ============================================================================
// 第 07 题 · variables5 —— 变量遮蔽：同一个名字，换一个“新人”
// ----------------------------------------------------------------------------
// 题目类型：compile（把代码改到能编译通过就算过关）
// 课件位置：第 2 章 · 2.1.3 变量遮蔽（Shadowing）
// 难度：★★☆☆☆
// 前置知识：variables4（mut 只能改值、不能改类型）
// ============================================================================
//
// 【题目要求】
// 先用同一个名字 number 存一段字符串 "T-H-R-E-E"，把它打印出来；
// 然后让这个名字改存数字 3，并计算 number + 2。
// 限制：第 1 行的赋值和第 3 行的“变量名”都不能改。
//
// 原题代码（未完成，仅供对照）：
//     fn main() {
//         let number = "T-H-R-E-E"; // don't change this line
//         println!("Spell a Number : {}", number);
//         number = 3; // don't rename this variable
//         println!("Number plus two is : {}", number + 2);
//     }
//
// 编译会报两处错：
//     1) error[E0384]: cannot assign twice to immutable variable `number`
//        （number 没加 mut，不能重新赋值）
//     2) 就算加了 mut，也会报
//        error[E0308]: mismatched types
//        （number 已经是 &str 了，不能塞进去一个整数 3）
//
// 【解题思路】
// 1. 先用 mut 试试行不行：
//        let mut number = "T-H-R-E-E";
//        number = 3;      // ← 这里会失败
//    因为 mut 只允许“改值”，不允许“改类型”。number 已经被定死为 &str。
// 2. 题目真正想要的技术叫**变量遮蔽（shadowing）**：
//    允许用 `let` 再声明一个**同名**变量，新变量会“遮住”旧变量。
//        let number = "T-H-R-E-E";   // 第 1 个 number，&str
//        let number = 3;             // 第 2 个 number，i32 —— 遮蔽了第 1 个
// 3. 所以在 `number = 3;` 前面补一个 `let`，变成 `let number = 3;`
//    既能保持变量名不变（满足题目要求），又能换成完全不同的类型。
// 4. 运行：先打印 Spell a Number : T-H-R-E-E，再打印 Number plus two is : 5。
//
// ============================================================================
//                              知 识 铺 垫
// ============================================================================
//
// ● 什么是“遮蔽”（shadowing）？
//   在同一个作用域里，用 `let` 再声明一个和前面**同名**的变量，
//   新变量就把旧变量“遮住”了。之后写这个名字，指的都是新变量。
//   打个比方：黑板上写着“number = T-H-R-E-E”，你又拿粉笔在同名位置
//   写上“number = 3”，旧内容还在黑板里，但你看到的是新内容。
//   （旧值并不会立刻消失，它会在作用域结束时统一清理；只是名字被占用了。）
//
// ● 遮蔽 vs mut：最容易混的一对
//   ┌──────────────┬────────────────────────┬──────────────────────────┐
//   │              │ mut                    │ 遮蔽（let 同名）         │
//   ├──────────────┼────────────────────────┼──────────────────────────┤
//   │ 写法         │ let mut x = 3;  x = 5; │ let x = 3; let x = 5;    │
//   │ 能否改值     │ 能                     │ 能（其实是新变量）       │
//   │ 能否改类型   │ 不能                   │ 能                       │
//   │ 是否同一个量 │ 是                     │ 不是，是两个变量         │
//   └──────────────┴────────────────────────┴──────────────────────────┘
//   记忆：**mut 是“同一个格子换内容”，遮蔽是“换一个新格子、贴同样的标签”。**
//
// ● 遮蔽的常见用途
//   1. 换类型：先读入字符串，再 parse 成数字：
//          let input = "42";
//          let input: i32 = input.parse().unwrap();  // 同名，类型变了
//   2. 加工一个值，又不想起新名字：
//          let spaces = "   ";
//          let spaces = spaces.len();   // 从 &str 变成 usize
//   3. 让变量“重新变回不可变”：先 let mut 慢慢改，最后用 let 遮蔽成不可变的。
//
// ● 作用域（scope）是什么？
//   一对 `{ }` 之间就是一个作用域。遮蔽只在**同一个作用域内**（或内层作用域）
//   有效；出了内层 `}`，外层同名变量又会“重新露出来”。例如：
//       let x = 1;
//       {
//           let x = 2;       // 只在这个花括号内遮住外面的 x
//           println!("{}", x);   // 2
//       }
//       println!("{}", x);       // 1  ← 又变回外层的 x 了
//   本题两行 let 都在 main 的同一个作用域里，所以第 2 个 number 一直有效到底。
//
// ● 为什么 `number + 2` 能算？
//   此时 number 是 i32，2 也是 i32，`+` 就是普通的整数加法，结果是 5。
//   如果 number 还是字符串 "T-H-R-E-E"，`"T-H-R-E-E" + 2` 是**不允许**的：
//   Rust 不会像 JavaScript 那样偷偷把数字转成字符串。
//   字符串拼接必须两边都是字符串，例如 format!("{}{}", s, t)。
//
// ● 遮蔽会不会“很浪费”？
//   不会。编译器知道旧值后面再也用不到，会做优化；
//   对 &str、i32 这类小类型更是零成本。可以放心用。
//
// ============================================================================
//                              参 考 答 案
// ============================================================================

fn main() {
    // 第 1 个 number：类型是 &str（字符串字面量），内容是 "T-H-R-E-E"
    // 这一行原题不允许改，我们保持原样
    let number = "T-H-R-E-E"; // don't change this line

    // 打印字符串：{} 会原样输出 T-H-R-E-E
    println!("Spell a Number : {}", number);

    // 关键改动：在 number = 3 前面补一个 let
    // 这不是“给旧 number 赋值”，而是**新建了一个同名的 number**，
    // 类型是 i32。旧的 &str 版本被“遮蔽”了，从此这个名字指向新变量。
    let number = 3; // don't rename this variable

    // 此时 number 是 i32，2 也是 i32，加法合法，结果 3 + 2 = 5
    println!("Number plus two is : {}", number + 2);
}

// ============================================================================
//                            逐 行 解 析
// ============================================================================
//
// let number = "T-H-R-E-E";
//   ├─ let         ：声明变量
//   ├─ number      ：变量名
//   ├─ = "T-H-R-E-E"：字符串字面量，类型 &str
//   └─ 生命周期    ：一直到 main 结束（中间被同名变量遮住）
//
// println!("Spell a Number : {}", number);
//   └─ 输出：Spell a Number : T-H-R-E-E
//
// let number = 3;
//   ├─ let    ：又声明了一个变量（不是赋值！），名字还叫 number
//   ├─ 效果   ：旧 number 被遮蔽，新 number 的类型是 i32
//   └─ 从此以后，number 指的都是这个整数
//
// println!("Number plus two is : {}", number + 2);
//   ├─ number + 2：i32 + i32 = 5
//   └─ 输出：Number plus two is : 5
//
// ============================================================================
//                          常 见 错 误 与 提 示
// ============================================================================
//
// 1. 只加 mut，不加 let：
//        let mut number = "T-H-R-E-E";
//        number = 3;
//    → error[E0308]: mismatched types
//      （mut 只允许改值，不允许改类型，这是最典型的误解）
//
// 2. 干脆把 3 写成字符串 "3"：
//        number = "3";
//    → 编译通过，但下一行 number + 2 就没法算了
//      （&str + 整数 是不允许的），而且题意也不对。
//
// 3. 改个新名字避开冲突：
//        let number_str = "T-H-R-E-E";
//        let number = 3;
//    → 编译通过，但题目明确说不要改变量名，而且也没练到遮蔽。
//
// 4. 把遮蔽写到内层花括号里：
//        let number = "T-H-R-E-E";
//        { let number = 3; }
//        println!("{}", number + 2);   // 这里 number 又是 &str 了
//    → error[E0308]，因为出了花括号，遮蔽就失效了。
//
// 5. 误以为遮蔽会“释放”旧变量：
//    → 旧值仍然活到作用域结束（对 String 这类堆类型来说，drop 也在那时发生）。
//      本题的 &str 是静态字符串，不涉及释放，不用担心。
//
// ============================================================================
//                          小 结
// ============================================================================
//
// 本题你需要记住：
//   1. 用 `let` 声明同名变量，就叫变量遮蔽（shadowing）；
//   2. 遮蔽可以换类型，mut 不行；
//   3. 遮蔽产生的是“新变量”，不是修改旧变量；
//   4. 遮蔽只在当前作用域（及其内层）有效，出了 `}` 就还原；
//   5. 常见用途：把字符串解析成数字、加工后仍叫原来的名字。
//
// 一句话记忆：**mut 是换内容，遮蔽是换人但用同一个名字。**
//
