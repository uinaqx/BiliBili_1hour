// ============================================================================
// 第 08 题 · variables6 —— 常量 const：必须写明类型
// ----------------------------------------------------------------------------
// 题目类型：compile（把代码改到能编译通过就算过关）
// 课件位置：第 2 章 · 2.1.1 变量绑定（const 常量：不可变且必须标注类型）
// 难度：★☆☆☆☆
// 前置知识：variables3（类型标注 `: i32`）、variables4（默认不可变）
// ============================================================================
//
// 【题目要求】
// 定义一个常量 NUMBER，值为 3，并在 main 里打印出来。
// 原题写的是 `const NUMBER = 3;`，少写了类型。
//
// 原题代码（未完成，仅供对照）：
//     const NUMBER = 3;
//     fn main() {
//         println!("Number {}", NUMBER);
//     }
//
// 编译会报错：
//     error: missing type for `const` item
//      --> variables6.rs:1:14
//       |
//     1 | const NUMBER = 3;
//       |              ^ help: provide a type for the constant: `: i32`
//     （const 项缺少类型；编译器贴心地把该补的 `: i32` 都写给你了）
//
// 【解题思路】
// 1. `let` 声明变量时，类型可以推断；但 `const` 声明常量时，
//    **类型必须手写**，一个都不能省。这是 Rust 的硬性规定。
// 2. 所以只要在名字后面补上 `: i32`：
//        const NUMBER: i32 = 3;
// 3. 注意 const 语句要写在函数外面（模块级），也可以写在函数里面，
//    但本题按原题保留在 main 之前，属于“整个文件都能用”的常量。
// 4. 常量名习惯全大写（NUMBER），多个单词用下划线连接（MAX_SIZE），
//    编译器会用 warning 提醒你遵守这个约定。
//
// ============================================================================
//                              知 识 铺 垫
// ============================================================================
//
// ● 变量（let）和常量（const）的区别
//   ┌────────────┬──────────────────────┬─────────────────────────────┐
//   │            │ let                  │ const                       │
//   ├────────────┼──────────────────────┼─────────────────────────────┤
//   │ 类型标注   │ 可以省略（能推断）   │ **必须写**                  │
//   │ 可变性     │ 默认不可变，可加 mut │ 永远不可变，没有 const mut  │
//   │ 作用域     │ 从声明处到所在 }     │ 整个模块，甚至可在函数外    │
//   │ 何时求值   │ 运行时               │ **编译期**（必须是常量表达式）│
//   │ 命名习惯   │ snake_case（小写）   │ SCREAMING_SNAKE_CASE（大写）│
//   │ 有无地址   │ 有                   │ 没有固定地址，用到就“抄一份”│
//   └────────────┴──────────────────────┴─────────────────────────────┘
//
// ● 为什么 const 必须写类型？
//   因为常量在**编译期**就要算出值、并直接嵌进使用它的地方。
//   编译器不愿意在“还没有任何上下文”的时候去猜类型 —— 猜错了影响全局。
//   所以规定：写常量请自己说清楚类型。这也让读代码的人一眼知道范围。
//
// ● 什么是“编译期常量表达式”？
//   const 右边只能写编译器能在编译时算出来的东西，例如：
//       const A: i32 = 1 + 2;              // ✅ 可以
//       const B: i32 = 60 * 60 * 24;       // ✅ 可以
//       const C: &str = "hello";           // ✅ 可以
//   不能写需要运行时才知道的值：
//       const D: i32 = read_number();      // ❌ 函数调用，编译期算不出来
//       const E: i32 = x;                  // ❌ x 是运行时变量
//
// ● 常量的“作用域”比变量大
//   本题的 NUMBER 写在 main 外面，属于模块级常量，整个文件都能用。
//   也可以写在函数里面，只在那对 {} 内有效：
//       fn main() {
//           const N: i32 = 3;
//           println!("{}", N);
//       }
//   两种写法都合法，只是可见范围不同。
//
// ● 常量会被“内联”
//   编译器在用到 NUMBER 的地方直接替换成 3，就像你在代码里到处写 3 一样。
//   所以常量没有固定内存地址；如果你需要“有地址的全局变量”，要用 static：
//       static COUNT: i32 = 0;
//   （static 还涉及可变性、线程安全问题，课程后续再深入。）
//
// ● 命名规范是“约定”，不是语法
//   写 `const number: i32 = 3;` 能编译，但会得到：
//       warning: constant `number` should have an upper case name
//   听编译器的话，改成 NUMBER 就好。
//
// ============================================================================
//                              参 考 答 案
// ============================================================================

// 常量声明放在函数外面 = 模块级常量，整个文件都能用
//   const NUMBER: i32 = 3;
//   │     │      │    └─ 值：编译期就能确定的字面量
//   │     │      └────── 类型：const 必须写，不能省
//   │     └───────────── 名字：习惯全大写 + 下划线
//   └─────────────────── 关键字：声明常量
const NUMBER: i32 = 3;

fn main() {
    // 直接使用常量：编译器会把 NUMBER 替换成 3
    // {} 会被替换成 3，所以输出 Number 3
    println!("Number {}", NUMBER);
}

// ============================================================================
//                            逐 行 解 析
// ============================================================================
//
// const NUMBER: i32 = 3;
//   ├─ const      ：声明常量（constant）的关键字
//   ├─ NUMBER     ：常量名，按约定全大写
//   ├─ : i32      ：类型标注，**const 必写**
//   ├─ = 3        ：初值，必须是编译期可求值的常量表达式
//   └─ ;          ：语句结束
//
// fn main() { ... }
//   └─ 程序入口
//
// println!("Number {}", NUMBER);
//   ├─ "Number {}"：格式化字符串
//   ├─ NUMBER     ：常量，编译后相当于直接写 3
//   └─ 输出       ：Number 3
//
// ============================================================================
//                          常 见 错 误 与 提 示
// ============================================================================
//
// 1. 不写类型（= 原题状态）：
//        const NUMBER = 3;
//    → error: missing type for `const` item
//
// 2. 想改常量：
//        const NUMBER: i32 = 3;
//        NUMBER = 4;
//    → error[E0070]: invalid left-hand side of assignment
//    （常量不能作为赋值的目标；它压根不是“变量”）
//
// 3. 给 const 加 mut：
//        const mut NUMBER: i32 = 3;
//    → error: expected identifier, found keyword `mut`（const 不接受 mut）
//
// 4. 用运行时才能算出的值初始化：
//        const NUMBER: i32 = 1 + 2;          // ✅ 编译期可算
//        let a = 1;
//        const B: i32 = a;                    // ❌ a 是运行时变量
//    → error[E0435]: attempt to use a non-constant value in a constant
//
// 5. 名字不大写：
//        const number: i32 = 3;
//    → 能编译，但有 warning: constant `number` should have an upper case name
//
// 6. 在 const 里用 let 的语法：
//        const NUMBER: i32;
//    → error: const items must have an initializer（常量必须当场赋值）
//
// ============================================================================
//                          小 结
// ============================================================================
//
// 本题你需要记住：
//   1. 常量用 `const 名字: 类型 = 值;` 声明，**类型不能省**；
//   2. 常量永远不可变，也不能加 mut；
//   3. 常量的值必须在编译期就能算出来；
//   4. 常量名约定用全大写加下划线（SCREAMING_SNAKE_CASE）；
//   5. 常量可以写在函数外，作用范围更广；它没有地址，使用处会被替换成值。
//
// 一句话记忆：**let 靠推断，const 必须自报类型，而且一辈子不能改。**
//
