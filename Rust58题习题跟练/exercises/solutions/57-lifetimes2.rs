// ============================================================================
// 第 57 题 · lifetimes2 —— 期限取“较小者”：借来的数据别比主人活得久
// ----------------------------------------------------------------------------
// 题目类型：compile（把代码改到能编译通过就算过关）
// 课件位置：第 6 章 · 6.2 生命周期（引用的作用域、'a 取较小者）
// 难度：★★★★☆
// 前置知识：第 56 题 lifetimes1（生命周期标注）、变量作用域（variables1）
// ============================================================================
//
// 【题目要求】
// 函数签名**已经**写好了生命周期标注，不需要改。要改的是 main：
// 让程序编译通过，并且仍然在最后打印最长字符串。
// 提示：可以移动 string2 的声明位置，也可以移动 println! 的位置。
//
// 原题代码（未完成，仅供对照）：
//     fn longest<'a>(x: &'a str, y: &'a str) -> &'a str {
//         if x.len() > y.len() { x } else { y }
//     }
//
//     fn main() {
//         let string1 = String::from("long string is long");
//         let result;
//         {
//             let string2 = String::from("xyz");            // ← 内层作用域
//             result = longest(string1.as_str(), string2.as_str());
//         }                                                 // ← string2 在这里被释放
//         println!("The longest string is '{}'", result);   // ← result 还在用它
//     }
//
// 编译器会报：
//     error[E0597]: `string2` does not live long enough
//     note: `string2` dropped here while still borrowed
//
// 【解题思路】
// 1. 先想清楚 'a 到底被填成了多长：
//        result = longest(string1.as_str(), string2.as_str());
//    两个参数共用同一个 'a，所以 'a = “两者中较短的那个期限”
//        string1 —— 活到 main 结束
//        string2 —— 只活到内层 { } 结束
//        → 'a 只能取到内层 { } 结束
// 2. 但返回值 result 被赋给了**外层**的变量，并且在 { } 外面还用它打印，
//    即 result 的“使用期限”超过了 'a。
//    编译器于是说：你承诺返回值最多活到 'a，却用到了 'a 之后 → 拒绝。
// 3. 解法：让 string2 活到和 string1 一样久（把它的声明挪到外层），
//    这样 'a 至少覆盖到 println! 那一行，一切合法。
// 4. 另一个等价解法：把 println! 挪进内层 { }，
//    让 result 的使用不超出 'a。两种都行，本答案选第一种（更常见）。
//
// ============================================================================
//                              知 识 铺 垫
// ============================================================================
//
// ● 作用域（scope）与“谁先被释放”
//   在 Rust 里，一个变量在它所在的 { } 结束时被 drop（释放内存）。
//        let a = ...;         // 外层
//        {
//            let b = ...;     // 内层
//        }                    // b 在这里被释放
//        // a 还活着
//   所以“内层变量的寿命 < 外层变量”。
//
// ● 'a 到底怎么取？—— 取交集（较短者）
//   函数 `fn longest<'a>(x: &'a str, y: &'a str) -> &'a str`
//   要求：x 至少活到 'a，y 至少活到 'a，返回值最多活到 'a。
//   一个 'a 要同时满足两边，只能选**两个实参期限中较短的那个**。
//   打个比方：你向 A 借书到周五、向 B 借书到周三，
//   你要把两本书一起转借给同学并承诺归还日，只能承诺“周三之前”——
//   取交集，也就是较短的那个。
//
// ● 为什么返回值也要受 'a 限制？
//   因为函数可能返回 x，也可能返回 y。
//   编译器不分析你的 if 逻辑（那是运行期的事），
//   它只看签名：返回值的期限不可能超过 'a。
//   所以调用者必须按“最多活到 'a”来使用返回值。
//
// ● 这个错误为什么在编译期就能发现？
//   这正是 Rust 的卖点：悬垂引用（dangling reference）不需要等到运行崩溃，
//   编译器静态分析就能拦住。C/C++ 里同样的代码能编译通过，
//   运行时可能读到垃圾数据，或者被 free 后访问（use-after-free）。
//
// ● 别混淆两件事
//   ① 变量的**实际存活时间**：由作用域决定，改标注改不了它；
//   ② 引用的**可用期限**：由标注描述，编译器据此检查使用是否越界。
//   本题要做的是改 ①（让 string2 活得久一点），而不是改标注。
//
// ============================================================================
//                              参 考 答 案
// ============================================================================

// 签名与上一题相同：三者共用一个期限 'a
fn longest<'a>(x: &'a str, y: &'a str) -> &'a str {
    if x.len() > y.len() {
        x
    } else {
        y
    }
}

fn main() {
    // string1 活到 main 结束
    let string1 = String::from("long string is long");

    // 关键改动①：把 string2 的声明提到外层
    // 这样它的存活范围和 string1 一样长，'a 至少覆盖到下面的 println!
    let string2 = String::from("xyz");

    // 关键改动②：去掉内层 { }，直接在这里拿到返回值
    // 此时 string1、string2 都还活着，result 的期限 'a 足够长
    let result = longest(string1.as_str(), string2.as_str());

    // 使用 result：它的有效期覆盖到这一行，完全合法
    println!("The longest string is '{}'", result);
}

// ============================================================================
//                            详 细 解 析
// ============================================================================
//
// 1）原代码到底“错”在哪一行？
//    错在逻辑关系，而不是某一行语法：
//        result  （外层变量，活到 main 结束）
//        却指向 string2 的数据（内层变量，{ } 结束就被释放）
//    一旦 { } 结束，string2 的堆内存被释放，
//    result 就成了悬垂引用 —— 再用它打印就是读已释放内存。
//    编译器 E0597 就是在说这件事：`string2` does not live long enough。
//
// 2）'a 是“取较短者”，为什么不是“取较长者”？
//    如果取较长者（string1 的期限），那么函数就承诺“返回值能活到 main 结束”，
//    但它可能返回的其实是 y（string2 的数据），而 string2 早就没了。
//    所以只能取较短者，保证“无论返回 x 还是 y 都安全”。
//
// 3）解法一（本答案）：把 string2 挪到外层
//        let string2 = String::from("xyz");      // 与 string1 同级
//        let result = longest(string1.as_str(), string2.as_str());
//        println!(...);
//    两个实参都活到 main 结束，'a 足够长，问题消失。
//
// 4）解法二：保留内层块，把 println! 也挪进去
//        let result;                       // 只声明，不初始化（延迟初始化）
//        {
//            let string2 = String::from("xyz");
//            result = longest(string1.as_str(), string2.as_str());
//            println!("The longest string is '{}'", result);   // ← 移进来
//        }
//    此时 result 的**最后一次使用**在 { } 内部，没有超出 'a，编译通过。
//    注意：`let result;` 这种“先声明后赋值”的写法是合法的，
//    但赋值前不能使用，且只能赋值一次。
//
// 5）解法三（不推荐）：把返回值改成 String
//        fn longest(x: &str, y: &str) -> String { x.to_string() ... }
//    这样就没有借用问题了（返回值拥有自己的数据），
//    但改变了函数语义和性能（多一次堆分配），题目也不允许改签名。
//
// 6）为什么 result 能在 { } 外面“被声明”？
//    `let result;` 只是声明，类型由后面的赋值推断成 &str。
//    真正的问题是它指向的数据（string2）先死了，
//    而不是 result 这个变量本身活得太久。
//
// 7）运行时会打印什么？
//    "long string is long"（20 个字符）比 "xyz"（3 个字符）长，
//    所以返回 string1 的内容。
//    注意：即使返回的是 string1（它没被释放），编译器也照样报错 ——
//    它检查的是**类型层面的可能性**，而不是这一次运行的实际结果。
//    这正是静态检查的价值：不靠运气。
//
// ============================================================================
//                          常 见 错 误 与 提 示
// ============================================================================
//
// 1. 试图只给 string2 加个标注（比如 &'static）来“延长寿命”：
//        let string2: &'static str = &String::from("xyz");   // 临时值
//    → error[E0716]: temporary value dropped while borrowed
//      （标注不能延长变量的实际寿命）
//
// 2. 把 result 声明成 String：
//        let mut result = String::new();
//        { ... result = longest(...).to_string(); }
//    → 能过，但等于换了语义（复制了一份数据），不是本题要练的借用分析。
//
// 3. 把 println! 挪到 { } 里，但 result 还在外面声明：
//    → 正确（解法二）。注意 result 必须在 { } 外声明，否则出了块就看不见。
//
// 4. 试图把两个参数标成不同生命周期并返回第二个：
//        fn longest<'a, 'b>(x: &'a str, y: &'b str) -> &'b str
//    → 本题签名不允许改；而且返回 x 的分支会类型不匹配。
//
// 5. 以为“只要把 use 写对 / 加 mut 就能好”：
//    → 这是借用期限问题，与 mut、use 无关。看错误码 E0597 就找“谁先被 drop”。
//
// 6. 忘记 as_str()：
//        longest(string1, string2)   // 传的是 String，不是 &str
//    → error[E0308]: mismatched types, expected `&str`, found `String`
//      help: consider borrowing here: `&string1`
//
// 7. 用 clone() 强行续命：
//        let string2 = String::from("xyz").clone();
//    → 没用，clone 出来的仍然是内层变量，照样 E0597。
//
// ============================================================================
//                          小 结
// ============================================================================
//
// 本题你需要记住：
//   1. `'a` 取所有相关借用中**较短**的那个期限（交集的比喻）；
//   2. 返回值最多只能活到 'a，调用者不能把它用到 'a 之后；
//   3. E0597 "does not live long enough" 的意思是“被借的值先死了”；
//   4. 修法只有两类：让数据活得更久（挪声明），或让引用用得更早（挪使用）；
//   5. 生命周期标注不能延长任何东西的寿命，它只是“承诺书”。
//
// 一句话记忆：**借条写的是“最短那份租期”；要么让主人晚点走，要么在主人走之前用完。**
//
