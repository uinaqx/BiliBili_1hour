// ============================================================================
// 第 01 题 · intro1 —— 跑通人生第一个 Rust 程序
// ----------------------------------------------------------------------------
// 题目类型：compile（把代码改到能编译通过就算过关）
// 课件位置：第 1 章 · 1.1~1.3 创建工程、编译运行第一个程序、println! 输出
// 难度：★☆☆☆☆
// 前置知识：无（这是全部练习的第一题，只需要会复制粘贴、会敲命令）
// ============================================================================
//
// 【题目要求】
// 这题比较特别：原题的代码本来就是**能编译通过**的。
// 它唯一“没做完”的地方，是文件开头那行 rustlings 用来标记“本题还没做”的
// 特殊注释（一行全大写的英文）。
//
// 因此本题要做的事只有两件：
//   1. 把那行未完成标记注释删掉（相当于告诉 rustlings：我做完这题了）；
//   2. 编译并运行，看看屏幕上打出什么，顺便观察 println! 的各种写法。
//
// 原题代码（未完成，仅供对照；开头那行标记注释已省略）：
//     fn main() {
//         println!("Hello and");
//         println!(r#"       welcome to...                      "#);
//         println!(r#"                 _   _ _                  "#);
//         println!(r#"  _ __ _   _ ___| |_| (_)_ __   __ _ ___  "#);
//         println!(r#" | '__| | | / __| __| | | '_ \ / _` / __| "#);
//         println!(r#" | |  | |_| \__ \ |_| | | | | | (_| \__ \ "#);
//         println!(r#" |_|   \__,_|___/\__|_|_|_| |_|\__, |___/ "#);
//         println!(r#"                               |___/      "#);
//         println!();
//         println!("This exercise compiles successfully. ...");
//         ...
//     }
//
// 【解题思路】
// 1. 先别急着改代码，先搞清楚“一行注释怎么可能让程序编译失败”——其实不会。
//    rustlings 的判定规则是：运行程序成功 **并且** 文件里没有那行未完成标记，
//    这题才算过。所以这题考的是“流程”，不是语法。
// 2. 用 rustc 把它编译成 exe，再运行，观察输出：先是一句问候，然后是一幅
//    用字符拼出来的 “rustlings” 艺术字。
// 3. 最后删掉那行标记注释，本题完成。
//
// ============================================================================
//                              知 识 铺 垫
// ============================================================================
//
// ● Rust 程序的“最小骨架”
//   一个能运行的 Rust 文件（后缀 .rs）至少要有：
//       fn main() {
//           ...
//       }
//   `fn` 是 function（函数）的缩写，`main` 是函数名，`()` 里放参数（这里没有
//   参数），`{ }` 里是函数体。**程序永远从 main 开始执行**，没有 main 的
//   可执行程序是编译不过的（后面 primitive_types4 那种测试题除外）。
//
// ● 注释（comment）
//   以 `//` 开头的行，从 // 到行尾都会被编译器忽略。注释是写给人看的。
//   本文件里那些 `// ====` 分隔线也是注释——它们对程序毫无影响。
//
// ● 语句和分号
//   Rust 里一条语句结束要写分号 `;`（少数情况除外，见 functions5）。
//   漏写分号，编译器就会抱怨。
//
// ● println! 是什么？为什么带感叹号？
//   println! 是标准库提供的**宏**（macro），作用是“把内容打印到屏幕上，并换行”。
//   宏的名字后面必须带 `!`，这是 Rust 区分“宏”和“普通函数”的写法。
//   写成 println(...)（不带 !）会报错：cannot find function `println`。
//   记忆口诀：**打印宏，带感叹号**。
//
// ● 空参数也能调用：println!();
//   这行会只打印一个换行符，也就是输出一个空行。本题用它来给艺术字和下面的
//   说明文字之间留出空隙。
//
// ● 普通字符串 vs 原始字符串
//   普通字符串："Hello and" —— 里面的 \ 是转义符（\n 换行、\" 引号、\\ 反斜杠）。
//   原始字符串：r#"..."# —— 里面的字符**原样保留**，\ 不再是转义符。
//   本题的艺术字里全是反斜杠（\__、/、| 之类），如果写成普通字符串，每个 \ 都要
//   写成 \\，非常难读；用 r#"..."# 就可以直接把图案贴进去。
//   两端的 `#` 是“围栏”，当字符串里本身就有引号时也不会提前结束。
//
// ● 编译型语言的两步走
//   1) rustc 把 .rs 源码翻译成机器码，生成 .exe（编译期）；
//   2) 双击/命令行运行 .exe（运行期）。
//   编译期发现的问题叫“编译错误”，程序根本跑不起来；运行期发现的问题叫
//   “panic / 运行时错误”。Rust 的口号是“把错误尽量提前到编译期”。
//
// ============================================================================
//                              参 考 答 案
// ============================================================================

// 程序入口：Rust 从 main 函数的第一行开始执行
fn main() {
    // 普通字符串：直接打印一行文字，然后换行
    println!("Hello and");

    // 原始字符串 r#"..."#：里面的反斜杠、竖线、空格都原样输出，
    // 不需要把一个 \ 写成 \\。这一行打印艺术字的第一行。
    println!(r#"       welcome to...                      "#);

    // 下面几行把 “rustlings” 这个单词用字符画出来。
    // 注意：每行前面的空格也是字符串的一部分，少一个空格图案就歪了。
    println!(r#"                 _   _ _                  "#);
    println!(r#"  _ __ _   _ ___| |_| (_)_ __   __ _ ___  "#);
    println!(r#" | '__| | | / __| __| | | '_ \ / _` / __| "#);
    println!(r#" | |  | |_| \__ \ |_| | | | | | (_| \__ \ "#);
    println!(r#" |_|   \__,_|___/\__|_|_|_| |_|\__, |___/ "#);
    println!(r#"                               |___/      "#);

    // 不带参数的 println!：只输出一个空行，起“空一行”的排版作用
    println!();

    // 下面是几句说明文字。字符串太长时，rustlings 把它拆成多行写，
    // 每一行都是一次独立的 println! 调用。
    println!("This exercise compiles successfully. The remaining exercises contain a compiler");
    println!("or logic error. The central concept behind Rustlings is to fix these errors and");
    println!("solve the exercises. Good luck!");
    println!();

    println!("The source for this exercise is in `exercises/intro/intro1.rs`. Have a look!");
    println!(
        "Going forward, the source of the exercises will always be in the success/failure output."
    );
    println!();

    println!(
        "If you want to use rust-analyzer, Rust's LSP implementation, make sure your editor is set"
    );
    println!("up, and then run `rustlings lsp` before continuing.");

    // 说明：函数体最后一条语句的分号其实可以省略（它就变成了“表达式”，
    // 见 functions5 的详细讲解）。这里保留分号，和原题保持一致。
}

// ============================================================================
//                            逐 行 解 析
// ============================================================================
//
// fn main() {
//   ├─ fn    ：声明“这是一个函数”
//   ├─ main  ：函数名，固定写法，程序入口
//   ├─ ()    ：参数列表，空的表示不接收任何参数
//   └─ {     ：函数体开始，一直到对应的 } 结束
//
// println!("Hello and");
//   ├─ println!  ：宏，打印 + 自动换行
//   ├─ ("...")   ：括号里是“格式化字符串”，这里没有占位符
//   └─ ;         ：语句结束
//
// println!(r#"  ...  "#);
//   └─ r#"..."#  ：原始字符串，反斜杠不转义，所以图案可以直接贴
//
// println!();
//   └─ 没有参数，只输出一个换行 → 视觉上是一个空行
//
// ============================================================================
//                          常 见 错 误 与 提 示
// ============================================================================
//
// 1. 把宏写成函数：
//        println("Hello");
//    → error: cannot find function `println` in this scope（宏必须带 !）
//
// 2. 把原始字符串的围栏写漏：
//        println!(r#" ... );        // 少了结尾的 "#
//    → error: unterminated raw string（原始字符串没有结束）
//
// 3. 用普通字符串贴艺术字：
//        println!("  _ __ _   _ ___| |_| ...");
//    → 反斜杠会被当成转义符，报 error: unknown character escape 或图案变形
//
// 4. 忘了删掉那行未完成标记注释：
//    → 代码能编译、能运行，但 rustlings 仍然显示这题没做完
//
// 5. 在错误的目录下编译：
//    → error: couldn't read xxx.rs（找不到源文件，注意路径）
//
// ============================================================================
//                          小 结
// ============================================================================
//
// 本题你需要记住：
//   1. Rust 程序从 fn main() 开始执行；
//   2. 打印用 println!（宏，带感叹号），自动换行；
//   3. 一行 // 注释对程序没有任何影响；
//   4. 反斜杠多的文本用原始字符串 r#"..."# 最省事；
//   5. 编译（rustc）和运行（.exe）是两个步骤。
//
// 一句话记忆：**main 是入口，println! 是喇叭，注释是给自己看的便签。**
