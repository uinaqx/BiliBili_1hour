// ============================================================================
// 第 23 题 · primitive_types6 —— 用点号下标访问元组元素
// ----------------------------------------------------------------------------
// 题目类型：test（让 #[test] 测试通过就算过关）
// 课件位置：第 3 章 · 3.2 元组（元组下标访问 tuple.0 / tuple.1）
// 难度：★★☆☆☆
// 前置知识：元组与解构（第 22 题 primitive_types5）、#[test] 测试（if1~if3）
// ============================================================================
//
// 【题目要求】
// 把原题留出的占位处换成“元组下标语法”，取出 numbers 的第二个元素。
// 原题代码（未完成，仅供对照）：
//     #[test]
//     fn indexing_tuple() {
//         let numbers = (1, 2, 3);
//         // Replace below placeholder with the tuple indexing syntax.
//         let second = /* 原题此处是待填写的占位符 */;
//
//         assert_eq!(2, second,
//             "This is not the 2nd number in the tuple!")
//     }
//
// 【解题思路】
// 1. numbers = (1, 2, 3)，是三个整数的元组。
// 2. “第二个元素”在编程里通常指“下标 1”（下标从 0 开始数）：
//      numbers.0 = 1（第一个）
//      numbers.1 = 2（第二个）  ← 要的就是它
//      numbers.2 = 3（第三个）
// 3. 元组下标的写法是 **点号 + 数字**：numbers.1，不是 numbers[1]。
// 4. 所以 `let second = numbers.1;`，此时 second = 2，
//    assert_eq!(2, second) 成立，测试通过。
//
// ============================================================================
//                              知 识 铺 垫
// ============================================================================
//
// ● 元组下标：点号 + 数字
//     numbers.0   // 第 1 个元素
//     numbers.1   // 第 2 个元素
//     numbers.2   // 第 3 个元素
//   为什么不是 numbers[0]？因为 [ ] 是数组 / 切片的索引语法，
//   而元组的元素类型可以不同，不能像数组那样用“运行期算出来的下标”去取，
//   所以 Rust 用点号下标：它在编译期就确定是第几个字段。
//   后果：numbers.i（i 是变量）不合法！只能写字面数字。
//
// ● 下标从 0 开始
//   这是几乎所有主流语言的约定（C、Java、Python、Rust 都一样）：
//     第 1 个元素的下标是 0，第 n 个元素的下标是 n-1。
//   “第二个元素” → 下标 1。本题的 assert_eq!(2, second) 也在提示这一点。
//
// ● 取出来的是“值”，不是引用
//   i32 是 Copy 类型，numbers.1 会复制出 2 赋给 second，
//   numbers 本身没有受到影响，之后仍然可以继续用。
//
// ● assert_eq! 的第三个参数是什么？
//     assert_eq!(期望, 实际, "自定义失败信息")
//   前两个参数比较，不相等时 panic，并把这句话打印出来帮助排错。
//   本题的 "This is not the 2nd number in the tuple!" 就是提示语。
//   注意：第三个参数必须出现在前两个之后，且只能是格式化字符串（可以带 {} 参数）。
//
// ● 用解构能不能做？能，但题目要求用下标：
//     let (_, second, _) = numbers;   // 用 _ 忽略不想要的元素
//   这种写法在上一题已经练过；本题特意让你熟悉 .0 / .1 这套下标语法。
//
// ● 测试文件的编译方式
//   本题只有 #[test] 函数、没有 main，所以必须用 `rustc --test` 编译，
//   否则会报 error[E0601]: `main` function not found in crate。
//
// ============================================================================
//                              参 考 答 案
// ============================================================================

#[test]
fn indexing_tuple() {
    // 一个三元组，类型是 (i32, i32, i32)
    let numbers = (1, 2, 3);

    // 元组下标：点号 + 常量数字（不是 numbers[1]）
    //   .0 → 1
    //   .1 → 2  ← “第二个元素”，本题要的就是它
    //   .2 → 3
    // i32 是 Copy，这里复制出 2 赋给 second，numbers 之后仍然可用
    let second = numbers.1;

    // assert_eq!(期望值, 实际值, 失败时打印的提示)
    // 相等则测试通过；不等则 panic，并打印那句 "This is not the 2nd number..."
    assert_eq!(2, second,
        "This is not the 2nd number in the tuple!")
    // 注意：这一行末尾没有分号，assert_eq! 的值是 ()，
    // 正好与测试函数的返回类型 () 匹配。
}

// ============================================================================
//                            逐 行 解 析
// ============================================================================
//
// let numbers = (1, 2, 3);
//   └─ 类型 (i32, i32, i32)；三个元素占用一块连续（或按对齐排布）的空间
//
// let second = numbers.1;
//   ├─ numbers   ：元组变量
//   ├─ .         ：访问字段/元组元素
//   └─ 1         ：字段编号（必须是字面数字，编译期确定）
//   结果：second = 2，类型 i32
//
// assert_eq!(2, second, "This is not the 2nd number in the tuple!")
//   ├─ 左边 2          ：期望值
//   ├─ 右边 second     ：实际值（2）
//   └─ 第三参数        ：自定义失败信息
//   相等 → 测试 ok；不等 → 测试 FAILED 并打印该信息。
//
// ============================================================================
//                          常 见 错 误 与 提 示
// ============================================================================
//
// 1. 用方括号索引：
//        let second = numbers[1];
//    → error[E0608]: cannot index into a value of type `(i32, i32, i32)`
//    （元组不支持 [ ]，只有数组/切片/Vec 才支持）
//
// 2. 用变量当下标：
//        let i = 1;  let second = numbers.i;
//    → error: `i` is a variable, not a tuple field
//    （元组下标必须是编译期已知的字段编号）
//
// 3. 下标算错（把“第二个”当成 .2）：
//        let second = numbers.2;   // 得到 3
//    → 测试失败：assertion `left == right` failed: left: 2, right: 3
//      This is not the 2nd number in the tuple!
//
// 4. 下标超出范围：
//        let second = numbers.3;
//    → error[E0609]: no field `3` on type `(i32, i32, i32)`
//
// 5. 写成 numbers . 1 中间加空格虽然能过（空白不影响），
//    但写成 numbers.1.0 这种链式访问只对“元组套元组”才成立。
//
// 6. 忘记 --test：
//        rustc primitive_types6.rs
//    → error[E0601]: `main` function not found in crate
//
// 7. 在 assert_eq! 里把自定义信息放错位置：
//        assert_eq!("This is not...", 2, second)
//    → error[E0308]（第一个参数变成 &str 了，类型对不上）
//
// ============================================================================
//                          小 结
// ============================================================================
//
// 本题你需要记住：
//   1. 元组取值有两种方式：解构 let (a, b) = t; 和下标 t.0 / t.1；
//   2. 元组下标是“点号 + 编译期常量数字”，不是方括号；
//   3. 下标从 0 开始，“第二个元素”是 .1；
//   4. assert_eq! 的第三个参数是失败提示，方便排错。
//
// 一句话记忆：**数组用 [i]，元组用 .i，而且元组的 i 只能是写死的数字。**
