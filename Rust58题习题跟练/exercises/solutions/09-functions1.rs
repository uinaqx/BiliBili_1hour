// ============================================================================
// 第 09 题 · functions1 —— 自己定义一个函数，然后调用它
// ----------------------------------------------------------------------------
// 题目类型：compile（把代码改到能编译通过就算过关）
// 课件位置：第 2 章 · 2.2.3 函数（定义函数、main 中调用）
// 难度：★☆☆☆☆
// 前置知识：intro1（fn main 就是函数）、variables1（let）
// ============================================================================
//
// 【题目要求】
// main 里调用了 call_me()，但 call_me 这个函数根本没有被定义。
// 请把它补上，让程序能编译、能运行。
//
// 原题代码（未完成，仅供对照）：
//     fn main() {
//         call_me();
//     }
//
// 编译会报错：
//     error[E0425]: cannot find function `call_me` in this scope
//     （在这个作用域里找不到叫 call_me 的函数）
//
// 【解题思路】
// 1. 第 3 行写了 `call_me();`，这叫“函数调用”：让名为 call_me 的函数去干活。
// 2. 但整个文件里只有 main 一个函数，编译器找不到 call_me 的定义 → E0425。
// 3. 用 `fn` 关键字补一个定义：
//        fn call_me() {
//            println!("Hello from call_me!");
//        }
// 4. `()` 表示它不接收参数，`{ }` 里面是它要做的事。
//    本题不要求返回值，所以也不用写 `-> 类型`。
// 5. 定义放在 main 前面还是后面都可以 —— Rust 不要求“先定义后使用”。
//
// ============================================================================
//                              知 识 铺 垫
// ============================================================================
//
// ● 函数定义的完整骨架
//       fn 函数名(参数列表) -> 返回类型 {
//           函数体
//       }
//   本题只用到最简单的形式：
//       fn call_me() { ... }
//   ├─ fn      ：function 的缩写，声明“我要定义一个函数”
//   ├─ call_me ：函数名（自己起，建议见名知意）
//   ├─ ()      ：参数列表，空的表示不接收任何参数
//   └─ { ... } ：函数体，函数被调用时执行的代码
//   如果函数没有返回值，`-> 返回类型` 这一整段可以直接省略（等价于返回 `()`）。
//
// ● 函数名为什么用下划线小写？
//   Rust 官方风格叫 snake_case（蛇形命名）：全小写，单词间用下划线。
//   例如 call_me、sale_price、is_even。
//   写成 callMe 或 CallMe 能编译，但会得到
//   warning: function `callMe` should have a snake case name。
//   （类型、结构体才用大驼峰 CamelCase，后面课程会见到。）
//
// ● 调用（call）是什么？
//       call_me();
//   ├─ call_me ：函数名，不带 fn
//   ├─ ()      ：调用运算符，括号里放实参（本题没有）
//   └─ ;       ：作为一条语句，末尾要分号
//   调用时程序会“跳进”函数体执行，执行完再跳回来继续往下走。
//   就像 main 喊了一声“call_me 你来一下”，call_me 干完活回来，main 继续。
//
// ● 定义顺序不重要
//   很多语言（如 C）要求函数先声明后使用；Rust 不需要。
//   下面两种写法完全等价：
//       fn call_me() { ... }        fn main() { call_me(); }
//       fn main() { call_me(); }    fn call_me() { ... }
//   因为编译器会先扫描整个文件，把所有函数登记下来，再检查调用。
//   （Rust 其实也允许在函数体里再定义函数，只是那种写法用得少；
//     本题按最常见的习惯，把 call_me 放在最外层、和 main 平级。）
//
// ● 一个文件里可以有多个函数
//   但**有且只有一个 main**。main 是程序入口，其它函数都必须被（直接或间接）
//   调用到才会执行；没被调用的函数会得到 dead_code 警告，不会自动运行。
//
// ● 空函数体也是合法的
//       fn call_me() {}
//   它能编译，只是被调用时什么都不做。本题为了让你看到“确实调用了”，
//   我们在里面写了一句 println!。
//
// ============================================================================
//                              参 考 答 案
// ============================================================================

fn main() {
    // 调用 call_me：程序会跳到下面的 call_me 函数体里执行，
    // 执行完再回到这一行，继续往下（这里下面已经没有代码了，main 结束）
    call_me();
}

// 补上的函数定义：
//   fn      —— 声明这是一个函数
//   call_me —— 函数名，必须和上面调用时写的一模一样（大小写也要一致）
//   ()      —— 不接收参数
//   没有 `-> 类型` —— 表示不返回值（返回类型是 ()，单元类型）
fn call_me() {
    // 函数体：这个函数被调用时，打印这句话
    println!("Hello from call_me!");
}

// ============================================================================
//                            逐 行 解 析
// ============================================================================
//
// fn main() {
//   └─ 程序入口，运行时从这里开始
//
// call_me();
//   ├─ 函数调用：找到名为 call_me 的函数并执行它
//   └─ 分号：这是一条语句
//
// fn call_me() {
//   ├─ fn      ：定义函数
//   ├─ call_me ：名字（与调用处完全一致才能被找到）
//   ├─ ()      ：参数列表为空
//   └─ { ... } ：函数体
//
// println!("Hello from call_me!");
//   └─ 函数真正干的活：打印一行字
//
// 执行顺序：
//   main 开始 → 调用 call_me → 打印 Hello from call_me!
//            → 回到 main → main 结束 → 程序退出
//
// ============================================================================
//                          常 见 错 误 与 提 示
// ============================================================================
//
// 1. 忘了定义（= 原题状态）：
//    → error[E0425]: cannot find function `call_me` in this scope
//
// 2. 名字拼错或大小写不一致：
//        fn call_me() { }     被调用成   Call_me();
//    → error[E0425]: cannot find function `Call_me` in this scope
//    （Rust 是大小写敏感的）
//
// 3. 定义时多写了参数，调用时没给：
//        fn call_me(n: i32) { }
//        call_me();
//    → error[E0061]: this function takes 1 argument but 0 arguments were supplied
//
// 4. 调用时忘了括号：
//        call_me;
//    → 编译能过（它是一个“函数项”表达式），但**函数体不会执行**，
//      而且会得到 warning: unused function item。调用一定要带 ()。
//
// 5. 把函数定义写进了 main 里面：
//        fn main() {
//            fn call_me() { }
//            call_me();
//        }
//    → 嵌套函数在 Rust 里其实合法，但本题按常规写在最外层，
//      这样其它函数也能调用它，可读性更好。
//
// ============================================================================
//                          小 结
// ============================================================================
//
// 本题你需要记住：
//   1. 函数定义：`fn 名字(参数) -> 返回类型 { 函数体 }`；
//   2. 没有返回值时，`-> 返回类型` 可以省略；
//   3. 调用函数要写 `名字(实参);`，括号不能少；
//   4. 函数名用 snake_case（小写 + 下划线）；
//   5. 定义和调用的顺序无所谓，但**名字必须完全一致**。
//
// 一句话记忆：**fn 负责“造”函数，名字加括号负责“叫”函数。**
//
