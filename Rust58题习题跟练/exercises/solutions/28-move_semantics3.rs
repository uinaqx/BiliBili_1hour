// ============================================================================
// 第 28 题 · move_semantics3 —— mut 写在参数上，一行都不用加
// ----------------------------------------------------------------------------
// 题目类型：test（让 #[test] 测试通过就算过关）
// 课件位置：第 2 章 · 2.3.2 函数参数绑定加 mut 才能可变借用
// 难度：★★☆☆☆
// 前置知识：move_semantics1、move_semantics2（移动、mut、clone）
// 题目约束：**不许新增代码行，只能在原有行上改动**（也不能一行塞多条语句）
// ============================================================================
//
// 【题目要求】
// 不改结构、不加新行，让代码编译通过、测试通过。
//
// 原题代码（未完成，仅供对照）：
//     #[test]
//     fn main() {
//         let vec0 = vec![22, 44, 66];
//         let mut vec1 = fill_vec(vec0);
//         assert_eq!(vec1, vec![22, 44, 66, 88]);
//     }
//
//     fn fill_vec(vec: Vec<i32>) -> Vec<i32> {
//         vec.push(88);          // ← 报错
//         vec
//     }
//
// 编译报错：
//     error[E0596]: cannot borrow `vec` as mutable, as it is not declared as mutable
//
// 【解题思路】
// 1. 报错的是 `vec.push(88);`：push 需要"可变借用" &mut vec，
//    而参数 `vec: Vec<i32>` 默认是不可变绑定，给不出 &mut。
// 2. 上一题的解法是在函数体里写 `let mut vec = vec;`，
//    但本题不许加新行，所以要把 mut 直接写在参数上：
//        fn fill_vec(mut vec: Vec<i32>) -> Vec<i32> {
// 3. 只改这一行就够了。`fn` 的参数其实就是一个"隐式的 let 绑定"，
//    所以 `mut vec: Vec<i32>` 和"进函数后马上 let mut vec = vec"完全等价。
// 4. main 里的代码一个字都不用动（`let mut vec1` 里的 mut 是原题自带的，
//    本题用不到，只会产生一条"变量不需要 mut"的 warning，不影响通过）。
//
// ============================================================================
//                              知 识 铺 垫
// ============================================================================
//
// ● 函数参数也是一个变量绑定
//   fn fill_vec(vec: Vec<i32>) 等价于在函数体开头写 `let vec = 实参;`。
//   既然是变量绑定，它就能加 mut：
//       fn fill_vec(mut vec: Vec<i32>)
//   读法："这个参数绑定是可变的"。
//
// ● 注意 mut 的位置（这是本题唯一的坑）
//       fn f(mut x: Vec<i32>)   // ✅ 正确：mut 修饰"变量 x"
//       fn f(x: mut Vec<i32>)   // ❌ 错误：mut 不能修饰类型
//       fn f(x: Vec<i32>) -> mut Vec<i32>   // ❌ 错误：返回值类型上不能写 mut
//   记忆：mut 永远紧贴在**变量名**前面（或者 & 后面表示 &mut）。
//
// ● mut 管的是"这个名字能不能改"，不是"值能不能被别人改"
//   举两个对照：
//       fn a(vec: Vec<i32>)            // 既不能 push，也不能 &mut 借出去
//       fn b(mut vec: Vec<i32>)        // 可以 push，也可以 &mut 借出去
//   参数进来时所有权已经归函数了，要不要"可写"完全由这个 mut 决定。
//
// ● 为什么 Rust 要这么啰嗦？
//   因为函数签名就是"合同"。调用者看 `mut vec: Vec<i32>` 立刻知道
//   "这个函数会在内部改动它拿到的这份数据"（虽然改动对外不可见，因为所有权已经转移）。
//   到了借用场景（&mut），这个信息就更重要了——它决定了调用方能不能同时用这块数据。
//
// ● 借用检查器（borrow checker）在干什么？
//   它专门检查"谁在什么时候借了谁、借了多久、有没有冲突"。
//   它不看你的注释，也不猜你的意图，只看代码里的所有权与借用关系。
//   本系列每一题的错误，几乎都是它报出来的。
//
// ● 顺便复习：push 为什么需要 &mut self？
//   push 会往堆里写数据、可能扩容、还要改 len，
//   所以它的签名是 `pub fn push(&mut self, value: T)`。
//   要调用它，你必须能提供 `&mut vec`，这就要求 vec 是 mut 绑定。
//
// ============================================================================
//                              参 考 答 案
// ============================================================================

#[test]
fn main() {
    // 创建 Vec，所有者 vec0
    let vec0 = vec![22, 44, 66];

    // 所有权移动进 fill_vec，函数返回的新 Vec 交给 vec1
    // 这里的 mut 是原题自带的，本题用不到，会有 unused_mut 警告，无害
    let mut vec1 = fill_vec(vec0);

    // 断言：22,44,66 加上 push 进去的 88
    assert_eq!(vec1, vec![22, 44, 66, 88]);
}

// 唯一的修改：在参数名 vec 前面加上 mut
// 这样 vec 在函数体内就是"可变绑定"，可以向它 push
fn fill_vec(mut vec: Vec<i32>) -> Vec<i32> {
    // push 需要 &mut vec；因为参数带 mut，这里合法
    // 数据是移动进来的，所以这次 push 改的就是原来 vec0 的那块堆内存
    vec.push(88);

    // 把改好的 Vec 交回去（所有权移出函数）
    vec
}

// ============================================================================
//                            逐 行 解 析
// ============================================================================
//
// let vec0 = vec![22, 44, 66];
//   └─ 堆上分配 3 个 i32
//
// let mut vec1 = fill_vec(vec0);
//   └─ 实参 vec0 移动进形参 vec（不复制）
//      函数内 push(88) 时，改的就是这块堆内存
//      返回时所有权移出，交给 vec1
//
// fn fill_vec(mut vec: Vec<i32>) -> Vec<i32>
//   ├─ mut       ：允许在函数体内修改这个绑定
//   ├─ vec       ：参数名（同时也是变量名）
//   └─ -> Vec<i32>：返回类型，说明要把 Vec 交回去
//
// vec.push(88);
//   └─ 需要 &mut vec，push 成功，len 从 3 变成 4
//
// vec
//   └─ 尾表达式，作为返回值，不加分号
//
// ============================================================================
//                  两种写法对比：参数 mut vs 函数体里再绑定
// ============================================================================
//
// 写法 A（上一题用过）：
//     fn fill_vec(vec: Vec<i32>) -> Vec<i32> {
//         let mut vec = vec;      // 多一行
//         vec.push(88);
//         vec
//     }
//
// 写法 B（本题答案）：
//     fn fill_vec(mut vec: Vec<i32>) -> Vec<i32> {
//         vec.push(88);
//         vec
//     }
//
// 两者语义完全相同，B 更简洁。A 的价值在于"想在中间换一种绑定方式"时更灵活，
// 比如先 let vec = vec; 做点别的事，再 let mut vec = vec;。
// 实际写代码推荐 B。
//
// ============================================================================
//                          常 见 错 误 与 提 示
// ============================================================================
//
// 1. 把 mut 写到类型上：
//        fn fill_vec(vec: mut Vec<i32>)
//    → error: expected type, found keyword `mut`
//
// 2. 改成 `fn fill_vec(vec: &mut Vec<i32>)`：
//    → 调用处 fill_vec(vec0) 类型不匹配（expected `&mut Vec<i32>`, found `Vec<i32>`），
//      而且这就改变了题目要考的"所有权移动"语义。
//
// 3. 在 main 里加 mut 试图解决问题：
//        let mut vec0 = vec![22, 44, 66];
//    → 报错点在函数内部，改调用方没用，仍然 E0596。
//
// 4. 用 clone 绕过（能过但不符合题意）：
//        let mut vec1 = fill_vec(vec0.clone());
//    本题没有要求保留 vec0，没必要复制；而且题目要求"只改原有行"。
//
// 5. 为了"省事"把 push 删掉：
//    → 断言变成 [22,44,66] != [22,44,66,88]，测试 FAILED。
//
// 6. 忘记 --test：
//        rustc move_semantics3.rs
//    → error[E0601]: `main` function not found
//
// ============================================================================
//                          小 结
// ============================================================================
//
// 本题你需要记住：
//   1. 函数参数也是变量绑定，可以写成 `mut 参数名: 类型`；
//   2. mut 只能修饰变量名，不能修饰类型；
//   3. push 需要 &mut self，所以调用方的绑定必须是 mut；
//   4. "所有权移动 + mut 参数"是 Rust 里最朴素的"改完再还给你"模式。
//
// 一句话记忆：**参数默认只读；要改，就在参数名前面写 mut。**
//
// 下一题（move_semantics4）要换个思路：干脆不让外面传，函数自己造一个再交回去。
