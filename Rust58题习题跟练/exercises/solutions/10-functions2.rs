// ============================================================================
// 第 10 题 · functions2 —— 参数必须写类型（而且冒号后面不能空着）
// ----------------------------------------------------------------------------
// 题目类型：compile（把代码改到能编译通过就算过关）
// 课件位置：第 2 章 · 2.2.3 函数（函数参数必须标注类型）
// 难度：★☆☆☆☆
// 前置知识：functions1（fn、调用）、variables3（类型标注）、variables2（u32/i32）
// ============================================================================
//
// 【题目要求】
// call_me(3) 想让函数响 3 次铃。但函数签名里参数的类型写漏了。
//
// 原题代码（未完成，仅供对照）：
//     fn main() {
//         call_me(3);
//     }
//
//     fn call_me(num:) {
//         for i in 0..num {
//             println!("Ring! Call number {}", i + 1);
//         }
//     }
//
// 编译会报错：
//     error: expected type, found `)`
//      --> functions2.rs:12:16
//       |
//    12 | fn call_me(num:) {
//       |                 ^ expected type
//     （这里本该是一个类型，却遇到了右括号）
//
// 【解题思路】
// 1. 看 `fn call_me(num:)`：参数名 `num` 写了，冒号 `:` 也写了，
//    但冒号后面本该跟类型，却直接来了个 `)`。
// 2. Rust 规定：**函数的每个参数都必须写明类型**，不能靠推断。
//    补上 `u32`（无符号 32 位整数）即可：
//        fn call_me(num: u32) {
// 3. 为什么选 u32？因为“次数”不可能是负数，用无符号更贴合语义；
//    而且 main 传进来的 3 是字面量，会自动推断成 u32。
//    写 i32 也能编译，只是语义上不如 u32 精确。
// 4. 补完之后，`for i in 0..num` 会循环 3 次，依次打印 1、2、3。
//
// ============================================================================
//                              知 识 铺 垫
// ============================================================================
//
// ● 带参数的函数长什么样
//       fn 函数名(参数名: 类型, 参数名: 类型) -> 返回类型 { ... }
//   例：
//       fn call_me(num: u32) { ... }        // 1 个参数
//       fn add(a: i32, b: i32) -> i32 { a + b }   // 2 个参数、有返回值
//   参数之间用逗号分隔；**每个参数都要单独写类型**，不能写 `a, b: i32`。
//
// ● 为什么参数类型不能省？
//   在函数体内部，编译器能看见值，可以推断；
//   但函数的“签名”（参数与返回类型）是它对外承诺的接口，
//   调用者可能来自别的文件，编译器必须先知道类型才能检查调用是否正确。
//   所以 Rust 规定：**函数签名里的类型必须写清楚**。
//   （这一点和变量相反：`let x = 3;` 可以推断。）
//
// ● u32 是什么？
//   u = unsigned（无符号），32 = 占 32 位，范围 0 ~ 4_294_967_295。
//   没有负数。表示“次数、长度、年龄”这类天然非负的量很合适。
//   Rust 里 i32 与 u32 是**不同类型**，不能直接混着运算，需要显式转换
//   （例如 `x as u32`，后续课程会讲）。
//
// ● 实参（argument）与形参（parameter）
//       fn call_me(num: u32) { ... }   // num 是形参：定义时的占位名字
//       call_me(3);                     // 3 是实参：调用时真正传进去的值
//   调用时把 3 “复制”给 num，于是函数体里的 num 就是 3。
//   因为 u32 是简单类型（实现了 Copy），传参不会把外面的东西“搬走”。
//
// ● `for i in 0..num` 快速认识
//       for 变量 in 区间 { 循环体 }
//   `0..num` 是“左闭右开”区间，表示 0、1、2 …… 直到 num 的前一个。
//   本题 num = 3，所以 i 依次取 0、1、2，循环 3 次。
//   打印时用 `i + 1`，于是输出 1、2、3（从 1 开始数，更符合日常说法）。
//   所以：“循环 3 次”和“i 从 0 数到 2”是一回事。
//   （for 循环属于第 4 章内容，这里先会读会用即可。）
//
// ● 数字字面量会“入乡随俗”
//   main 里写的是 `call_me(3)`，3 没有后缀。编译器看到形参是 u32，
//   就把这个 3 也当成 u32。所以不需要写 `call_me(3u32)`。
//
// ============================================================================
//                              参 考 答 案
// ============================================================================

fn main() {
    // 调用 call_me，实参是 3
    // 3 是整数字面量，会按形参的类型被推断成 u32
    call_me(3);
}

// 补全后的函数签名：
//   fn call_me(num: u32)
//              │    └─ 类型：无符号 32 位整数（不能为负，适合表示“次数”）
//              └────── 形参名：在函数体里用这个名字代表传进来的值
fn call_me(num: u32) {
    // for 循环：i 依次取 0、1、2（0..num 是左闭右开，不含 num）
    // i 的类型由 num 推断，也是 u32
    for i in 0..num {
        // i + 1 让编号从 1 开始，打印 "Ring! Call number 1/2/3"
        println!("Ring! Call number {}", i + 1);
    }
}

// ============================================================================
//                            逐 行 解 析
// ============================================================================
//
// fn call_me(num: u32) {
//   ├─ fn      ：定义函数
//   ├─ call_me ：函数名
//   ├─ (       ：参数列表开始
//   ├─ num     ：形参名
//   ├─ : u32   ：形参类型（**必须写**，原题就是漏了这里）
//   ├─ )       ：参数列表结束
//   └─ { }     ：函数体
//
// for i in 0..num {
//   ├─ for     ：循环关键字
//   ├─ i       ：循环变量（每轮自动换一个值）
//   ├─ in      ：固定搭配 for ... in ...
//   ├─ 0..num  ：区间 [0, num)，含 0 不含 num
//   └─ 循环体  ：每一轮执行的代码
//
// println!("Ring! Call number {}", i + 1);
//   ├─ i + 1   ：0+1=1、1+1=2、2+1=3
//   └─ 输出三行：Ring! Call number 1 / 2 / 3
//
// ============================================================================
//                          常 见 错 误 与 提 示
// ============================================================================
//
// 1. 冒号后面空着（= 原题状态）：
//        fn call_me(num:) {
//    → error: expected type, found `)`
//
// 2. 忘了写冒号：
//        fn call_me(num u32) {
//    → error: expected `:`, found `u32`
//
// 3. 参数类型和实参对不上：
//        fn call_me(num: u32) { }
//        call_me(-1);
//    → error: cannot apply unary operator `-` to type `u32`
//      （u32 不能是负数）
//
// 4. 两个参数只写一个类型：
//        fn add(a, b: i32) { }
//    → error: expected `:`, found `,`
//      （每个参数都要单独标注）
//
// 5. 调用时参数个数不对：
//        call_me();
//    → error[E0061]: this function takes 1 argument but 0 arguments were supplied
//
// 6. 类型写成 i32 也能编译，但语义上“次数”不该为负，u32 更贴切。
//    另外别把 u32 和 i32 混着算：
//        let n: i32 = 3;  call_me(n);
//    → error[E0308]: mismatched types（i32 不能当 u32 用）
//
// ============================================================================
//                          小 结
// ============================================================================
//
// 本题你需要记住：
//   1. 函数参数写法：`名字: 类型`，冒号和类型都不能少；
//   2. 每个参数都要单独写类型，函数签名不做类型推断；
//   3. u32 是无符号 32 位整数，适合表示次数、长度等非负量；
//   4. 实参的类型必须和形参一致（字面量会自动跟着推断）；
//   5. `for i in 0..n` 循环 n 次，i 从 0 到 n-1（左闭右开）。
//
// 一句话记忆：**变量可以猜类型，函数参数必须自报家门。**
//
