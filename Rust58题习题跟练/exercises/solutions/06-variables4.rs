// ============================================================================
// 第 06 题 · variables4 —— 想改变量，先加 mut
// ----------------------------------------------------------------------------
// 题目类型：compile（把代码改到能编译通过就算过关）
// 课件位置：第 2 章 · 2.1.1 变量绑定（默认不可变、mut 可变绑定）
// 难度：★☆☆☆☆
// 前置知识：variables1~3（let、初始化、类型标注）
// ============================================================================
//
// 【题目要求】
// 程序先把 x 打印成 3，再把 x 改成 5 并打印。要求**不能改注释了
// “don't change this line”的那一行**，只能改别的地方让它编译通过。
//
// 原题代码（未完成，仅供对照）：
//     fn main() {
//         let x = 3;
//         println!("Number {}", x);
//         x = 5; // don't change this line
//         println!("Number {}", x);
//     }
//
// 编译会报错：
//     error[E0384]: cannot assign twice to immutable variable `x`
//     （不能给不可变变量 x 赋值两次）
//
// 【解题思路】
// 1. Rust 的变量**默认不可变**（immutable）。`let x = 3;` 之后，x 就锁死了，
//    再写 `x = 5;` 就相当于“给一个只读变量赋值”，编译器直接拒绝（E0384）。
// 2. 既然题目规定 `x = 5;` 那一行不能动，那就只能在声明处动手：
//    加一个 `mut` 关键字，把 x 声明成“可变变量”。
//        let mut x = 3;
// 3. `mut` 是 mutable（可变的）的缩写。加了它，x 就可以被重新赋值。
// 4. 运行结果：先打印 Number 3，再打印 Number 5。
//
// ============================================================================
//                              知 识 铺 垫
// ============================================================================
//
// ● 默认不可变：Rust 最有个性的设计之一
//   在 C / Java / Python 里，变量生来就是可改的；
//   在 Rust 里，`let x = 3;` 相当于给 3 贴了个封条，x 只能读、不能改。
//   想改，必须显式写 `let mut x = 3;`。
//   这不是为了折磨你，而是为了：
//     1) 让读代码的人一眼看出“哪些值会变”，减少心智负担；
//     2) 让编译器帮你抓住“本来不该被改、却被改了”的 bug；
//     3) 为后面的“多线程安全”打基础：不可变数据可以随便共享。
//
// ● 错误码 E0384 怎么读？
//       error[E0384]: cannot assign twice to immutable variable `x`
//   翻译：不能对不可变变量 x 做第二次赋值。
//   注意“twice（两次）”的措辞：第一次 `let x = 3;` 是初始化，不算赋值；
//   后面的 `x = 5;` 才是“赋值”，而它不被允许。
//
// ● mut 的写法与位置
//       let mut x = 3;
//           ^^^
//   mut 写在变量名**前面**，不能写成 `let x mut = 3;`。
//   也可以同时写类型：`let mut x: i32 = 3;`
//
// ● mut 只影响“能不能改”，不影响类型
//   `let x = 3;` 和 `let mut x = 3;` 的 x 都是 i32。
//   区别只有一条：后者允许 `x = 别的 i32`。
//   而且**不能借 mut 改变类型**：
//       let mut x = 3;
//       x = "hello";   // 错！x 是 i32，不能塞字符串
//   想在同一个名字上换类型，用的是“变量遮蔽”（variables5 的内容）。
//
// ● mut 和“借用”的关系（提前知道就好）
//   后面 move_semantics 会讲到 `&mut x`（可变引用）。
//   想对 x 取可变引用，x 本身必须是 `let mut` 声明的。
//   所以 `mut` 这个词在 Rust 里到处都是，含义始终是“允许修改”。
//
// ● 赋值语句 `x = 5;` 本身也是一个“表达式”
//   它的类型是 `()`（单元类型，读作 unit，相当于“什么都没有”）。
//   所以不能写 `let y = x = 5;` 这种 C 语言风格的链式赋值。
//
// ============================================================================
//                              参 考 答 案
// ============================================================================

fn main() {
    // 关键改动：在 x 前面加上 mut，声明“这个变量以后允许被修改”
    //   let mut x = 3;
    //       ^^^  mutable（可变的）缩写
    let mut x = 3;

    // 第一次打印：此时 x 还是 3
    println!("Number {}", x);

    // 重新赋值：因为 x 是 mut 的，所以这一行合法
    // （题目要求这一行不能改，我们确实一个字都没动）
    x = 5; // don't change this line

    // 第二次打印：x 已经变成 5
    println!("Number {}", x);
}

// ============================================================================
//                            逐 行 解 析
// ============================================================================
//
// let mut x = 3;
//   ├─ let  ：声明变量
//   ├─ mut  ：允许之后重新赋值（没有它就会报 E0384）
//   ├─ x    ：变量名
//   ├─ = 3  ：初始化，类型推断为 i32
//   └─ ;    ：语句结束
//
// println!("Number {}", x);
//   └─ 打印 Number 3
//
// x = 5;
//   ├─ 这是一条“赋值语句”，不是新的声明（没有 let）
//   ├─ 只有 mut 变量才能这样写
//   └─ 执行后 x 的值从 3 变成 5
//
// println!("Number {}", x);
//   └─ 打印 Number 5
//
// ============================================================================
//                          常 见 错 误 与 提 示
// ============================================================================
//
// 1. 不加 mut（= 原题状态）：
//    → error[E0384]: cannot assign twice to immutable variable `x`
//
// 2. mut 写错位置：
//        let x mut = 3;
//    → error: expected `;`, found keyword `mut`
//
// 3. 用“重新声明”来绕过，但误解了题意：
//        let x = 5;   // 这是“遮蔽”，不是修改（variables5 会讲）
//    本题要求保留 `x = 5;` 这一行，所以必须用 mut，不能改成 let。
//
// 4. 以为 mut 能改类型：
//        let mut x = 3;
//        x = "hello";
//    → error[E0308]: mismatched types（x 已经是 i32 了）
//
// 5. 加了 mut 却从没修改：
//        let mut x = 3;
//    → 只是 warning: variable does not need to be mutable，仍能编译
//    但好习惯是“不需要就删掉 mut”。
//
// 6. 在常量上想用 mut：
//        const mut N: i32 = 3;   // 语法错误，const 永远不可变
//
// ============================================================================
//                          小 结
// ============================================================================
//
// 本题你需要记住：
//   1. Rust 变量默认不可变；想改必须写 `let mut`；
//   2. 修改不可变变量会报 E0384；
//   3. mut 只影响“能否赋值”，不改变类型；
//   4. 赋值语句 `x = 5;` 的类型是 ()；
//   5. 不需要修改时不要加 mut —— 让编译器帮你守住“不变”。
//
// 一句话记忆：**默认上锁，想改先配一把叫 mut 的钥匙。**
//
