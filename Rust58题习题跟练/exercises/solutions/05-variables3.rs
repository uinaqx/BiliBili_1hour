// ============================================================================
// 第 05 题 · variables3 —— 有了类型，还得有值
// ----------------------------------------------------------------------------
// 题目类型：compile（把代码改到能编译通过就算过关）
// 课件位置：第 2 章 · 2.1.1 变量绑定（变量必须先初始化再使用）、2.2.1 类型标注
// 难度：★☆☆☆☆
// 前置知识：variables1（let）、variables2（声明 vs 初始化、i32）
// ============================================================================
//
// 【题目要求】
// 让代码能把 x 的数字打印出来。原题给 x 写了类型，却没给它值。
//
// 原题代码（未完成，仅供对照）：
//     fn main() {
//         let x: i32;
//         println!("Number {}", x);
//     }
//
// 编译会报错：
//     error[E0381]: used binding `x` isn't initialized
//     （用到了变量 x，但它还没有被初始化）
//
// 【解题思路】
// 1. `let x: i32;` 的意思是：声明一个叫 x 的变量，**类型确定是 i32**，
//    但现在还没有值。冒号后面的 i32 是“类型标注”。
// 2. 下一行 println! 要把 x 填进 {} 里打印，于是要读 x 的值 → 可是它是空的
//    → 报 E0381，和 variables2 是同一个错误。
// 3. 补上值即可：`let x: i32 = 42;`（数字随便写，这里用 42）。
// 4. 也可以先声明、后赋值：
//        let x: i32;
//        x = 42;
//    同样合法，因为“使用 x 的那一刻”它已经有值了。
//
// ============================================================================
//                              知 识 铺 垫
// ============================================================================
//
// ● 类型标注（type annotation）的语法
//       let 名字: 类型 = 值;
//               ↑
//              冒号后面跟类型
//   例：
//       let x: i32 = 42;      // 32 位有符号整数
//       let y: f64 = 3.14;    // 64 位浮点数
//       let b: bool = true;   // 布尔
//       let c: char = 'A';    // 字符（单引号，只能一个字符）
//   注意冒号是英文半角 `:`，写成中文冒号 `：` 会报语法错误。
//
// ● 什么时候必须写类型？
//   1. 只声明不赋值时：`let x: i32;` —— 因为此时没有值可供推断；
//   2. 类型无法从上下文推断时，比如要把字符串转成数字；
//   3. const / static 常量必须写（见 variables6）。
//   其它情况下，能推断出来就可以不写，这也是 Rust 推荐的简洁写法。
//
// ● i32 到底是什么？
//   i = integer（整数），32 = 占 32 个二进制位。
//   可表示的范围是 -2_147_483_648 ~ 2_147_483_647，日常够用。
//   Rust 的整数默认就是 i32，所以 `let x = 42;` 和 `let x: i32 = 42;`
//   在本题里完全等价。
//
// ● 变量名后面为什么可以有 `: 类型`，但不能反过来？
//   这是 Rust 的语法规定（名字在前、类型在后），和 TypeScript、Kotlin 类似，
//   和 C/Java 的 `int x = 42;` 相反。习惯就好：
//       C / Java ：类型 名字 = 值;
//       Rust     ：let 名字: 类型 = 值;
//
// ● 打印数字和打印字符串用的是同一个 {} 
//   println! 会根据参数类型自动选择显示方式，整数直接显示十进制数字。
//   如果 {} 里的类型没有实现“可显示”能力（比如数组），编译才会报错。
//
// ============================================================================
//                              参 考 答 案
// ============================================================================

fn main() {
    // 声明变量 x，显式标注类型为 i32，并立刻赋初值 42
    //   let x : i32 = 42 ;
    //   │   │  │    │   └─ 分号：语句结束
    //   │   │  │    └───── 初值 42（类型已经是 i32，字面量直接匹配）
    //   │   │  └────────── 类型标注：x 是 32 位有符号整数
    //   │   └───────────── 变量名
    //   └───────────────── 声明变量的关键字
    let x: i32 = 42;

    // 把 x 的值填进 {}，打印 "Number 42" 并换行
    println!("Number {}", x);
}

// ============================================================================
//                            逐 行 解 析
// ============================================================================
//
// let x: i32 = 42;
//   ├─ let       ：创建一个新的变量绑定
//   ├─ x         ：变量名
//   ├─ : i32     ：类型标注（英文冒号），告诉编译器“这个格子只放 i32”
//   ├─ = 42      ：初始化，放入值 42
//   └─ ;         ：语句结束
//
// println!("Number {}", x);
//   ├─ "Number {}"：格式化字符串，{} 是占位符
//   ├─ x          ：第 1 个参数，类型 i32，会被格式化成 "42"
//   └─ 结果       ：Number 42
//
// ============================================================================
//                          常 见 错 误 与 提 示
// ============================================================================
//
// 1. 保持 `let x: i32;` 不变（= 原题状态）：
//    → error[E0381]: used binding `x` isn't initialized
//
// 2. 用中文冒号：
//        let x：i32 = 42;
//    → error: unknown start of token `：`（编译器不认识中文标点）
//
// 3. 类型和值对不上：
//        let x: i32 = "42";
//    → error[E0308]: mismatched types（期望 i32，实际是 &str）
//    想让字符串变数字要用 "42".parse::<i32>()（后续课程内容）。
//
// 4. 值超出 i32 范围：
//        let x: i32 = 3_000_000_000;
//    → error: literal out of range for `i32`（i32 最大约 21 亿）
//    换成 i64 就能装下。
//
// 5. 加 mut 也能编译（但本题不需要）：
//        let mut x: i32 = 42;
//    → 编译通过，只是会得到“变量从未被修改”的警告
//      （warning: variable does not need to be mutable）。
//    能不用 mut 就不用，这是 Rust 的好习惯。
//
// ============================================================================
//                          小 结
// ============================================================================
//
// 本题你需要记住：
//   1. 类型标注写法：`let 名字: 类型 = 值;`，冒号是英文的；
//   2. 只声明不赋值时，变量不能读（E0381），必须先初始化；
//   3. i32 是 32 位有符号整数，也是整数默认类型；
//   4. 先声明后赋值也合法，只要“读之前”已经有值；
//   5. 不需要修改的变量不要加 mut。
//
// 一句话记忆：**类型是给格子贴标签，值是往格子里放东西，两样都齐了才能用。**
//
