// ============================================================================
// 第 48 题 · generics1 —— 泛型的尖括号：给 Vec 指定“装什么”
// ----------------------------------------------------------------------------
// 题目类型：compile（把代码改到能编译通过就算过关）
// 课件位置：第 5 章 · 5.2 泛型类型参数
// 难度：★★☆☆☆
// 前置知识：变量与类型标注（variables2）、字符串 &str（strings1）
// ============================================================================
//
// 【题目要求】
// 购物清单程序编译不过。把 `Vec<?>` 里的 `?` 换成正确的类型，
// 让 `shopping_list.push("milk");` 能编译通过。
//
// 原题代码（未完成，仅供对照）：
//     fn main() {
//         let mut shopping_list: Vec<?> = Vec::new();
//         shopping_list.push("milk");
//     }
//
// 编译器会报（`?` 本身不是合法类型）：
//     error: expected type, found `?`
//
// 【解题思路】
// 1. `Vec` 是“动态数组（可变长数组）”，它能装任意类型的数据 ——
//    正因为它不限定装什么，所以你必须告诉它一次：装 String？装 i32？装 &str？
//    这个“待定的类型”用尖括号写在名字后面：`Vec<T>`。
// 2. 再看 push 进去的东西：`"milk"` 是**字符串字面量**，
//    它的类型是 `&str`（更准确地说是 `&'static str`，指向程序只读区的一段文本），
//    不是 `String`。
// 3. 所以填 `Vec<&str>`：
//        let mut shopping_list: Vec<&str> = Vec::new();
//        shopping_list.push("milk");
// 4. 反过来，如果你写 `Vec<String>`，push 的时候就会类型不匹配，
//    因为 `&str` 不是 `String`，那时必须改成 `shopping_list.push("milk".to_string());`。
//    题目只要求填 `?`，所以最省事的答案就是 `&str`。
//
// ============================================================================
//                              知 识 铺 垫
// ============================================================================
//
// ● 泛型（generic）是什么？—— “类型上的占位符”
//   想写一个“能装任何东西的盒子”，难道要为每种类型各写一个盒子吗？
//   （IntBox、StringBox、FloatBox ……）那样太啰嗦。
//   泛型就是给类型留一个空位：
//       struct Box<T> { value: T }     // T 是“待定类型”
//   用的时候再填：
//       Box<i32>      → value 是 i32
//       Box<String>   → value 是 String
//   打个比方：`Vec<T>` 是一张“表格模板”，T 是表头里空着的那一格；
//   `Vec<&str>` 就是把表头填成“字符串引用”的成品表格。
//   T 只是习惯叫法（Type 的首字母），你也可以写 `<U>`、`<Item>`、`<E>`。
//
// ● `Vec<T>` 是什么？
//   `Vec` 是标准库的动态数组，存在**堆**上，长度可以增长：
//       let v: Vec<i32> = Vec::new();   // 空的
//       v.push(1);                      // 追加一个元素，长度变 1
//   创建方式有两种常见写法：
//       Vec::new()          先建空的，之后再 push（本题用法）
//       vec![1, 2, 3]       用宏直接建一个带初始元素的
//   注意：想让 push 生效，变量必须是 `mut`（可变的），否则报 E0596。
//
// ● 为什么 `Vec::new()` 后面要写类型？
//   `Vec::new()` 创建的是一个“还没有任何元素”的空数组，
//   编译器从“空”里推断不出元素类型 —— 没有任何线索。
//   这时必须靠类型标注 `: Vec<&str>` 或者第一次 push 的值来告诉它。
//   如果连标注都没有、push 也还没写，编译器会报：
//       error[E0282]: type annotations needed
//       （它真的猜不出来）
//
// ● `&str` 和 `String` 的区别（第 3 章 3.1，strings1 讲过）
//   `&str`：字符串切片，是“借用”，不拥有数据；字符串字面量 "milk" 就是 &str。
//   `String`：拥有自己的堆内存，可以增长、修改，用 String::from("milk") 创建。
//   本题目的是“列出要买的东西”，只读不改，用 &str 完全够用，而且零分配、更省。
//
// ● `Str`（无 &）为什么不行？
//   `str` 是“长度在运行时才知道的文本”，它没有固定大小（?Sized），
//   不能直接放在变量、Vec 元素这种“需要编译期已知大小”的位置。
//   必须用引用 `&str`（引用的大小是固定的：一个指针 + 一个长度）。
//   所以 `Vec<str>` 会报 error[E0277]: the size for values of type `str`
//   cannot be known at compilation time。
//
// ● 泛型是“零成本”的
//   编译器在编译时会为每个具体类型生成一份专用代码（叫“单态化”），
//   所以 Vec<i32> 和 Vec<&str> 运行时没有任何“类型判断”的开销，
//   和手写两个不同类型的数组一样快。
//
// ============================================================================
//                              参 考 答 案
// ============================================================================

fn main() {
    // `let mut`  —— mut 表示这个变量可以修改（push 会往里加东西，必须 mut）
    // `shopping_list` —— 变量名
    // `: Vec<&str>` —— 类型标注：一个装着“字符串切片引用”的动态数组
    //                 尖括号 <> 里就是泛型参数 T 填的具体类型
    // `= Vec::new()` —— 调用 Vec 的关联函数 new()，创建一个空数组
    let mut shopping_list: Vec<&str> = Vec::new();

    // push：把元素追加到数组末尾
    // "milk" 是字符串字面量，类型 &'static str，正好匹配 Vec<&str>
    shopping_list.push("milk");

    // 小提示：这里没有打印，所以运行时什么也不输出；
    // 本题是 compile 模式，编译通过即算过关。
}

// ============================================================================
//                            详 细 解 析
// ============================================================================
//
// 1）尖括号 <> 怎么读？
//    `Vec<&str>` 读作“元素类型为 &str 的 Vec”，
//    或者更口语：“装着 &str 的动态数组”。
//    在 Rust 里，`<...>` 出现在类型/函数名后面，就是“填入泛型参数”。
//
// 2）为什么不能写 `Vec<String>` 然后保留 push("milk")？
//    `Vec<String>` 要求每个元素都是 String，
//    而 "milk" 的类型是 &str，两者是不同的类型（String 拥有数据，&str 是借用）。
//    push 时编译器会报：
//        error[E0308]: mismatched types
//        expected `String`, found `&str`
//    有两种修法：
//        a. 把类型改成 Vec<&str>（本题答案，只改类型标注）
//        b. 把 push 改成 shopping_list.push("milk".to_string())（改了两处）
//    题目说只补 `?`，所以选 a。
//
// 3）能不能干脆不写类型？
//        let mut shopping_list = Vec::new();
//        shopping_list.push("milk");
//    这样其实能编译！因为编译器看到 push("milk") 之后，就能把 T 推断成 &str。
//    那为什么题目还要求写？——因为这是**教学题**：
//    它想让你亲手体验“Vec 需要知道元素类型”这件事。
//    在真实项目里，如果上下文能推断出来，省略标注是常见且推荐的写法。
//
// 4）`mut` 能不能省？
//    不能。push 需要修改数组（可能触发扩容），签名是 `fn push(&mut self, value: T)`，
//    所以调用者必须有可变权限。省掉 mut 会报：
//        error[E0596]: cannot borrow `shopping_list` as mutable,
//        as it is not declared as mutable
//
// 5）为什么 "milk" 的类型是 &str 而不是 String？
//    字符串字面量在编译时就被写进二进制的只读数据段，
//    变量里存的只是一个“指向那段文本的指针 + 长度”，
//    所以它是借用（&str），不是拥有数据的 String。
//    这也是为什么字面量不能 push_str 修改 —— 它在只读内存里。
//
// 6）如果我想在清单里放多种类型怎么办？
//    泛型要求“同一个容器里元素类型统一”。
//    要放不同类型，可以用枚举把它们包起来：
//        enum Item { Food(String), Count(i32) }
//        let list: Vec<Item> = Vec::new();
//    这是 Rust 里“异构容器”的标准做法（枚举 + 泛型配合）。
//
// ============================================================================
//                          常 见 错 误 与 提 示
// ============================================================================
//
// 1. 写 `Vec<str>`（漏了 &）：
//    → error[E0277]: the size for values of type `str` cannot be known
//      at compilation time
//
// 2. 写 `Vec<String>` 但保留 push("milk")：
//    → error[E0308]: mismatched types, expected `String`, found `&str`
//
// 3. 忘了 mut：
//    → error[E0596]: cannot borrow `shopping_list` as mutable
//
// 4. 把尖括号写成圆括号或方括号：
//        Vec(&str)   /   Vec[&str]
//    → error: expected one of `!`, `(`, `+`, `,`, `::`, `<`, or `>`, found ...
//      （泛型参数必须用尖括号）
//
// 5. 以为 `?` 能自动补全：
//    `?` 在 Rust 里是“错误传播运算符”（用于 Result），不是类型的占位符。
//    出现在类型位置就是语法错误。
//
// 6. 写成 `Vec<&String>`：
//    语法上合法，但和 push("milk")（&str）不匹配，还是 E0308。
//
// ============================================================================
//                          小 结
// ============================================================================
//
// 本题你需要记住：
//   1. 泛型用尖括号 `<T>` 表示待定类型，`Vec<T>` 就是“装 T 的动态数组”；
//   2. `Vec::new()` 创建空数组时，编译器常常推断不出 T，需要你标注；
//   3. 字符串字面量是 `&str`，不是 `String`，别把两者混用；
//   4. `str` 大小未知，必须用引用 `&str` 才能放进容器。
//
// 一句话记忆：**Vec<T> 是“装 T 的盒子”，空盒子必须靠类型标注告诉编译器装什么。**
//
