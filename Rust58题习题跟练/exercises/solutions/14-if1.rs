// ============================================================================
// 第 14 题 · if1 —— 用 if 表达式返回较大的数
// ----------------------------------------------------------------------------
// 题目类型：test（让 #[test] 测试通过就算过关）
// 课件位置：第 4 章 · 4.1 if / else（if 是表达式，可以直接产生值）
// 难度：★★☆☆☆
// 前置知识：let 变量（variables1）、函数定义与返回值（functions1~functions5）
// ============================================================================
//
// 【题目要求】
// 补全函数 bigger：返回 a、b 中较大的那个数。
// 题目还限制了两条：
//   - 不能调用别的函数（比如不能用 max）；
//   - 不能新增额外的变量（不能写 let r = ...）。
// 原题代码（未完成，仅供对照）：
//     pub fn bigger(a: i32, b: i32) -> i32 {
//         // Complete this function to return the bigger number!
//         // Do not use:
//         // - another function call
//         // - additional variables
//     }
//
//     #[cfg(test)]
//     mod tests {
//         use super::*;
//
//         #[test]
//         fn ten_is_bigger_than_eight() {
//             assert_eq!(10, bigger(10, 8));
//         }
//
//         #[test]
//         fn fortytwo_is_bigger_than_thirtytwo() {
//             assert_eq!(42, bigger(32, 42));
//         }
//
//         #[test]
//         fn equal_numbers() {
//             assert_eq!(42, bigger(42, 42));
//         }
//     }
//
// 【解题思路】
// 1. 题目本质：比较两个数，谁大返回谁。
// 2. Rust 的 if 是一个“表达式（expression）”，它会“算出”一个值，
//    所以可以直接把 if ... else ... 放在函数体的最后，当作返回值。
// 3. 返回值类型是 i32，两个分支分别给出 a 和 b，类型都是 i32，一致。
// 4. 相等的情况（a == b）不用单独处理：a > b 为假时走 else 返回 b，
//    此时 a == b，返回 b 与返回 a 结果相同，测试 equal_numbers 才能通过。
//
// ============================================================================
//                              知 识 铺 垫
// ============================================================================
//
// ● if 的基本写法
//     if 条件 {
//         代码块
//     } else {
//         代码块
//     }
//   `条件` 必须是 bool 类型（true / false）。
//   注意：Rust 不像 C 那样“非 0 即真”，写 `if 1 { }` 会直接编译报错。
//
// ● 关键区别：语句（statement）vs 表达式（expression）
//   语句：做一件事，不产生值，例如 `let x = 5;`
//   表达式：会算出一个值，例如 `1 + 2`、`if a > b { a } else { b }`
//   Rust 里“几乎一切都是表达式”，if 也是表达式 —— 这是本题的核心。
//
// ● 分号决定一切
//     let x = if a > b { a } else { b };   // 有值，可以赋给 x
//     if a > b { a; } else { b; }          // 每个分支加了分号 → 变成语句 → 值为 ()
//   在函数最后一行写表达式且**不加分号**，它的值就是函数的返回值。
//   （这条规则在 functions5 里已经练过。）
//
// ● 两个返回值类型必须一致
//   if 的两个分支都是“候选项”，编译器要求它们算出同一种类型。
//   本题两个分支都是 i32，所以整个 if 表达式的类型是 i32，
//   正好等于函数声明的返回类型 -> i32。
//
// ● 大括号里的“最后一个表达式”就是块的值
//     {
//         a        // ← 没有分号，这个块的值就是 a
//     }
//   如果写成 `{ a; }`，这个块的值就是 ()（空元组），类型立刻对不上。
//
// ● #[cfg(test)] 与 #[test] 是什么？
//   #[cfg(test)] mod tests 表示“只有测试模式下才编译这个模块”。
//   里面 use super::*; 把外层的 bigger 引入测试模块，于是测试能调用它。
//   本题没有 main 函数，必须用 rustc --test 编译（见文末运行方式）。
//
// ============================================================================
//                              参 考 答 案
// ============================================================================

// pub 表示“公开”，让测试模块（以及将来的其他模块）能调用这个函数
// a、b：两个 i32（32 位有符号整数）参数，按值传入
// -> i32：函数返回一个 i32
pub fn bigger(a: i32, b: i32) -> i32 {
    // if 是表达式：条件 a > b 为真取 a，否则取 b
    // 注意两个分支最后都没有分号，所以 a / b 就是各自块的值
    if a > b {
        a // 分支 1 的值：a（不加分号才是值）
    } else {
        b // 分支 2 的值：b（不加分号才是值）
    }
    // 整个 if 表达式的值 = 函数的返回值，所以这里不需要写 return
}

// ---------------------------------------------------------------------------
// 下面这段是原题自带的测试代码，一个字都没有改动。
// #[cfg(test)]：只在 --test 编译时才包含这个模块
// mod tests    ：定义一个名叫 tests 的子模块
// use super::* ：把父模块（本文件最外层）的所有名字引入进来，才能用 bigger
// ---------------------------------------------------------------------------
#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn ten_is_bigger_than_eight() {
        // assert_eq!(期望值, 实际值)：两边相等才算通过
        assert_eq!(10, bigger(10, 8));
    }

    #[test]
    fn fortytwo_is_bigger_than_thirtytwo() {
        assert_eq!(42, bigger(32, 42));
    }

    #[test]
    fn equal_numbers() {
        // 相等时，走 else 分支返回 b = 42，结果依然是 42
        assert_eq!(42, bigger(42, 42));
    }
}

// ============================================================================
//                            逐 行 解 析
// ============================================================================
//
// pub fn bigger(a: i32, b: i32) -> i32
//   ├─ pub        ：公开可见
//   ├─ fn         ：定义函数
//   ├─ bigger     ：函数名
//   ├─ (a: i32, b: i32)：两个参数，每个都必须写类型（Rust 强制）
//   └─ -> i32     ：返回类型是 i32；函数体最后一个表达式的值即为返回值
//
// if a > b {
//   ├─ if     ：条件表达式关键字
//   ├─ a > b  ：比较运算，结果是 bool（true / false）
//   └─ { a }  ：真时执行这个块，块的值是 a
// } else {
//     b          ：假时执行这个块，块的值是 b
// }
//
// 整个 if/else 是一个表达式，它的类型是两个分支的公共类型 i32，
// 放在函数体最后、不带分号，所以直接成为返回值。
//
// ============================================================================
//                          常 见 错 误 与 提 示
// ============================================================================
//
// 1. 分支里多写了分号：
//        if a > b { a; } else { b; }
//    → error[E0308]: mismatched types
//      expected `i32`, found `()`
//    （因为加了分号，块的值变成了 ()，不是 i32）
//
// 2. 只写 if 不写 else：
//        if a > b { a }
//    → error[E0317]: `if` may be missing an `else` clause
//    （条件为假时整个表达式没有值，编译器不接受）
//
// 3. 用了被禁止的写法：
//        a.max(b)          // 调用了别的函数
//        let r = ...; r    // 新增了变量
//    这两种都能让测试通过，但不符合题面限制。
//    真正想练的是“if 是表达式”这件事。
//
// 4. C / Java 三元运算符的直觉：
//        a > b ? a : b     // C、Java 写法
//    Rust 没有 ?: 运算符（? 在 Rust 里是另一回事），要写成 if/else。
//
// 5. 打印/测试时函数名写错：
//        biggerr(10, 8)
//    → error[E0425]: cannot find function `biggerr` in this scope
//
// 6. 用普通方式编译：
//        rustc if1.rs
//    → error[E0601]: `main` function not found in crate
//    （本题没有 main，只有测试，必须加 --test）
//
// ============================================================================
//                          小 结
// ============================================================================
//
// 本题你需要记住：
//   1. Rust 的 if 是表达式，可以直接产生一个值；
//   2. 函数体最后一个表达式（不带分号）就是返回值；
//   3. if 的每个分支值类型必须一致，而且要跟函数返回类型一致；
//   4. 测试代码用 #[cfg(test)] + #[test]，编译要加 --test。
//
// 一句话记忆：**Rust 的 if 会“算出”一个值，别加分号就能把它当返回值。**
//
