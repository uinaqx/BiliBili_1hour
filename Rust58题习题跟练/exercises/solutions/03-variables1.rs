// ============================================================================
// 第 03 题 · variables1 —— 用 let 创建变量
// ----------------------------------------------------------------------------
// 题目类型：compile（把代码改到能编译通过就算过关）
// 课件位置：第 2 章 · 2.1.1 变量绑定
// 难度：★☆☆☆☆
// 前置知识：会写 fn main、会用 println! 打印（参考 intro1、intro2）
// ============================================================================
//
// 【题目要求】
// 让下面的代码编译通过。原题漏写了一个关键字。
//
// 原题代码（未完成，仅供对照）：
//     fn main() {
//         x = 5;
//         println!("x has the value {}", x);
//     }
//
// 【解题思路】
// 1. Rust 声明一个新变量必须用 `let` 关键字。
// 2. 原题写的是 `x = 5;`，编译器会理解成“给一个已经存在的变量 x 赋值”，
//    可是 x 从来没有声明过，于是报错：
//        error[E0425]: cannot find value `x` in this scope
// 3. 把第 1 行改成 `let x = 5;` 即可。
// 4. 不需要写类型：编译器会根据 5 自动推断出 x 是 i32（32 位有符号整数）。
//
// ============================================================================
//                              知 识 铺 垫
// ============================================================================
//
// ● 程序从哪里开始执行？
//   Rust 程序从 fn main() 开始执行，这一点和 C 的 main 函数一样。
//   `fn` 是“函数（function）”关键字，`main` 是函数名，`()` 里放参数。
//
// ● 什么是“变量绑定（binding）”？
//   变量就是给内存里的一块数据起个名字。
//     let x = 5;
//   读作“把名字 x 和值 5 绑定在一起”。Rust 官方把它叫“变量绑定”而不是
//   “变量赋值”，因为名字和值是一种“绑定”关系。
//
// ● 为什么必须写 let？
//   Rust 是静态类型语言，编译器在编译时就要把每个名字、每个类型都检查清楚。
//   只有看到 `let`，编译器才会“创建一个新变量”；
//   否则 `x = 5` 会被当成“给已有变量赋值”，找不到变量就报错。
//
// ● Rust 和 C 的一个大区别：变量默认不可修改
//   C 里 `int a = 100;` 之后可以随便 `a = 200;`；
//   Rust 里 `let x = 5;` 之后**不能再改 x**，想改必须写 `let mut x = 5;`。
//   这个“默认不可变”的特性会在 variables4 里详细讲。
//
// ============================================================================
//                              参 考 答 案
// ============================================================================

fn main() {
    // `let`：创建一个新的变量绑定
    // `x`  ：变量名（名字可以自己起，建议见名知意）
    // `5`  ：初始值；类型由编译器自动推断为 i32（32 位有符号整数）
    let x = 5;

    // 打印变量：
    //   println!        —— 标准库提供的“打印并换行”宏（注意末尾有感叹号 !）
    //   "x has the value {}" —— 格式化字符串，{} 是占位符
    //   x               —— 用于填充 {} 的参数
    println!("x has the value {}", x);

    // 每一条语句以分号 ; 结尾。
    // main 函数没有返回值，等价于返回单元类型 ()（可以理解成 C 的 void）。
}

// ============================================================================
//                            逐 行 解 析
// ============================================================================
//
// let x = 5;
//   ├─ let    ：声明变量的关键字
//   ├─ x      ：变量名
//   ├─ = 5    ：赋初值
//   └─ ;      ：一条语句结束
//
// println!("x has the value {}", x);
//   ├─ println!    ：宏，负责打印；自动换行
//   ├─ "..."       ：格式化字符串
//   ├─ {}          ：占位符，会按顺序被后面的参数替换
//   └─ x           ：要打印的变量
//
// ============================================================================
//                          常 见 错 误 与 提 示
// ============================================================================
//
// 1. 忘写 let：
//        x = 5;
//    → error[E0425]: cannot find value `x` in this scope
//
// 2. 忘写分号：
//        let x = 5
//    → error: expected `;`, found `println`
//
// 3. 打印时忘记传参数：
//        println!("x has the value {}");
//    → error: 1 positional argument in format string, but no arguments were given
//
// 4. 把 println! 写成 println：
//        println("hello");
//    → error: cannot find function `println` in this scope
//    （println 是宏，不是函数，必须带感叹号）
//
// 5. 变量名拼错：
//        let x = 5;  println!("{}", y);
//    → error[E0425]: cannot find value `y` in this scope
//
// ============================================================================
//                          小 结
// ============================================================================
//
// 本题你需要记住：
//   1. 用 `let 名字 = 值;` 创建变量；
//   2. 类型通常不用写，编译器会自动推断；
//   3. 打印用 println!（宏），{} 是占位符；
//   4. Rust 语句要打分号，main 是程序入口。
//
// 一句话记忆：**Rust 里任何新变量都必须先用 let 声明。**
//
