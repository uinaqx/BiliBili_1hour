// ============================================================================
// 第 27 题 · move_semantics2 —— 复制一份再送人，两个 Vec 各自安好
// ----------------------------------------------------------------------------
// 题目类型：test（让 #[test] 测试通过就算过关）
// 课件位置：第 2 章 · 2.3.1 移动后原变量失效；用 clone 或借用解决
// 难度：★★☆☆☆
// 前置知识：move_semantics1（传参 = 所有权移动）、Vec、函数返回值
// 本题地位：move_semantics 系列第 2 题，承接上一题："传完还想用原变量怎么办？"
// ============================================================================
//
// 【题目要求】
// 让测试通过，并且保证两个 Vec 互不影响：
//   vec0 仍然是 [22, 44, 66]；
//   vec1 是 [22, 44, 66, 88]。
//
// 原题代码（未完成，仅供对照）：
//     #[test]
//     fn main() {
//         let vec0 = vec![22, 44, 66];
//         let mut vec1 = fill_vec(vec0);
//         assert_eq!(vec0, vec![22, 44, 66]);      // ← 用不了了
//         assert_eq!(vec1, vec![22, 44, 66, 88]);
//     }
//
// 编译报错：
//     error[E0382]: borrow of moved value: `vec0`
//     （vec0 的值已经被移走了，不能再借用）
//
// 【解题思路】
// 1. `fill_vec(vec0)` 把 vec0 的所有权过户给了函数，从此 main 里的 vec0 作废；
//    后面 assert_eq!(vec0, ...) 再去读它，就报 E0382。
// 2. 题目要"两个 Vec 分开"，说明我们要的是"复制一份给函数，原件留着"。
// 3. Vec 提供了 clone()，可以真正复制一份（堆上的数据也复制）：
//        let mut vec1 = fill_vec(vec0.clone());
//    这样函数拿到的是副本，vec0 的原件还在，两个 assert 都能过。
// 4. 另一种思路是"不转移所有权，只借用"，也就是把 fill_vec 改成
//    `fn fill_vec(vec: &mut Vec<i32>)`，但那样函数就不该再返回 Vec 了，
//    改法比 clone 大，本题采用 clone 最直接。
//
// ============================================================================
//                              知 识 铺 垫
// ============================================================================
//
// ● 再复习一遍：移动（move）到底移走了什么？
//   Vec 变量里存着三样东西：指向堆的指针、长度 len、容量 capacity。
//   传参时，这三样被"搬"进函数里，原变量就被标记为"已失效"。
//   打个比方：vec0 是"图书馆借书卡"，传给函数等于把卡交给别人，
//   你手里就没卡了，自然不能再借书（再访问 vec0）。
//
// ● 为什么 Rust 不自动帮我们复制？
//   因为自动复制堆数据很贵（可能几百 MB），而且容易产生"两个变量都以为
//   自己拥有同一份数据"的问题。Rust 的原则是：
//   要么把所有权交出去（move），要么显式写 clone()，绝不偷偷复制。
//
// ● clone() 是什么？
//   Clone 是标准库里的一个"特征（trait）"，实现了它的类型可以调用 .clone()。
//   Vec<T> 的 clone() 是"深复制"：新 Vec 有自己独立的一份堆内存。
//   所以 clone 之后改副本，原件纹丝不动。
//   代价：要额外分配内存、复制每个元素，性能上比"借用"贵。
//
// ● 和 Copy 的区别（重要）
//   i32、bool、char 这类类型实现的是 Copy：赋值/传参时自动"复印"，原件照样能用。
//       let a = 5; let b = a;  // a 和 b 都能用
//   Vec 没有实现 Copy（因为它管理堆内存），只实现了 Clone，必须手动 .clone()。
//   记忆：**Copy 是自动复印，Clone 是手动复印。**
//
// ● 那为什么不干脆都 clone？
//   因为复制有成本。Rust 的哲学是"能借就借，非要复制才复制"。
//   后面的 move_semantics4、move_semantics6 会带你用"借用 &"避免复制。
//
// ● `let mut vec1` 里的 mut 是多余的吗？
//   是。本题里 vec1 创建后没有被修改，编译器会给一个 warning：
//       warning: variable does not need to be mutable
//   这是原题自带的写法，warning 不影响测试通过；想清爽可以去掉 mut。
//
// ============================================================================
//                              参 考 答 案
// ============================================================================

#[test]
fn main() {
    // 原始 Vec：[22, 44, 66]，所有者是 vec0
    let vec0 = vec![22, 44, 66];

    // vec0.clone()：先复制出一份"独立的副本"（堆数据也复制）
    // 交给 fill_vec 的是副本，副本被 push(88) 后返回；
    // 原件 vec0 从头到尾没有被动过
    let mut vec1 = fill_vec(vec0.clone());

    // 原件检查：还是 [22, 44, 66]
    assert_eq!(vec0, vec![22, 44, 66]);

    // 副本检查：被追加了 88，变成 [22, 44, 66, 88]
    assert_eq!(vec1, vec![22, 44, 66, 88]);
}

fn fill_vec(vec: Vec<i32>) -> Vec<i32> {
    // 接收的是 clone 出来的副本，所以这里改它不会影响外面的 vec0
    // let mut vec = vec; 把参数重新绑定成可变的（参考 move_semantics1）
    let mut vec = vec;

    // 在副本末尾追加 88
    vec.push(88);

    // 把改好的副本交回去，成为 main 里的 vec1
    vec
}

// ============================================================================
//                            逐 行 解 析
// ============================================================================
//
// let vec0 = vec![22, 44, 66];
//   └─ 堆上分配 3 个 i32，vec0 持有指针/长度/容量
//
// vec0.clone()
//   └─ 再分配一块堆内存，把 22,44,66 复制过去，得到一个新的 Vec
//      此时内存里有两份独立数据：vec0 一份，副本一份
//
// let mut vec1 = fill_vec(副本);
//   └─ 副本的所有权移动进函数；函数 push 后把它返回，所有权交给 vec1
//
// assert_eq!(vec0, vec![22, 44, 66]);
//   └─ vec0 没被移动过，可以正常读；内容仍是 3 个元素
//
// assert_eq!(vec1, vec![22, 44, 66, 88]);
//   └─ vec1 是副本改出来的，多了一个 88
//
// ============================================================================
//                 如果我偏不用 clone，还有别的解法吗？
// ============================================================================
//
// 有，思路是"别把所有权送出去"，让函数借用：
//
//     fn main() {
//         let mut vec0 = vec![22, 44, 66];
//         let vec1 = fill_vec(&mut vec0);   // 只借，不送
//         ...
//     }
//     fn fill_vec(vec: &mut Vec<i32>) -> Vec<i32> {
//         vec.push(88);
//         vec.clone()      // 想返回一个新 Vec，还得 clone
//     }
//
// 你会发现：只要函数需要"返回一个改过的 Vec"，终究绕不开复制一次。
// 真正省掉复制的方法，是让函数直接返回 () 并原地修改借用进来的 Vec，
// 或者干脆像 move_semantics4 那样"在函数里创建、再交回去"。
//
// 本题测试的写法（`assert_eq!(vec0, ...)` 和 `assert_eq!(vec1, ...)` 都要成立）
// 决定了必须有两份数据，所以 clone 是最贴合题意的答案。
//
// ============================================================================
//                          常 见 错 误 与 提 示
// ============================================================================
//
// 1. 什么都不改，直接编译：
//    → error[E0382]: borrow of moved value: `vec0`
//       help: consider cloning the value if the performance cost is acceptable
//       （编译器其实已经把答案提示给你了）
//
// 2. 只在 main 里给 vec0 加 mut：
//        let mut vec0 = vec![22, 44, 66];
//    → 没用，mut 不代表"可以复制"，vec0 还是被移走了。
//
// 3. 以为是"引用传参"，改成 fill_vec(&vec0) 却忘了改函数签名：
//    → error[E0308]: mismatched types（expected `Vec<i32>`, found `&Vec<i32>`）
//
// 4. 函数里忘了 let mut vec = vec;
//    → error[E0596]: cannot borrow `vec` as mutable（同上一题）
//
// 5. 用 vec0.to_vec() 代替 clone()：
//    对 Vec<i32> 来说 to_vec() 也能用（它来自切片），效果和 clone 一样；
//    但 clone() 语义更直白，推荐用 clone()。
//
// ============================================================================
//                          小 结
// ============================================================================
//
// 本题你需要记住：
//   1. 传 Vec 给函数后，原变量就"报废"了（E0382 就是它）；
//   2. 想保留原件，用 .clone() 显式复制一份；
//   3. clone 是深复制，两个 Vec 各有一块堆内存，互不影响；
//   4. Vec 没有 Copy，所以不会自动复制，必须手动 clone；
//   5. 复制有成本，能借（&）就别复制——这是后面几题的主线。
//
// 一句话记忆：**送了就没收；舍不得，就先 clone 一份再送。**
//
