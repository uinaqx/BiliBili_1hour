// ============================================================================
// 第 21 题 · primitive_types4 —— 从数组里切出一段（切片）
// ----------------------------------------------------------------------------
// 题目类型：test（让 #[test] 测试通过就算过关）
// 课件位置：第 3 章 · 3.5 数组（数组切片）；也涉及 3.1 切片的概念
// 难度：★★☆☆☆
// 前置知识：变量、数组基础、引用 &（参考 variables*、primitive_types3）
// ============================================================================
//
// 【题目要求】
// 从数组 a 中截取一段，赋给 nice_slice，使最后的断言成立。
//
// 原题代码（未完成，仅供对照）：
//     #[test]
//     fn slice_out_of_array() {
//         let a = [1, 2, 3, 4, 5];
//
//         let nice_slice = ???
//
//         assert_eq!([2, 3, 4], nice_slice)
//     }
//
// 【解题思路】
// 1. 数组 a = [1, 2, 3, 4, 5]，下标从 0 开始：a[0]=1, a[1]=2, a[2]=3, a[3]=4, a[4]=5。
// 2. 想要 [2, 3, 4]，就是从下标 1 开始、到下标 4 之前（不含 4）结束：1..4。
// 3. 用切片语法：&a[1..4]，得到的是“数组的一段引用”，类型是 &[i32]。
// 4. 注意必须加 &（借用）。写成 a[1..4] 会把这一段“移动/复制”出来，类型对不上。
//
// ============================================================================
//                              知 识 铺 垫
// ============================================================================
//
// ● 数组（array）：[T; N]
//   let a = [1, 2, 3, 4, 5];  // 类型是 [i32; 5]，长度固定为 5
//   数组长度在编译时就确定，元素类型全部相同，连续存放在内存中（栈上）。
//
// ● 下标（index）从 0 开始
//   a[0] = 1, a[1] = 2, a[2] = 3, a[3] = 4, a[4] = 5
//   越界访问（比如 a[5]）会直接 panic（程序崩溃并报错），不会像 C 那样是未定义行为。
//
// ● 区间（range）语法
//   a..b  ：左闭右开 [a, b)  ——包含 a，不包含 b（最常用）
//   a..=b ：闭区间     [a, b] ——a 和 b 都包含
//   例：1..4 表示 1、2、3 三个数字。
//
// ● 切片（slice）：&[T]
//   切片是“对一段连续数据（数组/向量/字符串等）的引用”，本身不拥有数据。
//     &a[1..4] 的类型是 &[i32]，长度在运行时才知道。
//   如果写 a[1..4]（不加 &），会触发 Rust 的一个限制：
//   无法把数组的一部分“移出来”，因为数组元素不能单独移动，编译会报错。
//
// ● #[test] 是什么？
//   #[test] 标记一个“测试函数”。用 rustc --test 编译后运行，会逐个执行这些测试。
//   测试里用 assert_eq!(左, 右) 断言“左右相等”，不相等就 panic（测试失败）。
//   本题只有测试、没有 main，所以必须用 --test 方式编译运行。
//
// ============================================================================
//                              参 考 答 案
// ============================================================================

#[test]
fn slice_out_of_array() {
    // 一个长度为 5 的 i32 数组，类型是 [i32; 5]（栈上连续存放）
    let a = [1, 2, 3, 4, 5];

    // 取 a 中下标 1 到 4（不含 4）的一段引用：
    //   1..4  → 下标 1、2、3 → 元素 [2, 3, 4]
    //   &     → 借用，不复制数据；得到的类型是 &[i32]（切片引用）
    let nice_slice = &a[1..4];

    // 断言：左边的数组 [2, 3, 4] 应该等于右边的切片 &[2, 3, 4]
    // assert_eq! 是宏，比较失败时会 panic，并打印左右两边的值
    assert_eq!([2, 3, 4], nice_slice)
    // 注意：这里最后一个表达式后面没有分号，
    // 因为测试函数返回 ()，这条 assert_eq! 就是函数的最后一条语句/表达式。
}

// ============================================================================
//                            详 细 解 析
// ============================================================================
//
// 1）为什么是 1..4 而不是 1..3？
//    区间是“左闭右开”：&a[1..4] 取下标 1、2、3，正好是 [2, 3, 4]。
//    如果你写 &a[1..3]，得到的是 [2, 3]；写 &a[1..=4]，得到的是 [2, 3, 4, 5]。
//
// 2）切片和数组有什么区别？
//    数组 [i32; 5]：长度固定、编译期已知、拥有自己的数据。
//    切片 &[i32] ：长度运行期才确定、只是一个“引用”，不拥有数据。
//    所以切片可以指向数组、Vec、甚至另一个切片的一部分。
//
// 3）为什么一定要加 &？
//    如果不加 &，a[1..4] 的类型是 [i32]（无固定长度的数组类型），
//    Rust 不允许这种“大小未知的类型”直接放在变量里，会报错：
//        error[E0277]: the size for values of type `[i32]` cannot be known...
//    更深层的原因：数组的元素是连续存放的，Rust 不允许把数组的一部分“搬出来”，
//    只能借用（&）一段。
//
// 4）为什么断言里可以直接写 [2, 3, 4]？
//    [2, 3, 4] 会自动被推断为 [i32; 3] 数组；
//    Rust 标准库实现了数组与切片之间的按元素比较（PartialEq），
//    所以 [i32; 3] 和 &[i32] 可以比较。
//
// 5）运行方式（本题是测试题）：
//    rustc --edition 2021 --test primitive_types4.rs -o primitive_types4.exe
//    .\primitive_types4.exe
//    输出类似：
//        running 1 test
//        test slice_out_of_array ... ok
//
// ============================================================================
//                          常 见 错 误 与 提 示
// ============================================================================
//
// 1. 写成 let nice_slice = a[1..4];（不加 &）
//    → error[E0277]: the size for values of type `[i32]` cannot be known at compilation time
//
// 2. 下标算错：&a[2..4] → [3, 4]，断言失败
//    → test slice_out_of_array ... FAILED
//
// 3. 用闭区间写错：&a[1..=4] → [2, 3, 4, 5]，长度不对 → 断言失败
//
// 4. 忘记 --test：
//        rustc primitive_types4.rs
//    → error[E0601]: `main` function not found in crate
//    （因为本题只有测试函数，没有 main）
//
// 5. 越界：&a[1..6] → 运行期 panic: range end index 6 out of range for slice of length 5
//
// ============================================================================
//                          小 结
// ============================================================================
//
// 本题你需要记住：
//   1. 数组 [T; N] 长度固定，下标从 0 开始；
//   2. 切片 &[T] 是对一段连续数据的引用，不拥有数据；
//   3. 切片语法：&数据[开始..结束]（左闭右开），&数据[开始..=结束]（闭区间）；
//   4. 测试函数用 #[test] 标记，编译时要加 --test。
//
// 一句话记忆：**切片 = 借来的一段连续内存，用“左闭右开”的起点..终点表示。**
//
