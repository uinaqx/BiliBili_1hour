// ============================================================================
// 第 30 题 · move_semantics5 —— 同一时刻只能有一个“可变借用”
// ----------------------------------------------------------------------------
// 题目类型：test（让测试通过就算过关）
// 课件位置：第 2 章 · 2.3.2 引用与借用（可变引用的使用条件）
// 难度：★★★★☆
// 前置知识：move_semantics1~4（所有权、& 借用、&mut 可变借用）
// ============================================================================
//
// 【题目要求】
// 只允许“调整 main() 里语句的顺序”，不能增加、删除或修改任何一行，
// 让代码能编译并通过测试。
//
// 原题代码（未完成，仅供参考）：
//     #[test]
//     fn main() {
//         let mut x = 100;
//         let y = &mut x;
//         let z = &mut x;
//         *y += 100;
//         *z += 1000;
//         assert_eq!(x, 1200);
//     }
//
// 编译会报错：
//     error[E0499]: cannot borrow `x` as mutable more than once at a time
//     （不能同时把 x 可变借用两次）
//
// 【解题思路】
// 1. y 和 z 都是 &mut x（x 的可变引用），但 Rust 规定：
//    同一作用域内，同一块数据同一时刻**只能有一个可变引用**。
// 2. 原题的 y 一直“活着”，直到最后一次使用（*y += 100）才算结束；
//    z 在这之前就又借了一次 x，于是冲突。
// 3. 只要在 z 借用之前，先让 y 用完（即把 *y += 100 挪到 z 之前），
//    借用检查器就认为 y 的生命周期已经结束，z 的借用就合法了。
// 4. 调整后的顺序：
//        let mut x = 100;
//        let y = &mut x;
//        *y += 100;        ← 先用完 y
//        let z = &mut x;   ← 再借 z
//        *z += 1000;
//        assert_eq!(x, 1200);
//
// ============================================================================
//                              知 识 铺 垫
// ============================================================================
//
// ● 所有权（ownership）一句话版
//   Rust 里每个值都有一个“所有者”变量；值同一时刻只能有一个所有者；
//   所有者离开作用域，值就被自动释放（drop）。这样就不需要 GC，也不会双重释放。
//
// ● 借用（borrow）是什么？
//   不想交出所有权，又想让别的代码读/改这个值，就用“引用”：
//     &x    —— 不可变引用（只读借用）
//     &mut x —— 可变引用（可读可写借用）
//   引用本身不拥有数据，只是“借来用一下”，用完要还。
//
// ● 可变引用的两条铁律（本节核心）
//   1. 同一时刻，一个值只能有一个可变引用（&mut）；
//   2. 可变引用和不可变引用不能同时存在。
//   为什么？这是为了在**编译期**就排除“两个指针同时改同一块内存”的数据竞争，
//   这是 Rust 内存安全的核心设计。
//
// ● 引用的“生命周期”到哪里结束？
//   很多人误以为“引用必须在代码块 } 结束才失效”，其实不是。
//   现代 Rust 使用“非词法生命周期（NLL）”：**引用的生命周期在它最后一次被使用后
//   就结束了**，而不是等到 }。
//   本题就是利用这一点：*y += 100 用完 y 后，y 的可变借用就结束了。
//
// ● 解引用 * 是什么？
//   *y 表示“y 指向的那个值”。对 &mut i32 来说，*y += 100 等价于
//   “把 y 指向的那个整数加 100”。
//
// ● #[test] fn main() 是什么写法？
//   本题的入口函数既叫 main 又被 #[test] 标记，所以必须以测试方式运行：
//   rustc --test 时它是一个测试函数；平常 rustc 编译时它不当作 main，
//   会报“找不到 main”。所以本题要用 --test 运行。
//
// ============================================================================
//                              参 考 答 案
// ============================================================================

#[test]
fn main() {
    // 声明一个可变变量 x（想用 &mut x 借用，x 本身必须先是 mut）
    let mut x = 100;

    // 第一次可变借用：y 指向 x
    let y = &mut x;

    // 立刻通过 y 修改 x：x 变成 200。
    // 这一行之后，y 最后一次被使用，它的借用生命周期到此结束（NLL）。
    *y += 100;

    // 此时 x 已经没有被借用了，可以再次可变借用：z 指向 x
    let z = &mut x;

    // 通过 z 修改 x：x 变成 200 + 1000 = 1200
    *z += 1000;

    // 断言 x 的最终值为 1200；不相等则测试失败
    assert_eq!(x, 1200);
}

// ============================================================================
//                            逐 行 解 析
// ============================================================================
//
// let mut x = 100;
//   ├─ let      ：声明变量
//   ├─ mut      ：允许之后修改 x（不加 mut 的话连 &mut x 都不允许借）
//   ├─ x = 100  ：初值 100，类型推断为 i32
//   └─ ;        ：语句结束
//
// let y = &mut x;
//   └─ 取 x 的可变引用交给 y；类型是 &mut i32
//
// *y += 100;
//   └─ 解引用后对 x 加 100（等价于 x += 100，但这里必须通过引用来改）
//
// let z = &mut x;
//   └─ 第二次可变借用；之所以合法，是因为 y 已经用完了
//
// *z += 1000;
//   └─ 通过 z 再加 1000，最终 1200
//
// ============================================================================
//                        为什么原顺序会报错？
// ============================================================================
//
// 原顺序：
//     let mut x = 100;
//     let y = &mut x;   // 借用 1
//     let z = &mut x;   // 借用 2 —— 此时 y 还没被使用！
//     *y += 100;        // y 还活着
//     *z += 1000;
//
// 借用检查器看到：y 和 z 这两个可变引用“同时存在”，违反“只能有一个可变引用”，
// 于是报 E0499。把 *y += 100; 提到 z 之前，两个借用就不再重叠了。
//
// 这就是 Rust 与 C/C++ 最大的不同之一：
// 同样的内存操作，C 编译器可能只给你一个警告甚至不报错，运行时才出错；
// Rust 在编译期就把“同时存在两个可变指针”这种危险代码拦住了。
//
// ============================================================================
//                          常 见 错 误 与 提 示
// ============================================================================
//
// 1. 不改顺序，只加括号想“强行分开作用域”：
//        let z = &mut x;
//        { *y += 100; }
//    → 仍然报 E0499，因为 y 的借用一直覆盖到它的最后一次使用。
//
// 2. 去掉 mut：let x = 100; 然后 &mut x
//    → error[E0596]: cannot borrow `x` as mutable, as it is not declared as mutable
//
// 3. 以为要把 y、z 换成不可变引用：
//    题目要求不能改代码，只能换顺序；而且不可变引用也不能用于 *y += 100。
//
// 4. 用 --test 之外的方式编译：
//        rustc move_semantics5.rs
//    → error[E0601]: `main` function not found（因为入口被 #[test] 标记了）
//
// ============================================================================
//                          小 结
// ============================================================================
//
// 本题你需要记住：
//   1. 一个值同一时刻只能有一个可变引用；
//   2. 引用的生命周期在“最后一次使用”之后结束（NLL），不是等到 }；
//   3. 编译器检查的是“借用是否重叠”，而不是“变量声明在哪”；
//   4. 所有权 + 借用规则是 Rust 不需要 GC 也能保证内存安全的关键。
//
// 一句话记忆：**先用完再借第二个；两个 &mut 不能同时活着。**
//
