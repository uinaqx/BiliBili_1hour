// ============================================================================
// 第 26 题 · move_semantics1 —— 想 push，就得先拿到"可变"的所有权
// ----------------------------------------------------------------------------
// 题目类型：test（让 #[test] 测试通过就算过关）
// 课件位置：第 2 章 · 2.3.1 所有权随函数传参移动；2.3.2 修改需要 mut
// 难度：★★☆☆☆
// 前置知识：变量与 let、mut、函数参数与返回值、Vec 的 push（参考 vecs1、vecs2）
// 本题地位：move_semantics 系列第 1 题，先认识"所有权会搬家"和"改东西要 mut"
// ============================================================================
//
// 【题目要求】
// 原题在 `fill_vec` 里对 vec 调用 push(88)，但编译不过。
// 让测试通过：补上让 vec 能"被修改"所需要的那个关键字。
//
// 原题代码（未完成，仅供对照）：
//     #[test]
//     fn main() {
//         let vec0 = vec![22, 44, 66];
//         let vec1 = fill_vec(vec0);
//         assert_eq!(vec1, vec![22, 44, 66, 88]);
//     }
//
//     fn fill_vec(vec: Vec<i32>) -> Vec<i32> {
//         let vec = vec;          // ← 这里重新绑定，结果变成了"不可变"
//         vec.push(88);           // ← 报错
//         vec
//     }
//
// 编译报错：
//     error[E0596]: cannot borrow `vec` as mutable, as it is not declared as mutable
//     （不能把 vec 当成可变的来借用，因为它没有被声明为 mut）
//
// 【解题思路】
// 1. 参数 `vec: Vec<i32>` 本身是一个"不可变的变量绑定"，
//    就像 `let vec = ...;` 一样，默认不允许修改。
// 2. 原题又写了一句 `let vec = vec;`，这叫"重新绑定"（变量遮蔽），
//    新绑定的 vec 依然是**不可变**的，所以 push 仍然被拒绝。
// 3. 把这一行改成 `let mut vec = vec;`，明确告诉编译器"我要改它"。
// 4. 也可以把 mut 写在参数上：`fn fill_vec(mut vec: Vec<i32>)`，
//    效果等价，改法更短（本题答案采用前一种，和原题代码只差一个 mut）。
//
// ============================================================================
//                              知 识 铺 垫
// ============================================================================
//
// ● 所有权（ownership）是什么？
//   每个值都有一张"借书证"，上面写着"这本书归谁"。
//   证在谁手里，谁就负责在离开作用域时把书还掉（释放内存）。
//   Rust 规定：一本书同一时刻只能有一张借书证（一个所有者）。
//   这就是"所有权"：值的所有者唯一，所有者一死，值立刻被回收。
//
// ● 什么是"移动（move）"？
//   当把一个 Vec 传给函数时，借书证被"过户"给了函数里的参数。
//   过户之后，原来的变量就失效了：
//       let vec0 = vec![1, 2, 3];
//       let vec1 = fill_vec(vec0);   // vec0 的证过户走了
//       // 这里再用 vec0 就会报错：borrow of moved value
//   本题的测试在传完之后不再使用 vec0，所以看不出问题；
//   下一题 move_semantics2 正是要考"传完还想用"的情况。
//
// ● 为什么 Vec 会被"移动"，而 i32 不会？
//   i32 这种大小固定、复制便宜的简单类型实现了 Copy，传参时是"复印一份"；
//   Vec 里存着"堆上的数据 + 长度 + 容量"，复制一份会导致两块内存指向同一份堆数据，
//   等到释放时就会"同一块内存释放两次"，所以 Rust 干脆按"过户"处理。
//   可以用一个比方：i32 是"一张写着数字的便利贴"（复印即可），
//   Vec 是"一串仓库钥匙"（只能给一个人，不能复制）。
//
// ● mut 到底是什么？
//   它不是"这个变量永远是常量"，而是"允许通过这个变量修改它绑定的值"。
//   let x = 5;      → 不能改
//   let mut x = 5;  → 可以 x = 6;
//   注意：mut 只管"这一个绑定"，不改变值本身的所有权归属。
//
// ● 变量遮蔽（shadowing）
//   `let vec = vec;` 用新变量覆盖了同名的旧变量，旧变量从此看不见。
//   Rust 允许同名重复绑定，这在需要"换类型"或"换可变性"时很方便。
//   本题正是要在遮蔽时加上 mut，否则遮蔽出来的新绑定仍然不可变。
//
// ● #[test] fn main() 是什么写法？
//   本题的入口函数既叫 main，又被 #[test] 标注。
//   普通 rustc 编译时不把它当 main（会报"找不到 main"），
//   所以必须用 rustc --test 编译，用测试框架运行它。
//
// ============================================================================
//                              参 考 答 案
// ============================================================================

#[test]
fn main() {
    // 创建一个 Vec<i32>，内容是 [22, 44, 66]，所有权归 vec0
    let vec0 = vec![22, 44, 66];

    // 把 vec0 传进函数：所有权"过户"给 fill_vec 的参数 vec
    // 从这一行之后，main 里就不能再用 vec0 了（本题也确实没再用）
    let vec1 = fill_vec(vec0);

    // 断言：vec1 应该是 [22, 44, 66, 88]
    assert_eq!(vec1, vec![22, 44, 66, 88]);
}

fn fill_vec(vec: Vec<i32>) -> Vec<i32> {
    // 重新绑定（变量遮蔽）：把传进来的 vec 再绑定成一个新的 vec
    // 关键是加上 mut —— 只有 mut 绑定才允许调用 push
    // 这一步不复制数据，仍然是同一个 Vec，只是"换了个可写的名字"
    let mut vec = vec;

    // push(88)：在末尾追加一个元素，长度从 3 变 4
    // push 需要 &mut self，所以 vec 必须是可变绑定，这就是上面加 mut 的原因
    vec.push(88);

    // 最后一行不加分号：把 vec 的所有权交还给调用者
    vec
}

// ============================================================================
//                            逐 行 解 析
// ============================================================================
//
// let vec0 = vec![22, 44, 66];
//   └─ 创建 Vec，vec0 是唯一的所有者；数据在堆上，vec0 自己（指针+长度+容量）在栈上
//
// let vec1 = fill_vec(vec0);
//   └─ 实参 vec0 被"移动"进形参 vec；返回的 Vec 被移动给 vec1
//      整个过程中数据没有被复制，只是"所有权换了个名字"
//
// fn fill_vec(vec: Vec<i32>) -> Vec<i32>
//   └─ 参数 vec 默认不可变；返回类型 Vec<i32> 说明要把 Vec 交回去
//
// let mut vec = vec;
//   └─ 变量遮蔽：新 vec 覆盖旧 vec，并且允许修改（mut）
//
// vec.push(88);
//   └─ 需要 &mut vec；因为上一步是 mut 绑定，这里合法
//
// vec
//   └─ 表达式作为返回值，所有权移出函数
//
// ============================================================================
//                    为什么原来的写法一定编译不过？
// ============================================================================
//
// 原题 `fn fill_vec(vec: Vec<i32>)` 里的 vec，等价于 `let vec = ...;`，
// 是不可变绑定；紧接着 `let vec = vec;` 又遮蔽出一个新的不可变绑定。
// push 的签名是 `fn push(&mut self, value: T)`，它要的是"可变借用"，
// 而不可变绑定根本无法提供 &mut，于是编译器报 E0596。
//
// 这体现的是 Rust 的一贯思路：
//   "能不能改"这件事必须白纸黑字写出来，编译器不会替你猜。
// 对比 C：函数参数 `int *p` 你随时可以改，靠自觉；
// 对比 Java：对象引用天然可改，靠文档。Rust 靠类型系统和 mut 关键字。
//
// ============================================================================
//                          常 见 错 误 与 提 示
// ============================================================================
//
// 1. 只在 main 里加 mut（改错地方）：
//        let mut vec0 = vec![22, 44, 66];
//    → 仍然报 E0596，因为报错的是函数里的 vec，不是 main 里的 vec0。
//
// 2. 把 mut 加在返回类型上：fn fill_vec(vec: Vec<i32>) -> mut Vec<i32>
//    → error: mut 只能用在变量绑定/引用/指针上，不能修饰类型。
//
// 3. 删掉 `let vec = vec;` 这一行但不给参数加 mut：
//        fn fill_vec(vec: Vec<i32>) { vec.push(88); }
//    → 还是 E0596。要么 `fn fill_vec(mut vec: ...)`，要么 `let mut vec = vec;`。
//
// 4. 把 vec 改成 clone 传参：
//        let vec1 = fill_vec(vec0.clone());
//    能过，但那是下一题的做法；本题没有用到 vec0，没必要复制。
//
// 5. 不加 --test 编译：
//        rustc move_semantics1.rs
//    → error[E0601]: `main` function not found（入口被 #[test] 标注了）
//
// ============================================================================
//                          小 结
// ============================================================================
//
// 本题你需要记住：
//   1. 传 Vec 给函数 = 所有权移动，原变量随即失效；
//   2. 变量绑定默认不可变，想改必须 mut；
//   3. mut 是"对这一个绑定"的许可，不是对类型本身的修改；
//   4. `let vec = vec;` 是变量遮蔽，遮蔽时也要写 mut 才能改。
//
// 一句话记忆：**所有权会搬家，搬家后原名字作废；想动手改，先写 mut。**
//
// 下一题（move_semantics2）会追问：如果传完还想继续用原来的 vec0，怎么办？
