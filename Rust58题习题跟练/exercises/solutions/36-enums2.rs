// ============================================================================
// 第 36 题 · enums2 —— 让枚举变体“携带数据”
// ----------------------------------------------------------------------------
// 题目类型：compile（把代码改到能编译通过就算过关）
// 课件位置：第 3 章 · 3.4 枚举（3.4.2 携带数据的变体：结构体式 / 元组式 / 无数据）
// 难度：★★★☆☆
// 前置知识：enums1（枚举与单元变体）、structs1（结构体字段）、strings1（String 基础）
// ============================================================================
//
// 【题目要求】
// 补全 enum Message，使 main 里出现的四种写法都能成立：
//   Message::Move { x: 10, y: 30 }        —— 带“字段名”的数据
//   Message::Echo(String::from("..."))    —— 带一个 String
//   Message::ChangeColor(200, 255, 255)   —— 带三个数字
//   Message::Quit                         —— 不带数据
// 同时 impl Message 里的 call 方法不能改。
//
// 原题代码（未完成，仅供对照）：
//     #[derive(Debug)]
//     enum Message {
//         // TODO: define the different variants used below
//     }
//
//     impl Message {
//         fn call(&self) {
//             println!("{:?}", self);
//         }
//     }
//
//     fn main() {
//         let messages = [
//             Message::Move { x: 10, y: 30 },
//             Message::Echo(String::from("hello world")),
//             Message::ChangeColor(200, 255, 255),
//             Message::Quit,
//         ];
//
//         for message in &messages {
//             message.call();
//         }
//     }
//
// 【解题思路】
// 1. 从 main 的“构造方式”反推变体长什么样，这是做枚举题最稳的办法：
//      - `Move { x: 10, y: 30 }`：花括号里写了字段名 → 结构体式变体
//            Move { x: i32, y: i32 }
//      - `Echo(String::from("hello world"))`：圆括号里一个 String → 元组式变体
//            Echo(String)
//      - `ChangeColor(200, 255, 255)`：圆括号里三个数字 → 元组式变体
//            ChangeColor(u8, u8, u8)
//      - `Quit`：后面什么都没有 → 单元变体
//            Quit
// 2. 四个变体之间用逗号隔开，整体放进 `enum Message { ... }`。
// 3. 类型怎么定？x、y 用 i32（普通整数）；颜色三个分量用 u8（0~255 正好是颜色范围）。
// 4. 不要动 main 和 impl：题目只让你补 enum 定义。
//
// ============================================================================
//                              知 识 铺 垫
// ============================================================================
//
// ● 枚举变体可以“带东西”
//   上一题 enums1 的变体只是四个名字。但现实里的“消息”往往要带内容：
//   “移动”要带坐标，“回显”要带一段文字，“改颜色”要带 RGB 三个分量。
//   Rust 允许每个变体自带不同数量、不同类型的数据，这叫“携带数据的变体”。
//   可以把它想成一张带附件的表单：先勾选“要办哪件事”，再填这件事需要的材料。
//
// ● 三种变体形式（本题三种都会出现）
//   1. 单元变体（unit variant）—— 不带数据
//          Quit
//   2. 元组变体（tuple variant）—— 带若干个“没有名字”的数据
//          Echo(String)
//          ChangeColor(u8, u8, u8)
//      构造：Message::ChangeColor(200, 255, 255)
//      取数据：只能靠 match 按位置解构（enums3 会讲）
//   3. 结构体变体（struct variant）—— 带若干个“有名字”的数据
//          Move { x: i32, y: i32 }
//      构造：Message::Move { x: 10, y: 30 }
//      取数据：match 时写 Message::Move { x, y } 或 Message::Move { x: a, y: b }
//
// ● 变体名其实就是“构造函数”
//   `Message::Echo` 不是普通常量，它像一个函数：给它一个 String，它就还你一个
//   Message 类型的值。所以 `Message::Echo(String::from("hi"))` 是合法的表达式。
//   单元变体 `Message::Quit` 则像“已经做好的成品”，不用再调用。
//
// ● 为什么一个数组能同时装四种不同的消息？
//   数组要求所有元素“类型相同”。这里四个元素的类型都是 Message，只是变体不同。
//   一个 Message 值在内存里 = 一个标签（记录当前是哪个变体）+ 该变体需要的数据。
//   enum 的大小取“最大的那个变体”，所以四个元素能整齐地放进同一个数组。
//
// ● 方法 `fn call(&self)`
//   `impl Message { fn call(&self) { ... } }` 给枚举加方法。
//   `&self` 表示“借用当前这个值来读一读”，不夺走所有权。
//   调用时写 `值.call()`，Rust 会自动把 `&值` 传进去。
//
// ● `for message in &messages`
//   遍历数组的“引用”，每次拿到的 message 类型是 `&Message`（借用，不复制）。
//   `message.call()` 里 call 需要 `&self`，而 message 已经是 &Message，
//   编译器会自动解引用，等价于 `Message::call(message)`。
//
// ============================================================================
//                              参 考 答 案
// ============================================================================

#[derive(Debug)]
enum Message {
    // 结构体式变体：花括号 + 字段名 + 字段类型
    Move { x: i32, y: i32 },

    // 元组式变体：圆括号 + 类型列表，字段没有名字
    Echo(String),

    // 元组式变体：三个 u8，正好表示 R、G、B 三个颜色分量（0~255）
    ChangeColor(u8, u8, u8),

    // 单元变体：不带数据
    Quit,
}

impl Message {
    // &self：借用当前的 Message 值，只读不改
    fn call(&self) {
        // self 的类型是 &Message；Debug 对 &T 也能打印，会自动打印 T 的内容
        println!("{:?}", self);
    }
}

fn main() {
    // 一个数组装四条消息：元素类型统一是 Message，变体各不相同
    let messages = [
        // 结构体式变体：必须写字段名 x、y
        Message::Move { x: 10, y: 30 },
        // 元组式变体：String 被“移动”进枚举里
        Message::Echo(String::from("hello world")),
        // 元组式变体：三个 u8 字面量
        Message::ChangeColor(200, 255, 255),
        // 单元变体：直接写名字
        Message::Quit,
    ];

    // 用 &messages 借用数组，避免把数组移动走
    for message in &messages {
        // message 是 &Message；调用 call(&self) 时自动解引用
        message.call();
    }
}

// ============================================================================
//                            详 细 解 析
// ============================================================================
//
// 1）每种变体的 Debug 输出长什么样？
//    结构体式：Move { x: 10, y: 30 }
//    元组式  ：Echo("hello world")      ← String 的 Debug 会带双引号
//    元组式  ：ChangeColor(200, 255, 255)
//    单元式  ：Quit
//    这四行就是程序的运行结果。
//
// 2）ChangeColor 为什么用 u8 而不是 i32？
//    u8 的范围是 0~255，正好覆盖一个颜色通道。写 200、255、255 都在范围内，
//    编译器会把这三个整数字面量推断成 u8。
//    如果写成 ChangeColor(300, 0, 0)，300 超出 u8 范围，会报：
//        error: literal out of range for `u8`
//    当然，用 i32 也能编译通过，但 u8 更贴合“颜色分量”的语义，也更省内存。
//
// 3）Echo(String) 里传 String 发生了什么？
//    String 拥有堆上的文字数据。把它放进枚举变体时，所有权从 String::from
//    的临时值“移动”进了 Message 里；之后这个 Message 就负责在销毁时释放那段内存。
//    如果先 `let s = String::from("hi"); Message::Echo(s);`，之后再用 s 就会报错，
//    因为 s 已经被移动走了（参考 move_semantics1、move_semantics2）。
//
// 4）为什么数组能装下不同大小的变体？
//    数组元素必须等长，而各变体携带的数据长度不同（String 是固定大小的“指针+长度+容量”，
//    ChangeColor 是 3 个字节）。enum 会按“最大变体”分配固定空间，再附一个标签。
//    所以每个 Message 元素占用的字节数相同，数组才能连续存放。
//
// 5）call 方法为什么写 &self 而不是 self？
//    写 self 会把消息“吃掉”（移动进方法），for 循环里就不好继续使用；
//    写 &self 只是借用，打印完原值还在。这就是“能借就别拿走”的原则。
//
// ============================================================================
//                          常 见 错 误 与 提 示
// ============================================================================
//
// 1. 把结构体式变体写成元组式：
//        Move(i32, i32)
//    → 构造处 `Message::Move { x: 10, y: 30 }` 报
//      error[E0559]: variant `Message::Move` has no field named `x`
//
// 2. 元组变体多写/少写类型：
//        ChangeColor(u8, u8)   // 但 main 给了三个值
//    → error[E0061]: this enum variant takes 2 arguments but 3 arguments were supplied
//
// 3. 结构体式变体漏字段：
//        Move { x: i32 }       // 但 main 里写了 y
//    → error[E0560]: variant `Message::Move` does not have a field named `y`
//
// 4. 颜色字面量超范围（300）：
//    → error: literal out of range for `u8`
//
// 5. 在变体定义里给字段写初值：
//        Move { x: 10, y: 30 }
//    → error: expected type, found `10`
//    （enum 定义里只能写类型，不能写值）
//
// 6. 修改了 main 或 impl Message：
//    题目只要求补 enum。改 main 可能让程序“编译过但行为不对”，
//    这种题请保持题面代码原样。
//
// 7. 忘记写 #[derive(Debug)]：
//    → error[E0277]: `Message` doesn't implement `Debug`
//
// 8. 编译时出现 `fields ... are never read` 警告：
//    这不是错误。编译器发现变体里的数据除了 Debug 之外从未被读取，
//    于是提醒你“这些字段好像没用上”。本题只打印、不解构，所以会出现。
//    到 enums3 用 match 把字段取出来使用后，这类警告自然消失。
//
// ============================================================================
//                          小 结
// ============================================================================
//
// 本题你需要记住：
//   1. 枚举变体可以携带数据，分为单元式、元组式、结构体式三种；
//   2. 结构体式用 `{ 字段: 类型 }`，构造时写字段名；
//   3. 元组式用 `(类型1, 类型2, ...)`，构造时按位置给值；
//   4. 变体名相当于构造函数，`Message::Echo(文本)` 会造出一个 Message；
//   5. enum 的大小由最大的变体决定，所以不同变体可以放进同一个数组；
//   6. 方法用 `&self` 借用，不会夺走值的所有权。
//
// 一句话记忆：**枚举的每个选项都可以自带“附件”，附件可以有名（结构体式）也可以无名（元组式）。**
//
