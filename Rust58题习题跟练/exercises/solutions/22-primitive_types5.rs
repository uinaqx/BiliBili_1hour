// ============================================================================
// 第 22 题 · primitive_types5 —— 用模式解构元组（let (name, age) = cat）
// ----------------------------------------------------------------------------
// 题目类型：compile（把代码补全到能编译通过就算过关）
// 课件位置：第 3 章 · 3.2 元组（元组的定义与解构）
// 难度：★★☆☆☆
// 前置知识：let 变量（variables1）、基本类型 char/bool（第 18、19 题）
// ============================================================================
//
// 【题目要求】
// 把 cat 这个元组“拆开”，让下面的 println! 能用上 name 和 age 两个变量。
// 原题代码（未完成，仅供对照）：
//     fn main() {
//         let cat = ("Furry McFurson", 3.5);
//         let /* your pattern here */ = cat;
//
//         println!("{} is {} years old.", name, age);
//     }
//
// 【解题思路】
// 1. cat 是一个**元组**：(名字, 年龄)。
//    第 0 个元素是 "Furry McFurson"（&str），第 1 个元素是 3.5（f64）。
// 2. 后面打印时用的是两个独立变量 name 和 age，说明要把元组“拆成两个变量”。
// 3. Rust 支持“解构（destructuring）”：在 let 左边写一个和数据结构形状
//    一样的**模式**，就能一次性把里面的值分别绑到变量上：
//        let (name, age) = cat;
// 4. 位置要对应：第 0 个给 name（字符串），第 1 个给 age（浮点数）。
//    顺序写反了类型就对不上，println! 时也会出问题。
//
// ============================================================================
//                              知 识 铺 垫
// ============================================================================
//
// ● 什么是元组（tuple）？
//     let cat = ("Furry McFurson", 3.5);
//   元组是把**若干个不同类型**的值打包在一起的小容器：
//     - 长度固定（不能增删元素）；
//     - 元素类型可以各不相同（这里一个是 &str，一个是 f64）；
//     - 用圆括号 ( ) 写，元素之间用逗号分隔。
//   它的类型写作 (T1, T2, ...)，本题 cat 的类型是 (&str, f64)。
//
// ● 元组 vs 数组
//     数组 [T; N]：所有元素类型相同，可以循环遍历；
//     元组 (T1, T2)：元素类型可以不同，靠“位置”区分，通常只有几个元素。
//   类比：数组像“一排同款矿泉水”，元组像“一份套餐（汉堡 + 可乐 + 薯条）”。
//
// ● 怎么取出元组里的值？两种方式
//     1) 解构：  let (name, age) = cat;        ← 本题用这个
//     2) 下标：  cat.0、cat.1                    ← 下一题 primitive_types6 用这个
//   注意元组的下标是 **点号 + 数字**，不是 cat[0]。
//
// ● 什么是“模式（pattern）”？
//   模式是“描述数据形状的写法”，let 左边、match 分支、函数参数里都能用。
//     let (name, age) = cat;
//   左边 (name, age) 就是一个元组模式：它要求右边是一个二元组，
//   然后把第 0 个元素绑给 name，第 1 个绑给 age。
//   这和数学里“设 (x, y) = (1, 2)”是一个意思。
//
// ● 解构会不会“移动”数据？
//   会按元素类型决定：&str 是 Copy（复制的是引用），f64 也是 Copy，
//   所以这里的解构只是“复制一份”，cat 本身仍然可用。
//   如果元组里有 String（非 Copy），解构时所有权会被移动出来，
//   之后就不能再用 cat 了 —— 这个细节等学了所有权（第 2.3 节）再回顾。
//
// ● 类型推断
//     let (name, age) = cat;
//   不需要写类型，编译器从 cat 的类型 (&str, f64) 推断出
//   name: &str、age: f64。
//
// ● println! 的 {} 能打印 f64 吗？
//   能。f64 实现了 Display（面向人的显示），3.5 会原样打印成 "3.5"。
//   注意：整数和浮点数不能用 {} 以外的格式乱配，比如 {:d} 只给整数用。
//
// ● 常见坑：变量名必须和后面用的一致
//   后面 println! 里写的是 name 和 age，所以解构时也必须起这两个名字。
//
// ============================================================================
//                              参 考 答 案
// ============================================================================

fn main() {
    // 一个二元组：第 0 个元素是名字（&str），第 1 个元素是年龄（f64）
    // 类型是 (&str, f64)，长度固定为 2
    let cat = ("Furry McFurson", 3.5);

    // 解构（destructuring）：
    //   (name, age) 是一个“元组模式”，形状必须和 cat 一致（两个元素）
    //   位置一一对应：第 0 个 → name，第 1 个 → age
    //   编译器自动推断 name: &str、age: f64
    let (name, age) = cat;

    // 现在 name、age 就是两个普通变量，可以直接用
    // {} 是占位符，按顺序被后面的参数替换：
    //   第 1 个 {} ← name（"Furry McFurson"）
    //   第 2 个 {} ← age （3.5）
    println!("{} is {} years old.", name, age);
}

// ============================================================================
//                            逐 行 解 析
// ============================================================================
//
// let cat = ("Furry McFurson", 3.5);
//   ├─ let     ：声明变量
//   ├─ cat     ：变量名
//   ├─ ( ... ) ：元组字面量
//   │    ├─ "Furry McFurson" ：&str（字符串字面量）
//   │    └─ 3.5              ：f64（浮点数默认类型）
//   └─ ;       ：语句结束
//
// let (name, age) = cat;
//   ├─ let         ：声明变量（一次声明两个！）
//   ├─ (name, age) ：元组模式，两个“坑位”
//   ├─ = cat       ：右边必须是一个二元组
//   └─ ;           ：语句结束
//   效果等价于：
//        let name = cat.0;   // "Furry McFurson"
//        let age  = cat.1;   // 3.5
//
// println!("{} is {} years old.", name, age);
//   └─ 打印：Furry McFurson is 3.5 years old.
//
// ============================================================================
//                          常 见 错 误 与 提 示
// ============================================================================
//
// 1. 解构时变量个数不对：
//        let (name,) = cat;
//    → error[E0308]: mismatched types
//      expected a tuple with 2 elements, found one with 1 element
//
// 2. 用了方括号（把它当数组）：
//        let [name, age] = cat;
//    → error[E0308]: mismatched types
//      expected an array, found a tuple
//    （元组只能用圆括号，数组才用方括号；不过 Rust 现在支持“元组也是数组模式”的
//      某些场景，但这里形状仍不匹配，不要背错）
//
// 3. 变量名和后面用的不一致：
//        let (n, a) = cat;
//        println!("{} is {} years old.", name, age);
//    → error[E0425]: cannot find value `name` in this scope
//
// 4. 写成 cat[0]：
//        let name = cat[0];
//    → error[E0608]: cannot index into a value of type `(&str, f64)`
//    （元组下标是 cat.0，不是 cat[0]）
//
// 5. 忘记分号：
//        let (name, age) = cat
//    → error: expected `;`, found `println`
//
// 6. 顺序写反并强行打印：
//        let (age, name) = cat;
//        println!("{} is {} years old.", name, age);
//    → 编译能通过（println! 不关心参数类型），但输出会变成
//      "3.5 is Furry McFurson years old." —— 逻辑错了，编译器不会提醒你。
//
// ============================================================================
//                          小 结
// ============================================================================
//
// 本题你需要记住：
//   1. 元组 (T1, T2, ...)：长度固定、元素类型可不同、用圆括号；
//   2. 解构写法 `let (a, b) = 元组;` 可以一次性拆开并命名；
//   3. 位置的顺序必须和元组一致；
//   4. 另一种取值方式是下标 cat.0、cat.1（下一题练）。
//
// 一句话记忆：**左边写形状、右边给数据，形状对上就“自动分配”给每个名字。**
//
