// ============================================================================
// 第 47 题 · options3 —— match 拿走了盒子里的东西（部分移动）
// ----------------------------------------------------------------------------
// 题目类型：compile（把代码改到能编译通过就算过关）
// 课件位置：第 4 章 · 4.3 match 模式绑定；第 2 章 · 2.3.1 所有权（移动）
// 难度：★★★☆☆
// 前置知识：Option（第 45、46 题）、match、所有权与借用（第 30 题 move_semantics5）
// ============================================================================
//
// 【题目要求】
// 让代码编译通过。约束是：**不能删除最后一行 `y;`**，
// 也就是说匹配完之后 y 还必须“还活着、还能用”。
//
// 原题代码（未完成，仅供对照）：
//     struct Point { x: i32, y: i32 }
//
//     fn main() {
//         let y: Option<Point> = Some(Point { x: 100, y: 200 });
//
//         match y {                                  // ← 这里把 y 移动进去了
//             Some(p) => println!("Co-ordinates are {},{} ", p.x, p.y),
//             _ => panic!("no match!"),
//         }
//         y;   // Fix without deleting this line.     // ← error[E0382]
//     }
//
// 编译器会报：
//     error[E0382]: use of moved value: `y`
//     note: `Option<Point>` doesn't implement `Copy`, so the value was moved
//
// 【解题思路】
// 1. 问题根源：`match y` 是按**值**匹配的。
//    `Some(p)` 这个模式要把 Point 从 Some 里“掏出来”交给 p，
//    于是整个 y 的所有权被移进了 match，match 结束后 y 就作废了。
// 2. 可是最后一行还要用 y，这就产生了“用了已经被移走的值”的错误。
// 3. 解法：让 match 只**借用** y，不拿走它 —— 写成 `match &y`。
//    这样被匹配的是 `&Option<Point>`，模式里的 p 自动变成 `&Point`（只读引用），
//    打印 p.x / p.y 依然合法（只是读，不需要所有权），y 本身毫发无伤。
// 4. 只改一个字符（加 &），其他一行不动，符合题目约束。
//
// ============================================================================
//                              知 识 铺 垫
// ============================================================================
//
// ● 先用一句话复习所有权
//   Rust 里每个值都有唯一的所有者。所有者可以把值“移动（move）”给别人，
//   移动之后原来的变量就不能再用了（编译器会拦住）。
//   例：
//       let a = String::from("hi");
//       let b = a;        // 所有权从 a 移到 b
//       println!("{}", a); // error[E0382]: borrow of moved value: `a`
//   为什么这么严？因为 String 的数据在堆上，如果 a、b 都能用，
//   就会两次释放同一块内存（double free）。Rust 用“移动”在编译期杜绝它。
//
// ● 什么是“部分移动（partial move）”？
//   有时候整个值没被移走，只是它的一部分被移走了。
//   本题里 y 是 `Option<Point>`，`Some(p)` 把里面的 Point 移出来给 p，
//   于是 y 处于“半空”状态 —— 这就是部分移动。
//   对 Option 来说，部分移动后整个 y 都不能再当作完整值使用（编译器保守处理），
//   所以最后一行 `y;` 报 E0382。
//
// ● 为什么会移动，而不是复制？
//   `i32` 这类简单类型实现了 Copy（可以按位复制，没有堆内存），
//   但 `Point { x: i32, y: i32 }` 虽然字段都是 Copy，
//   **结构体默认不会自动实现 Copy**（需要手动写 #[derive(Copy, Clone)]）。
//   而 `Option<Point>` 只有在 Point: Copy 时才是 Copy。
//   本题 Point 没有 derive，所以 y 不是 Copy，match 就变成了移动。
//
// ● 借用 & 的力量
//   不想交出所有权，就“借”：
//       &y       不可变引用（只读借用），类型 &Option<Point>
//       &mut y   可变引用（可读可写借用）
//   借来的东西不能带走，但可以看、可以读字段。
//
// ● “match 人体工学（match ergonomics）”
//   当你 match 一个引用 `&Option<Point>` 时，Rust 允许你直接写 `Some(p)`，
//   编译器会自动把 p 推断成 `&Point`（而不是要求你写 `&Some(ref p)`）。
//   所以 `p.x` 完全合法：通过引用访问字段，i32 会直接复制出来。
//   这个特性从 Rust 2018 起生效，让代码干净很多。
//
// ● `_ => panic!(...)` 里的 `_` 是什么？
//   通配模式，匹配“其他所有情况”（这里就是 None）。
//   panic! 会立刻终止程序并打印错误信息。本题 y 是 Some，所以走不到这个分支。
//
// ● 单独的 `y;` 这一行有什么意义？
//   它是一条“表达式语句”：把 y 求值后立刻丢弃（drop）。
//   它本身没什么用处，题目只是拿它当“试纸”——证明 match 之后 y 仍然有效。
//   编译器可能给一个 `path statement with no effect` 之类的警告，但警告不影响编译通过。
//
// ============================================================================
//                              参 考 答 案
// ============================================================================

// 定义一个普通结构体 Point，两个字段都是 i32（32 位有符号整数）
// 注意：这里没有 #[derive(Copy, Clone)]，所以 Point 不是 Copy 类型
struct Point {
    x: i32,
    y: i32,
}

fn main() {
    // y 的类型是 Option<Point>，值是“装着 Point{x:100,y:200} 的盒子”
    let y: Option<Point> = Some(Point { x: 100, y: 200 });

    // 关键改动：match &y（原来是 match y）
    //   &y 的类型是 &Option<Point>，只是借用，不夺走所有权
    //   于是模式 Some(p) 里的 p 自动被推断为 &Point（match 人体工学）
    //   p.x / p.y 通过引用读取字段，i32 是 Copy，直接复制出值来打印
    match &y {
        Some(p) => println!("Co-ordinates are {},{} ", p.x, p.y),
        // `_` 覆盖 None 的情况；真遇到 None 就 panic（本题不会走到）
        _ => panic!("no match!"),
    }

    // 因为上面只是借用，y 的所有权一直在自己手里，
    // 所以这一行仍然合法（题目要求不能删掉它）
    y;
}

// ============================================================================
//                            详 细 解 析
// ============================================================================
//
// 1）`match y` 到底“移动”了什么？
//    match 会把被匹配的值放到一个临时位置（按值匹配时就是移动进 match）。
//    模式 `Some(p)` 又要求把 Point 绑定到 p 上，p 要拿到 Point 的所有权，
//    所以 Point 从 y 里被搬走了 —— 这就是部分移动。
//    移动之后，y 只剩下一个“壳”，Rust 不允许再把 y 当成完整值使用，
//    哪怕你只是想把它丢掉（`y;` 也是一次完整值的使用）。
//
// 2）改成 `match &y` 之后，类型发生了什么变化？
//       被匹配的值：&Option<Point>
//       模式       ：Some(p)   →  p: &Point
//       打印 p.x   ：等价于 (*p).x，读一个 i32（Copy），得到 100
//   整个过程中没有任何数据被搬走，只是“看了一眼”。
//
// 3）p.x 为什么能直接写，不用 (*p).x？
//    Rust 的 `.` 运算符会自动解引用：p.x 会自动展开成 (*(p)).x。
//    这叫“自动解引用（auto-deref）”，对你的手写代码是透明的。
//
// 4）还有哪些改法？（都能过，但不如 &y 干净）
//    a. 加 derive，让 Point 变成可复制的类型：
//           #[derive(Copy, Clone)]
//           struct Point { x: i32, y: i32 }
//       这样 match y 只是复制，y 仍然有效。但题目说“只改一处”，
//       而且这没教到借用，不推荐。
//    b. 改成 `match y.clone()`：复制一份去匹配，y 保留。缺点是多一次复制。
//    c. 只借用需要的字段：
//           match y.as_ref() { Some(p) => ..., _ => ... }
//       `Option::as_ref()` 把 Option<T> 变成 Option<&T>，效果和 &y 类似，
//       是标准库推荐写法之一。
//    d. 如果不需要结构体，只打印两个坐标：
//           if let Some(p) = &y { println!("{},{}", p.x, p.y); }
//       if let 同样支持借用模式。
//
// 5）为什么 `_ => panic!()` 不会报“不可达代码”？
//    match &y 依然可能遇到 None（类型上允许），编译器不知道 y 一定是 Some，
//    所以要保留这个分支。只有当你写成 `let y = Some(...)` 且编译器能做常量传播时
//    才可能出现 unreachable 警告，但本题不会。
//
// 6）如果把最后一行改成 `y.x;` 会怎样？
//    y 是 Option<Point>，不是 Point，没有 x 字段，报错。
//    要写 y.as_ref().unwrap().x 或 match 取出来才行。
//
// ============================================================================
//                          常 见 错 误 与 提 示
// ============================================================================
//
// 1. 直接把最后一行删掉（题目禁止）：
//    → 能编译，但违反题目约束，rustlings 仍会判过 —— 但你什么也没学到。
//
// 2. 改成 `match &y` 后仍然写 `Some(p) => println!("{}", p)`：
//    → error[E0277]: `Point` doesn't implement `Display`
//      （Point 没有实现 Display，只能打印它的字段）
//
// 3. 写成 `match y { Some(ref p) => ... }`：
//    → 也能过（老式写法，借用绑定）。但 match y 本身已经把 y 移动进 match 了，
//      移动之后 `y;` 依然报 E0382 —— 所以这种改法不解决问题。
//
// 4. 把 `y;` 改成 `&y;`：
//    → 能编译，但这属于“改题目要求的那一行”，不符合题意。
//
// 5. 给 Point 加 #[derive(Copy, Clone)] 后忘了 Option<Point> 也是 Copy：
//    其实只要 Point: Copy，Option<Point> 自动是 Copy，能过；但这是绕过问题，
//    没有练到“借用”这个核心知识。
//
// 6. 反复出现的老问题：`Some(p)` 里 p 是引用还是值？
//    看被匹配值的类型：
//        match option_value      → p: Point   （拿走所有权）
//        match &option_value     → p: &Point  （借用）
//        match option_value.as_ref() → p: &Point（借用，等价）
//
// ============================================================================
//                          小 结
// ============================================================================
//
// 本题你需要记住：
//   1. `match 值` 默认按值匹配，会把值（或值的一部分）移动进去；
//   2. 移动之后原变量失效，再用就报 error[E0382]；
//   3. `match &值` 只借用不移动，模式里的绑定自动变成引用；
//   4. 只读打印字段时优先用借用，别轻易交出所有权。
//
// 一句话记忆：**match 一个值 = 把东西搬进 match；match &一个值 = 只是借来看一眼。**
//
