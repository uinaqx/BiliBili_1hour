// 下面这段是原题自带的测试，一个字都没改。
// #[cfg(test)] 表示"只在测试模式下编译这个模块"；
// mod tests 是一个模块，use super::*; 把外面的 vec_loop / vec_map 引进来。

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_vec_loop() {
        // (1..) 是 1,2,3,... 的无限序列，filter 只留偶数，take(5) 取前 5 个，
        // collect 收集成 Vec<i32> → v = [2, 4, 6, 8, 10]
        let v: Vec<i32> = (1..).filter(|x| x % 2 == 0).take(5).collect();
        // clone() 复制一份给 vec_loop，这样测试里还能继续用 v
        let ans = vec_loop(v.clone());

        assert_eq!(ans, v.iter().map(|x| x * 2).collect::<Vec<i32>>());
    }

    #[test]
    fn test_vec_map() {
        let v: Vec<i32> = (1..).filter(|x| x % 2 == 0).take(5).collect();
        // 传 &v：只借用，不交出所有权
        let ans = vec_map(&v);

        assert_eq!(ans, v.iter().map(|x| x * 2).collect::<Vec<i32>>());
    }
}

// ============================================================================
//                            详 细 解 析
// ============================================================================
//
// 1）为什么第一空是 `*element *= 2;` 而不是 `element *= 2;`？
//    element 的类型是 &mut i32，它只是"地址"，不是整数本身。
//    写 element *= 2 会试图把"地址"乘 2，编译器直接报类型错误。
//    加 * 表示"地址指向的那个整数"，才能做乘法。
//
// 2）为什么第二空是 `element * 2` 而不是 `*element *= 2;`？
//    vec_map 的参数是 &Vec<i32>，是"只读借用"，根本没有修改权限；
//    而且 map 的设计就是"你给我一个新值，我不碰旧值"。
//    所以这里只做"读 + 算 + 返回"，风格上更函数式。
//
// 3）element * 2 里，element 是 &i32，为什么可以直接乘？
//    Rust 标准库为引用实现了大量运算符（impl Mul<i32> for &i32 等），
//    所以 &i32 * i32 会自动取用引用指向的值。你写 *element * 2 也对。
//
// 4）collect() 为什么不用写类型？
//    函数返回类型是 Vec<i32>，编译器据此推断 collect::<Vec<i32>>()。
//    如果把返回类型改成别的，这里就会跟着变——这叫"类型推断"。
//
// 5）两种写法结果一样，区别在哪？
//    vec_loop：拿到所有权，原地改，省内存，但会"消耗"传进来的 Vec；
//    vec_map ：只借用，产生新 Vec，原数据保持不动，更安全、更易组合。
//    实际开发中，能不改原数据就不改，map 风格更常用。
//
// 6）运行方式（本题是测试题，必须加 --test）：
//    rustc --edition 2021 --test vecs2.rs -o vecs2.exe
//    .\vecs2.exe
//
// ============================================================================
//                          常 见 错 误 与 提 示
// ============================================================================
//
// 1. 第一空写成 element *= 2;
//    → error[E0368]: binary assignment operation `*=` cannot be applied to type `&mut i32`
//
// 2. 第一空写成 *element = element * 2;
//    → 类型不匹配（右边是引用，左边是 i32），应写 *element = *element * 2;
//
// 3. 第二空写成 *element *= 2;（想改只读数据）
//    → error[E0594]: cannot assign to `*element`, which is behind a `&` reference
//
// 4. 第二空忘了返回新值，光写一句 `element * 2;`（带分号）
//    → 闭包返回 ()，collect 收集出一堆 ()，类型对不上，报 E0277。
//    记住：不加分号的表达式才是返回值。
//
// 5. 把 vec_loop 参数里的 mut 删掉：
//        fn vec_loop(v: Vec<i32>) -> Vec<i32> { for e in v.iter_mut() {...} }
//    → error[E0596]: cannot borrow `v` as mutable, as it is not declared as mutable
//
// 6. 忘记 --test：
//        rustc vecs2.rs
//    → error[E0601]: `main` function not found in crate（本题没有 main）
//
// ============================================================================
//                          小 结
// ============================================================================
//
// 本题你需要记住：
//   1. Vec<T> 是可增长的动态数组，vec![...] 用来创建；
//   2. iter() 借出 &T（只读），iter_mut() 借出 &mut T（可改）；
//   3. 通过引用改值要解引用：*p = ...；
//   4. map + collect 可以"不改原数据、造出新 Vec"；
//   5. 可变借用要求变量本身是 mut。
//
// 一句话记忆：**要改就 iter_mut 配 *element；不改就 iter 配 map + collect。**
//
