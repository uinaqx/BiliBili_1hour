// ============================================================================
// 第 25 题 · vecs2 —— 两种方式把 Vec 里每个元素变成 2 倍
// ----------------------------------------------------------------------------
// 题目类型：test（让两个 #[test] 测试都通过就算过关）
// 课件位置：第 6 章 · 6.1.1 动态数组 Vec（遍历并修改元素）
// 难度：★★★☆☆
// 前置知识：变量与 mut、函数的参数与返回值、for 循环、Vec 的创建（参考 vecs1）
// 扩展说明：第二种写法用到"迭代器 + 闭包"，课件没讲，本文件会从零讲明白
// ============================================================================
//
// 【题目要求】
// 给一个装偶数的 Vec，把每个元素乘以 2，但要求用两种不同风格：
//   1. vec_loop：用 for 循环"原地修改" v 里的每个元素，最后把 v 返回；
//   2. vec_map：不修改 v，而是"造"一个新的 Vec 返回（用迭代器 map）。
// 两处待填的占位符都要补上（原题里写作三个问号）。
//
// 原题代码（未完成，仅供对照）：
//     fn vec_loop(mut v: Vec<i32>) -> Vec<i32> {
//         for element in v.iter_mut() {
//             // TODO: 把每个元素乘以 2
//             （待填：一行语句）
//         }
//         // 走到这里时，v 应该等于 [4, 8, 12, 16, 20]
//         v
//     }
//
//     fn vec_map(v: &Vec<i32>) -> Vec<i32> {
//         v.iter().map(|element| {
//             // TODO: 和上面做一样的事，但不要去改 Vec，
//             //       而是直接返回新的数字
//             （待填：一个表达式）
//         }).collect()
//     }
//
// 注意：vec_map 的参数是 `&Vec<i32>`（只借来看），
// 所以题目要求它"只读不写"，只能造新的 Vec 出来。
//
// 【解题思路】
// 1. v.iter_mut() 会依次"借出"每个元素的可变引用，element 的类型是 &mut i32。
//    引用不是值本身，想改它指向的那个数，必须"解引用"：*element。
//    于是第一空写：*element *= 2;
// 2. v.iter() 依次"借出"每个元素的不可变引用，element 的类型是 &i32。
//    既然不能改原数据，就把新值"作为结果交出去"：
//        element * 2
//    map 会把这些新值一个个收集起来，最后由 collect() 汇总成新的 Vec<i32>。
//
// ============================================================================
//                              知 识 铺 垫
// ============================================================================
//
// ● Vec 是什么？
//   Vec<i32> 是"可以变长的数组"，数据存在堆（heap）上，可以随意 push 追加。
//   let v = vec![22, 44, 66];   // 用 vec! 宏创建
//   let v: Vec<i32> = Vec::new(); // 或者先建空的，再 v.push(22)
//   对比数组 [i32; 3]：数组长度在编译期就固定，Vec 长度可以在运行时变化。
//
// ● 三种"遍历"方法的区别（本题的关键）
//     v.iter()      —— 借出每个元素的不可变引用，元素类型 &T（只读）
//     v.iter_mut()  —— 借出每个元素的可变引用，元素类型 &mut T（可改）
//     v.into_iter() —— 把 Vec 的所有权拿走，元素类型 T（消费掉原 Vec）
//   本题第一空用 iter_mut（要改），第二空用 iter（只读）。
//
// ● 引用与解引用
//   &x    ：x 的不可变引用（借来看，不能改）
//   &mut x：x 的可变引用（借来改）
//   *r    ：解引用，表示"r 指向的那个值"。
//   打个比方：element 是一把"写着 3 号仓库地址的纸条"，
//   *element 才是"3 号仓库里的货物"。改货物必须写 *element = ...。
//
// ● 为什么 vec_loop 的参数写着 `mut v`？
//   因为 iter_mut() 需要"可变地借用 v 自己"（相当于 &mut v），
//   而 Rust 规则：要可变借用，变量本身必须先声明成 mut。
//   这就是函数签名里 `mut v: Vec<i32>` 的由来（参数也是变量绑定）。
//
// ● for 循环
//   for 元素变量 in 一个"可以逐个取出东西"的东西 { ... }
//   每轮循环，元素变量就被赋成下一个元素；循环结束后 v 仍然归我们所有。
//
// ● 闭包（closure）：长得像 |x| x + 1 的小函数
//   map(|element| { element * 2 })
//   |element| 是参数列表（竖线代替圆括号），后面是函数体。
//   闭包可以"随手写"在表达式里，不需要先用 fn 起名字。
//   这里 element 就是"当前正在处理的这个元素"。
//
// ● map 和 collect
//   .map(闭包)：对每个元素调用一次闭包，把返回值当作新元素，"串"成一条新的序列；
//               它不会修改原数据，只是产生"加工后的流水线"。
//   .collect()：把流水线上的结果收集进一个集合（这里是 Vec）。
//   collect() 自己不知道要收集成什么类型，靠函数返回类型 Vec<i32> 反推出来。
//
// ● *= 是什么？
//   `*element *= 2;` 是 `*element = *element * 2;` 的简写，
//   和 C/Java 里的 +=、*= 一个意思。
//
// ============================================================================
//                              参 考 答 案
// ============================================================================

fn vec_loop(mut v: Vec<i32>) -> Vec<i32> {
    // v.iter_mut()：依次借出每个元素的可变引用（&mut i32）
    // element 在每一轮都是一个 &mut i32，指向 v 中的某个格子
    for element in v.iter_mut() {
        // *element：解引用，拿到"格子里真正的数"
        // *= 2   ：把它乘 2 再写回同一个格子（原地修改 v）
        *element *= 2;

        // 等价的啰嗦写法：*element = *element * 2;
        // 不能写 element *= 2;，因为 element 是引用，不是 i32
    }

    // 循环结束后，v 的内容已经变成 [4, 8, 12, 16, 20]
    // 最后一行不加分号 = 把这个 Vec 作为函数返回值交出去（所有权一起交出去）
    v
}

fn vec_map(v: &Vec<i32>) -> Vec<i32> {
    // v.iter()：依次借出每个元素的不可变引用（&i32），只读
    // .map(|element| ...)：对每个元素算出"新值"
    // .collect()：把所有新值收集成一个新的 Vec<i32>（类型由返回值推出）
    v.iter()
        .map(|element| {
            // element 是 &i32；&i32 乘 i32 时，Rust 会自动帮我们取出里面的数
            // 这里直接返回新数字，原 Vec v 一点都没被改动
            element * 2
        })
        .collect()
}

