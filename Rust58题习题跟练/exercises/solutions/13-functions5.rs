// ============================================================================
// 第 13 题 · functions5 —— 一个分号，让函数“什么都没返回”
// ----------------------------------------------------------------------------
// 题目类型：compile（把代码改到能编译通过就算过关）
// 课件位置：第 2 章 · 2.2.3 函数（语句 vs 表达式、最后一行表达式即返回值）
// 难度：★★☆☆☆
// 前置知识：functions4（返回类型、末尾表达式即返回值）
// ============================================================================
//
// 【题目要求】
// square(3) 应该返回 9（3 的平方），但函数体里多写了一个分号，
// 导致函数返回的不是数字。请修好它。
//
// 原题代码（未完成，仅供对照）：
//     fn main() {
//         let answer = square(3);
//         println!("The square of 3 is {}", answer);
//     }
//
//     fn square(num: i32) -> i32 {
//         num * num;
//     }
//
// 编译会报错：
//     error[E0308]: mismatched types
//      --> functions5.rs:13:24
//       |
//    13 | fn square(num: i32) -> i32 {
//       |    ------              ^^^ expected `i32`, found `()`
//       |    |
//       |    implicitly returns `()` as its body has no tail or `return` expression
//    14 |     num * num;
//       |              - help: remove this semicolon to return this value
//    翻译：函数声明说返回 i32，实际返回的却是 ()；
//          函数体没有“尾部表达式”也没有 return，所以隐式返回 ()；
//          编译器甚至直接提示：去掉这个分号就能返回该值。
//
// 【解题思路】
// 1. 函数声明说好要返回 i32，函数体最后一行是 `num * num;`。
// 2. 注意末尾的分号 `;`：它把“表达式 num * num”变成了一条**语句**，
//    语句不产生值（或者说值是 `()`），于是函数实际返回 `()`。
// 3. 类型对不上：声明 i32，实际 () → E0308。
// 4. 删掉分号，让 `num * num` 重新成为“尾部表达式”，它的值就成为返回值。
//        fn square(num: i32) -> i32 {
//            num * num
//        }
// 5. 运行：answer = 9，打印 The square of 3 is 9。
//
// ============================================================================
//                              知 识 铺 垫
// ============================================================================
//
// ● 表达式（expression）与语句（statement）
//   表达式：**能算出一个值**。例如：
//       1 + 2         → 值 3
//       num * num     → 值 9
//       x > 0         → 值 true/false
//       if a { 1 } else { 2 }   → 值 1 或 2
//   语句：**只做事，不产出可用的值**。例如：
//       let x = 3;    println!("hi");
//   在 Rust 里，一个表达式后面加上分号，它就从“表达式”变成了“语句”，
//   值被丢掉，整条语句的类型是 `()`。
//
// ● 分号 = “把值扔掉”的开关（重点！）
//       num * num      // 表达式，值 9，可以被返回
//       num * num;     // 语句，值被丢弃，类型 ()
//   这就像你算出了 9 写在纸上，加分号等于把纸揉掉扔进垃圾桶，
//   函数手里什么都没剩下，只好返回 `()`。
//
// ● () 是什么？
//   单元类型（unit type），读作“unit”。它只有一个值，也写作 `()`。
//   可以理解成“什么都没有”“空元组”。没有返回值的函数，返回类型就是 ()。
//   所以报错里的 `found ()` = “函数实际什么也没返回”。
//
// ● 代码块（block）本身也是表达式
//   一对 `{ }` 会把它最后那个不带分号的表达式的值，作为整个块的值：
//       let y = {
//           let a = 2;
//           a * 3        // ← 块的值是 6
//       };
//       println!("{}", y);   // 6
//   函数体就是这样一个代码块，所以“最后一行表达式 = 返回值”。
//
// ● 函数返回值的三种写法
//   1) 尾部表达式（最惯用）：
//          fn square(n: i32) -> i32 { n * n }
//   2) 显式 return（提前返回时必需）：
//          fn square(n: i32) -> i32 { return n * n; }
//   3) 用 if/else 表达式：
//          fn abs(n: i32) -> i32 { if n < 0 { -n } else { n } }
//   注意 2) 里 return 后面要分号，因为 `return` 本身是语句；
//   而 1) 和 3) 的核心值都**不能**带分号。
//
// ● 为什么 Rust 要这么设计？
//   它让“有返回值”这件事非常显式：你看最后一行有没有分号，就知道它返不返回。
//   同时也避免了 C 语言里 `return` 忘写、函数返回随机值的坑。
//   代价是新手常常多打一个分号 —— 本题就是专门练这个。
//
// ● 本题的执行流程
//   main：调用 square(3) → 函数体算出 9 并返回 → answer = 9
//        → 打印 The square of 3 is 9
//
// ============================================================================
//                              参 考 答 案
// ============================================================================

fn main() {
    // 调用 square(3)，把返回的 i32 接住，存进 answer
    // 如果 square 返回的是 ()，这里就会因为类型不匹配而报错
    let answer = square(3);

    // 打印结果：9
    println!("The square of 3 is {}", answer);
}

// 返回 i32 的函数
fn square(num: i32) -> i32 {
    // 关键改动：**删掉原来的分号**
    // 这样 num * num 就是函数体的“尾部表达式”，
    // 它的值（9）会自动成为函数的返回值
    num * num
}

// ============================================================================
//                            逐 行 解 析
// ============================================================================
//
// fn square(num: i32) -> i32 {
//   ├─ fn         ：定义函数
//   ├─ square     ：函数名
//   ├─ num: i32   ：参数
//   ├─ -> i32     ：承诺返回一个 i32
//   └─ { ... }    ：函数体（一个代码块，它的值就是返回值）
//
//     num * num
//   ├─ 这是一个表达式，算出 9
//   ├─ 末尾**没有分号** → 它是“尾部表达式”
//   └─ 于是 9 被当作返回值交回给 main
//
// 对比错误写法：
//     num * num;
//   └─ 加了分号 → 变成语句，值 9 被丢弃 → 函数返回 () → E0308
//
// main:
//   let answer = square(3);   // answer = 9
//   println!("The square of 3 is {}", answer);   // 输出 9
//
// ============================================================================
//                          常 见 错 误 与 提 示
// ============================================================================
//
// 1. 保留分号（= 原题状态）：
//        num * num;
//    → error[E0308]: mismatched types
//      expected `i32`, found `()`
//      并附 help: remove this semicolon to return this value
//    ★ 看到 “found ()” 且提示 “remove this semicolon”，几乎总是多打了分号。
//
// 2. 用 return 但忘了分号：
//        return num * num
//    → error: expected `;`, found `}`
//      （return 是语句，后面要分号）
//
// 3. 想用 let 存结果再返回，却忘了最后一行：
//        let r = num * num;
//    → error[E0308]（函数体最后是 let 语句，返回 ()）
//    正确写法：最后再加一行 `r`（不带分号）。
//
// 4. 声明返回 i32，却写成没有返回值：
//        fn square(num: i32) { num * num }
//    → error[E0308]: mismatched types（函数默认返回 ()）
//      并警告“unused arithmetic operation / 表达式未被使用”。
//
// 5. 在 if 分支里加分号：
//        if n > 0 { n; } else { -n }
//    → error[E0308]，分支类型变成 ()，与另一分支不一致。
//
// ============================================================================
//                          小 结
// ============================================================================
//
// 本题你需要记住：
//   1. 表达式有值，语句没有值（类型是 ()）；
//   2. 表达式后加分号 → 变成语句 → 值被丢弃；
//   3. 函数体最后一个“不带分号的表达式”就是返回值；
//   4. `-> i32` 是承诺，实际返回 () 会报 E0308；
//   5. 看到 “expected i32, found ()” 先检查最后一行有没有多余分号。
//
// 一句话记忆：**要交作业的那一行，千万别打分号。**
//
