// ============================================================================
// 第 02 题 · intro2 —— 给占位符补上参数
// ----------------------------------------------------------------------------
// 题目类型：compile（把代码改到能编译通过就算过关）
// 课件位置：第 1 章 · 1.3 println! 格式化输出（{} 占位符与参数）
// 难度：★☆☆☆☆
// 前置知识：intro1（fn main、println!、注释）
// ============================================================================
//
// 【题目要求】
// 让程序向这个世界问一声好 —— 也就是让 println! 真正打印出
// "Hello world!"（world 可以换成你喜欢的词，比如 Rust）。
//
// 原题代码（未完成，仅供对照）：
//     fn main() {
//         println!("Hello {}!");
//     }
//
// 编译会报错：
//     error: 1 positional argument in format string, but no arguments were given
//     （格式化字符串里有 1 个占位参数，但没有提供任何参数）
//
// 【解题思路】
// 1. 看格式化字符串 "Hello {}!"：其中 `{}` 是一个“空位”，也就是占位符。
// 2. println! 的规则是：字符串里有几个 {}，后面就必须跟几个参数来填。
//    现在有 1 个 {}，但逗号后面什么都没有 → 编译器报错。
// 3. 在字符串后面加一个逗号，再写一个值，比如 "world"：
//        println!("Hello {}!", "world");
// 4. 编译运行，{} 的位置就被 world 顶上了，输出 Hello world!
//
// ============================================================================
//                              知 识 铺 垫
// ============================================================================
//
// ● 宏调用长什么样？
//       println!("Hello {}!", "world");
//       └─名字─┘└──第 1 个参数──┘└─第 2 个参数─┘
//   宏名后面必须带 `!`。括号里用逗号分隔若干个参数，第一个参数几乎总是
//   “格式化字符串”，后面的参数是“要填进占位符的值”。
//
// ● 什么是占位符 {}？
//   你可以把 "Hello {}!" 想成一张填空题的卷子：
//       Hello ____ !
//   `{}` 就是那条横线。后面给的第一个值会填进第一个 {}，第二个值填第二个 {}，
//   以此类推（所以叫“按位置对应”）。
//
// ● 参数的类型：这里是字符串字面量
//   "world" 这种用双引号直接写出来的文本叫“字符串字面量”，类型是 &str
//   （读作“字符串切片引用”）。现在不用深究，先记住：
//       双引号 + 文本 = 字符串
//   等到 strings1 那组题会详细讲 String 和 &str 的区别。
//
// ● 一个 {} 只能填一个值，但值不一定是字符串
//   {} 很聪明，数字、布尔、字符都能填：
//       println!("我今年 {} 岁", 18);        // 填整数
//       println!("{} + {} = {}", 1, 2, 3);   // 三个 {} 对应三个参数
//   它甚至能填表达式：println!("{}", 1 + 2);
//
// ● 参数个数必须和占位符个数一致
//   少了 → "no arguments were given" / "2 positional arguments ... but 1 argument was given"
//   多了 → "argument never used"（参数没被用到，也是编译错误）
//   Rust 在**编译期**就检查这件事，不会等到运行时才发现。
//
// ● 想输出一对大括号本身怎么办？
//   写 {{ 和 }}：
//       println!("用 {{}} 表示占位符");
//   输出：用 {} 表示占位符
//
// ============================================================================
//                              参 考 答 案
// ============================================================================

fn main() {
    // "Hello {}!" ：格式化字符串，{} 是占位符，等待被后面的参数替换
    // "world"     ：第 1 个参数，会被填进第 1 个 {} 里
    // 逗号        ：用来分隔“格式化字符串”和“要填进去的值”，不能省
    println!("Hello {}!", "world");
    // 运行输出：Hello world!
}

// ============================================================================
//                            逐 行 解 析
// ============================================================================
//
// println!("Hello {}!", "world");
//   ├─ println!  ：打印宏（宏名带感叹号），打印完自动换行
//   ├─ "Hello {}!"：格式化字符串；其中 {} 是占位符
//   ├─ ,         ：分隔参数
//   ├─ "world"   ：第 1 个参数 → 填进第 1 个 {}
//   └─ ;         ：语句结束
//
// 拼装过程（可以用手在纸上模拟）：
//   模板：Hello {}!
//   填 1：Hello world!
//   再自动补一个换行
//
// ============================================================================
//                          常 见 错 误 与 提 示
// ============================================================================
//
// 1. 只改字符串、不给参数（= 原题状态）：
//        println!("Hello {}!");
//    → error: 1 positional argument in format string, but no arguments were given
//
// 2. 给了参数但忘了逗号：
//        println!("Hello {}!" "world");
//    → error: expected `,`
//
// 3. 参数给多了：
//        println!("Hello {}!", "world", "again");
//    → error: argument never used（第 2 个参数没地方放）
//
// 4. 占位符写错，比如写成了中文括号：
//        println!("Hello ｛｝!", "world");
//    → 编译能过，但屏幕上会原样打印 Hello ｛｝!（中文括号不是占位符）
//
// 5. 想打印大括号本身却只写了一个：
//        println!("{}");
//    → 仍然报“没有给参数”，因为 {} 还是被当成占位符
//    正确写法：println!("{{}}");
//
// ============================================================================
//                          小 结
// ============================================================================
//
// 本题你需要记住：
//   1. println! 是宏，名字后面必须有 !；
//   2. {} 是占位符，相当于填空题的空位；
//   3. 有几个 {}，逗号后面就要有几个值，个数必须一致；
//   4. 字符串字面量用双引号，类型是 &str；
//   5. 想输出字面的大括号，写成 {{ 和 }}。
//
// 一句话记忆：**{} 是空位，逗号后面按顺序把值塞进去。**
//
