// ============================================================================
// 第 39 题 · strings2 —— 一个 & 搞定 String → &str 的自动解引用
// ----------------------------------------------------------------------------
// 题目类型：compile（把代码改到能编译通过就算过关）
// 课件位置：第 3 章 · 3.1 字符串（String 借用为 &str）；2.3.2 引用与借用
// 难度：★★☆☆☆
// 前置知识：strings1（String 与 &str 的区别）、move_semantics6（用 & 借用避免移动）
// ============================================================================
//
// 【题目要求】
// 不修改函数签名、也尽量不改第 11 行（`let word = String::from("green");`），
// 只允许在调用 `is_a_color_word` 的地方做最小改动，让代码编译通过。
//
// 原题代码（未完成，仅供对照）：
//     fn main() {
//         let word = String::from("green"); // Try not changing this line :)
//         if is_a_color_word(word) {
//             println!("That is a color word I know!");
//         } else {
//             println!("That is not a color word I know.");
//         }
//     }
//
//     fn is_a_color_word(attempt: &str) -> bool {
//         attempt == "green" || attempt == "blue" || attempt == "red"
//     }
//
// 编译器会报：
//     error[E0308]: mismatched types
//       expected `&str`, found `String`
//       help: consider borrowing here: `&word`
//
// 【解题思路】
// 1. `word` 是 String（拥有堆上的文本）；函数参数 `attempt: &str` 要的是一个**借用**。
// 2. 把 `word` 直接传进去，等于想把整个 String “移动”给函数，类型也不对。
// 3. 在 `word` 前面加一个 `&`：
//        if is_a_color_word(&word) {
//    `&word` 的类型表面上是 `&String`，但 Rust 有一条“自动解引用强制转换”规则：
//    当函数需要 `&str` 而你给的是 `&String` 时，编译器会自动把它转成 `&str`。
// 4. 于是只加一个字符 `&`，代码就通过了，而且 word 的所有权还在 main 手里。
//
// ============================================================================
//                              知 识 铺 垫
// ============================================================================
//
// ● 先复习两种字符串
//   String：拥有堆上的文本，可以增长，离开作用域自动释放。
//   &str  ：对一段文本的借用（指针 + 长度），不拥有、不能扩容。
//
// ● 为什么函数参数喜欢写 &str？
//   因为 &str 既能接收字符串字面量（"green"），也能接收 String 的借用（&word），
//   还不用夺走调用者的所有权。函数只是“看一眼”文本，用借用最划算。
//   如果参数写成 String，调用时就得把整个 String 移动进去，调用方之后不能再用 word。
//
// ● “借用”到底借了什么？
//   `&word` 借的是 `word` 这个 String 值本身；
//   而函数想要的是“文本内容”的视图 &str。
//   String 内部其实就是一个“指针 + 长度 + 容量”，文本在堆上；
//   &str 需要的是“指针 + 长度”。
//   两者只差“容量”这一项，所以从 &String 拿到 &str 几乎不需要额外工作。
//
// ● 自动解引用强制转换（deref coercion）
//   标准库为 String 实现了 `Deref<Target = str>`，意思是：
//   “把 String 解引用一次，得到 str”。
//   于是编译器在需要 &str 的地方看到 &String 时，会自动插入解引用：
//        &String  ──自动转换──▶  &str
//   这个过程和你手写 `&*word` 效果一样，但更简洁。
//
// ● 打个比方
//   String 像“一个装着书的盒子”，&String 是“借用这个盒子”，
//   &str 是“直接看盒子里的书页”。
//   函数说“我要看书页”，你递过去盒子，编译器会自动帮你打开盒子把书页露出来。
//
// ● 这个转换只发生在“引用之间”
//   它不会把 String 变成 &str 的所有权魔法，也不会让 `word` 变成别的类型：
//   word 依然是 String，只是传参时临时借出一个 &str 视图。
//
// ● 记忆小技巧：看参数是“要盒子”还是“要书页”
//   参数 `String`  → 要盒子本身（会把所有权拿走，调用后原变量失效）
//   参数 `&String` → 要盒子的借用（少见，通常直接写 &str 更通用）
//   参数 `&str`    → 要书页（最常用，字面量和 String 借用都能传）
//   调用处的 `&` 就是“把盒子递过去”，打开盒子取书页的动作由编译器完成。
//
// ● as_str 方法
//   `String::as_str(&self) -> &str` 是标准库提供的显式转换，
//   效果等价于 `&self[..]`，但更清楚地表达“我要的是文本视图”。
//   当你想让代码意图更明显时，用 as_str() 比裸 & 更好读。
//
// ● 等价的几种写法（都能编译）
//   is_a_color_word(&word)        // 依赖自动解引用，最简洁（本题答案）
//   is_a_color_word(word.as_str())// 显式调用 as_str，明确表达意图
//   is_a_color_word(&word[..])    // 手动切片，取整个字符串
//   is_a_color_word(&*word)       // 手动解引用再取地址
//   初学推荐第一种；读别人代码时见到后三种也要认识。
//
// ============================================================================
//                              参 考 答 案
// ============================================================================

fn main() {
    // word 是 String，拥有堆上的 "green"（这一行保持原样）
    let word = String::from("green");

    // &word：借用 word，而不是把它移动走。
    // 函数要 &str，编译器自动把 &String 解引用转换成 &str。
    if is_a_color_word(&word) {
        println!("That is a color word I know!");
    } else {
        println!("That is not a color word I know.");
    }

    // 因为只是借用，这里 word 依然有效（原题没有再用它，
    // 你可以自己试着在下面加一行 println!("{}", word); 验证这一点）
}

// 参数是 &str：只借用文本，不夺走所有权
fn is_a_color_word(attempt: &str) -> bool {
    // attempt 与字符串字面量都是 &str，可以直接用 == 比较内容
    attempt == "green" || attempt == "blue" || attempt == "red"
}

// ============================================================================
//                            详 细 解 析
// ============================================================================
//
// 1）不加 & 时，编译器到底在抱怨什么？
//    函数签名要求 `&str`（一个借用），而你给的是 `String`（一个拥有所有权的值）。
//    类型不匹配，报 E0308；编译器还会贴心提示 `help: consider borrowing here: &word`。
//
// 2）加了 & 之后，类型是 &String，为什么也能通过？
//    因为 Rust 在“函数传参”这种明确知道目标类型的场景下，会自动尝试解引用转换：
//        &String → &str
//    规则来自 `impl Deref for String { type Target = str; ... }`。
//    编译器发现 &String 不能直接当 &str 用，就插入一次 `*`，变成 str，
//    再取 `&`，得到 &str。这正是“自动解引用强制转换”的名字来源。
//
// 3）为什么 `attempt == "green"` 能比较？
//    == 两边都是 &str，比较的是文本内容（逐字节），不是地址。
//    如果试图比较 String 和 &str，标准库也实现了对应的 PartialEq，同样能比。
//
// 4）函数返回 bool，if 条件正好需要 bool
//    `is_a_color_word(&word)` 返回 true 或 false，直接放进 if 的条件位置。
//    Rust 的 if 条件必须是 bool，不像 C 那样“非 0 即真”。
//
// 5）如果写成 `is_a_color_word(&word[..])` 会怎样？
//    也能编译。`word[..]` 是对整个 String 的切片，类型是 str（不定长，不能单独存在），
//    前面加 & 得到 &str。效果与 &word 一样，只是写法更啰嗦。
//
// 6）这题和所有权有什么关系？
//    如果函数参数是 String，`is_a_color_word(word)` 会把 word 移动进函数，
//    函数结束后 word 就被释放，main 里不能再用。用 & 借用则完全没有这个问题。
//    这就是 move_semantics6 反复强调的“能借就别拿走”。
//
// 7）`attempt == "green"` 里为什么不用写 `*attempt`？
//    == 对 &str 有专门的实现，比较的是两段文本的内容，而不是指针地址。
//    如果写 `*attempt`，得到的是不定长的 str，不能按值使用，反而会报错。
//
// 8）借用在函数返回后还会不会悬垂？
//    不会。&str 借用的是 main 里的 word，而 word 活得比函数调用久，
//    所以函数内部短暂借用是安全的。反过来，如果函数试图把 &str 返回出去，
//    就需要生命周期标注来证明“借的东西活得够久”（见 lifetimes1）。
//
// ============================================================================
//                          常 见 错 误 与 提 示
// ============================================================================
//
// 1. 忘记加 &：
//        is_a_color_word(word)
//    → error[E0308]: mismatched types，expected `&str`, found `String`
//
// 2. 加了两个 &：
//        is_a_color_word(&&word)
//    → 类型是 &&String，自动解引用只能消一层，仍报 E0308
//      （expected `&str`, found `&&String`）
//
// 3. 手动解引用写错：
//        is_a_color_word(*word)
//    → error[E0507]: cannot move out of dereference of `String`
//      （str 是不定长类型，不能按值搬出来）
//
// 4. 改函数签名为 `attempt: String`：
//    虽然把调用改成传 word 也能编译，但题目要求不改签名；
//    而且这样会移动 word，违背“借用”的练习目的。
//
// 5. 改成 `is_a_color_word(&word.to_string())`：
//    能编译，但白白又分配了一个 String，属于不必要的开销。
//
// 6. 把 `&` 加到函数定义上（`attempt: &str` 改成 `&String`）：
//    会连带影响其他调用方（比如传字面量 "green" 的地方），不推荐。
//
// 7. 以为加了 & 就复制了一份：
//    & 只是借用，没有复制任何文本；调用结束后 word 仍然有效。
//    想真正复制请用 `word.clone()` 或 `word.to_string()`。
//
// 8. 在函数里想返回借用：
//        fn first_char(s: &str) -> &str { &s[0..1] }
//    这个例子能编译，因为返回值借自参数 s，生命周期由调用方保证。
//    但如果返回的是函数内部新建 String 的切片，就会报“返回了局部变量的引用”。
//
// ============================================================================
//                          小 结
// ============================================================================
//
// 本题你需要记住：
//   1. 函数参数写 `&str` 最通用：既能收字面量，也能收 String 的借用；
//   2. 传 String 给 &str 参数时，加一个 `&` 即可；
//   3. 背后机制叫“自动解引用强制转换”：&String 会自动变成 &str；
//   4. 借用不会转移所有权，调用后原变量仍然可用；
//   5. 想显式表达意图时，也可以写 `word.as_str()`。
//
// 一句话记忆：**String 是盒子，&str 是书页；给函数 `&盒子`，编译器帮你翻开。**
//
