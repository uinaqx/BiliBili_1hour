// ============================================================================
// 第 29 题 · move_semantics4 —— 让函数自己造数据，再"交"给调用者
// ----------------------------------------------------------------------------
// 题目类型：test（让 #[test] 测试通过就算过关）
// 课件位置：第 2 章 · 2.3.2 用返回值转移所有权，替代"传入再返回"
// 难度：★★★☆☆
// 前置知识：move_semantics1~3（移动、mut、参数绑定）
// 题目约束：`fill_vec()` **不再接收参数**，这一点不许改
// ============================================================================
//
// 【题目要求】
// 重构代码：不再把 vec0 传进 fill_vec，
// 而是让 fill_vec 自己在内部创建这个 Vec，再把它返回给 main。
//
// 原题代码（未完成，仅供对照）：
//     #[test]
//     fn main() {
//         let vec0 = vec![22, 44, 66];
//         let mut vec1 = fill_vec(vec0);
//         assert_eq!(vec1, vec![22, 44, 66, 88]);
//     }
//
//     // `fill_vec()` 不再接收 `vec: Vec<i32>` 参数 —— 不要改这个函数签名！
//     fn fill_vec() -> Vec<i32> {
//         // 改成"在这里创建并填充 Vec"
//         let mut vec = vec;        // ← 错：vec 是什么？没有这个变量
//         vec.push(88);
//         vec
//     }
//
// 编译报错：
//     error[E0425]: cannot find value `vec` in this scope
//     （找不到叫 vec 的值）
//
// 【解题思路】
// 1. 函数签名已经变成 `fn fill_vec() -> Vec<i32>`：不接收参数，只返回 Vec。
//    所以函数体里不能再指望"外面传进来一个 vec"。
// 2. 既然要返回 [22, 44, 66, 88]，就得在函数内部把它造出来：
//        let mut vec = vec![22, 44, 66];
//    这里的 `vec![...]` 是宏（注意感叹号），负责创建一个新的 Vec。
// 3. main 里：删掉 `let vec0 = ...` 这一行（题目 hint 原话：get rid of the first line），
//    并把 `fill_vec(vec0)` 改成无参的 `fill_vec()`；
//    此时 vec1 只是接收返回值、不再 push，所以前面的 `mut` 也可以去掉。
// 4. 这样"数据从哪来"就变成了函数自己的事，main 只负责收结果——
//    这正是"返回值转移所有权"的典型用法。
//
// ============================================================================
//                              知 识 铺 垫
// ============================================================================
//
// ● 所有权可以"进出函数"两个方向流动
//   进：`fill_vec(vec0)`  —— 调用者把所有权交给函数（上一题的做法）
//   出：`fn fill_vec() -> Vec<i32>` —— 函数把所有权交给调用者（本题的做法）
//   Rust 里这两件事都不复制数据，只是"借书证换名字"。
//   打个比方：函数像一个加工厂，原料可以由外面送进来（传参），
//   也可以由工厂自己采购（函数内创建），成品都要交给客户（返回值）。
//
// ● 返回 Vec 时发生了什么？
//   `vec` 是函数的局部变量，函数结束时它本该被释放；
//   但因为最后一行 `vec`（不加分号）把它当作返回值交了出去，
//   所有权就"搬"到了调用者的变量里，所以不会被释放。
//   这就是 Rust 不用 GC 也不会悬垂指针的原因：所有权账目始终平衡。
//
// ● `vec![...]` 宏
//   `vec![22, 44, 66]` 展开后大致相当于：
//       let mut tmp = Vec::new();
//       tmp.push(22); tmp.push(44); tmp.push(66);
//       tmp
//   它只是让写法更短，本质还是创建一个 Vec。注意 `!` 表示宏，不能漏。
//
// ● 为什么 main 里的 vec0 要删掉？
//   题目要求"不再把 vec0 传进函数"。既然没人用它了，就该删掉这一行；
//   若保留 `let vec0 = ...;`，编译器会提示：
//       warning: unused variable: `vec0`
//   warning 不影响测试通过，但属于"死代码"，写 Rust 时应尽量保持零警告。
//   本题答案按题目要求直接删除该行。
//
// ● 为什么这不是"多此一举"？
//   当数据的创建过程很复杂（要读文件、要计算、要校验），
//   把它封装进一个函数、只把成品交出来，调用方就只需要关心结果。
//   Rust 的所有权让这种"工厂函数"既安全又零拷贝。
//
// ● 与"传入再返回"的对比
//   传入再返回：fn fill_vec(vec: Vec<i32>) -> Vec<i32>
//               调用者必须先有一个 Vec，函数只是"加工一下还给你"。
//   自己创建：  fn fill_vec() -> Vec<i32>
//               调用者什么都不用准备，函数负责"从无到有"。
//   两种都是把所有权交出去，区别只在"原料谁提供"。
//
// ============================================================================
//                              参 考 答 案
// ============================================================================

#[test]
fn main() {
    // 按题目要求：不再创建 vec0（原来的 `let vec0 = ...` 这一行要删掉）

    // 调用改成 fill_vec()：不传参数
    // 函数内部造好 Vec 并返回，所有权交给 vec1
    // 这里不需要 mut：vec1 只是接收结果，后面不再修改它
    let vec1 = fill_vec();

    // 断言：22,44,66 加上 88
    assert_eq!(vec1, vec![22, 44, 66, 88]);
}

// 函数签名保持原样：不接收参数，返回一个 Vec<i32>
fn fill_vec() -> Vec<i32> {
    // 关键改动：在函数内部创建 Vec
    // mut 是必须的，因为下面要 push（push 需要 &mut self）
    let mut vec = vec![22, 44, 66];

    // 追加 88
    vec.push(88);

    // 把 Vec 交出去（所有权移出函数，进入调用者的 vec1）
    vec
}

// ============================================================================
//                            逐 行 解 析
// ============================================================================
//
// （原题第一行 `let vec0 = vec![22, 44, 66];` 已按题目要求删除）
//
// let vec1 = fill_vec();
//   └─ 无参调用；函数返回的 Vec 所有权交给 vec1
//      （不再需要 mut，因为后面不再修改 vec1）
//
// fn fill_vec() -> Vec<i32>
//   ├─ ()          ：参数列表为空，不接收任何东西
//   └─ -> Vec<i32> ：返回类型，表示"我会交给你一个 Vec<i32>"
//
// let mut vec = vec![22, 44, 66];
//   └─ 在函数内部新建 Vec：堆上分配，内容 22,44,66
//      这是一次"从无到有"的创建，不再依赖外部
//
// vec.push(88);
//   └─ 追加一个元素，len 变 4
//
// vec
//   └─ 尾表达式（没有分号），把所有权移出函数
//
// ============================================================================
//                 为什么返回值能"带走"局部变量？——所有权的账本
// ============================================================================
//
// 函数结束时，所有局部变量都要被 drop（释放）。
// 但如果某个局部变量被"移动"出去了（作为返回值、或存进别的结构），
// 它的所有权就不在函数里了，函数结束时不会释放它。
//
// 你可以这样理解账本：
//   1. 创建 vec → 账本记："vec 拥有这份堆内存"
//   2. return vec → 账本改成："调用者的 vec1 拥有这份堆内存"
//   3. 函数返回 → 函数里没有需要释放的 vec 了，跳过
//   4. main 结束时 → 账本说 vec1 拥有它，由 vec1 负责释放
//
// 整个过程中，内存只被分配一次、释放一次，绝不会 double free，也不需要 GC。
//
// ============================================================================
//                          常 见 错 误 与 提 示
// ============================================================================
//
// 1. 只改函数体，忘了改调用处：
//        let mut vec1 = fill_vec(vec0);
//    → error[E0061]: this function takes 0 arguments but 1 argument was supplied
//
// 2. 函数体里写成 `let mut vec = Vec::new();` 却不 push 初始三个元素：
//    → 断言失败（[] 或 [88] != [22,44,66,88]），test FAILED
//
// 3. 用了 `vec` 却漏了感叹号：`let mut vec = vec(22, 44, 66);`
//    → error[E0423]: expected function, found macro `vec`（vec 是宏，必须写 vec!）
//
// 4. 忘了 mut：
//        let vec = vec![22, 44, 66];  vec.push(88);
//    → error[E0596]: cannot borrow `vec` as mutable
//
// 5. 画蛇添足给函数加参数（违反题目"不要改签名"）：
//        fn fill_vec(vec: Vec<i32>) -> Vec<i32>
//    本题就是要练"函数自己创建"，加参数就回到上一题了。
//
// 6. 以为 main 里不用改就能过：
//    函数签名是无参的，`fill_vec(vec0)` 一定会报参数个数不匹配。
//
// ============================================================================
//                          小 结
// ============================================================================
//
// 本题你需要记住：
//   1. 函数可以通过返回值把所有权交给调用者（零拷贝）；
//   2. 局部变量作为返回值时不会被释放，所有权"搬"了出去；
//   3. `vec![...]` 是创建 Vec 的宏，别忘了感叹号；
//   4. 函数签名决定调用方式，改签名就必须同步改调用处；
//   5. 所有权在"创建 → 传参 → 返回 → 离开作用域"这条链上始终唯一。
//
// 一句话记忆：**原料可以由外面送，也可以自己造；成品交出去，所有权跟着走。**
//
