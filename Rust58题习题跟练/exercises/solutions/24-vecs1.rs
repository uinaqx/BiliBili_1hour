// ============================================================================
// 第 24 题 · vecs1 —— 用 vec![] 宏创建动态数组
// ----------------------------------------------------------------------------
// 题目类型：test（让 #[test] 测试通过就算过关）
// 课件位置：第 6 章 · 6.1.1 动态数组 Vec<T>（Vec::new / vec![] 创建）
// 难度：★★☆☆☆
// 前置知识：数组 [T; N] 与切片（第 20 题 primitive_types3、第 21 题）
// ============================================================================
//
// 【题目要求】
// 创建一个 Vec，里面的元素和数组 a 完全一样，让测试通过。
// 原题代码（未完成，仅供对照）：
//     fn array_and_vec() -> ([i32; 4], Vec<i32>) {
//         let a = [10, 20, 30, 40]; // a plain array
//         let v = // TODO: declare your vector here with the macro for vectors
//
//         (a, v)
//     }
//
//     #[cfg(test)]
//     mod tests {
//         use super::*;
//
//         #[test]
//         fn test_array_and_vec_similarity() {
//             let (a, v) = array_and_vec();
//             assert_eq!(a, v[..]);
//         }
//     }
//
// 【解题思路】
// 1. 函数返回类型是 ([i32; 4], Vec<i32>)，说明要返回“一个数组 + 一个 Vec”。
// 2. 数组已经给好了：a = [10, 20, 30, 40]。
// 3. Vec 这一行原题只写了 `let v =`，注释提示“用宏来创建 vector”。
//    Rust 创建 Vec 有两个常用办法：
//      a) Vec::new() + 逐个 push（麻烦一点，但能体现“长度可变”）；
//      b) vec![10, 20, 30, 40] 宏（最简洁，题目注释要的就是这个）。
// 4. 于是写 `let v = vec![10, 20, 30, 40];`。
// 5. 测试里 assert_eq!(a, v[..])：把 Vec 用 v[..] 变成切片，再和数组比较；
//    元素逐个相等就通过。
//
// ============================================================================
//                              知 识 铺 垫
// ============================================================================
//
// ● 为什么需要 Vec？
//   数组 [T; N] 的长度在编译期就固定了（第 20 题），可现实中经常需要
//   “边运行边往里加元素”。Vec<T> 就是“长度可变”的数组：
//     - 数据存在**堆（heap）**上，所以长度可以动态变化；
//     - 通过 3 个字段记录：指向堆的指针、长度 len、容量 capacity；
//     - 类型写法 Vec<i32>，读作“装着 i32 的向量”。
//
// ● 两种创建方式
//   1) 宏（本题要求）：
//        let v = vec![10, 20, 30, 40];
//      方括号里是元素列表。还有 `vec![0; 5]` 这种写法，
//      表示“5 个 0”（分号左边是值、右边是个数，和数组的 [0; 5] 很像）。
//   2) 先建空表再 push：
//        let mut v = Vec::new();   // 或 let mut v: Vec<i32> = Vec::new();
//        v.push(10);
//        v.push(20);
//      注意必须加 mut，因为 push 会修改 v。
//
// ● vec! 是宏还是函数？
//   是**宏**（末尾有感叹号 !）。宏在编译期展开成创建 Vec 的代码，
//   可以接受“不定个数”的参数，这是普通函数做不到的
//   （普通函数没法既接受 3 个参数又接受 4 个参数）。
//   类似的还有 println!、format!。
//
// ● 返回元组（复习第 22 题）
//     (a, v)   // 把数组和 Vec 打包成二元组，类型是 ([i32; 4], Vec<i32>)
//   函数声明里的返回类型正好是 ([i32; 4], Vec<i32>)，两者匹配。
//
// ● v[..] 是什么？
//   这是“对整个 Vec 的切片”。v 本身是 Vec<i32>，v[..] 是 [i32]（无固定长度），
//   在 assert_eq! 里会被自动借用成 &[i32]。
//   为什么不能直接 assert_eq!(a, v)？
//   因为那是拿数组 [i32; 4] 和 Vec<i32> 比较 —— 标准库没有为这两个类型
//   直接实现 PartialEq，会报 E0277（trait bound not satisfied）。
//   而“数组和切片”之间是有比较实现的，所以要先切片。
//
// ● 数组和 Vec 的关系
//   Vec 可以借用成切片 &[T]，数组也能借用成切片 &[T]，
//   所以“切片”是两个容器之间的公共语言：很多函数参数写成 &[T]，
//   这样数组、Vec 都能传进去。
//
// ● #[cfg(test)] mod tests（复习 if1）
//   只有测试模式才编译这个模块；use super::* 引入外层函数 array_and_vec。
//   本题没有 main，必须 rustc --test。
//
// ============================================================================
//                              参 考 答 案
// ============================================================================

// 返回一个二元组：(固定长度数组, 动态数组)
// 类型写作 ([i32; 4], Vec<i32>)
fn array_and_vec() -> ([i32; 4], Vec<i32>) {
    let a = [10, 20, 30, 40]; // 普通数组：长度编译期固定，放在栈上

    // vec![] 是“创建 Vec 的宏”（注意末尾的感叹号）
    // 方括号里按顺序列出元素，得到的类型是 Vec<i32>
    // Vec 的数据放在堆上，长度可以在运行时变化
    let v = vec![10, 20, 30, 40];

    // 把两个容器打包成元组返回（最后一行不带分号 → 就是返回值）
    (a, v)
}

// ---------------------------------------------------------------------------
// 下面这段是原题自带的测试代码，完全没有改动。
// ---------------------------------------------------------------------------
#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_array_and_vec_similarity() {
        // 用元组解构（复习第 22 题）：a 是数组，v 是 Vec
        let (a, v) = array_and_vec();

        // v[..] ：把整个 Vec 借成切片 &[i32]
        // 数组和切片之间实现了“按元素比较”，所以这个断言合法
        assert_eq!(a, v[..]);
    }
}

// ============================================================================
//                            逐 行 解 析
// ============================================================================
//
// fn array_and_vec() -> ([i32; 4], Vec<i32>)
//   ├─ ()                  ：没有参数
//   └─ ([i32; 4], Vec<i32>)：返回“4 个 i32 的数组”和“i32 的 Vec”组成的元组
//
// let a = [10, 20, 30, 40];
//   └─ 数组，类型 [i32; 4]，占 16 字节，在栈上
//
// let v = vec![10, 20, 30, 40];
//   ├─ vec!              ：宏，展开为创建 + 填充 Vec 的代码
//   └─ [10, 20, 30, 40]  ：元素列表
//   结果：v 的类型 Vec<i32>，len() == 4，数据在堆上
//
// (a, v)
//   └─ 元组字面量；不带分号 → 作为函数返回值
//
// assert_eq!(a, v[..])
//   ├─ a      ：&[i32; 4]（assert_eq! 内部取引用）
//   ├─ v[..]  ：&[i32]（切片的引用）
//   └─ 两者按元素逐个比较，[10,20,30,40] == [10,20,30,40] → 通过
//
// ============================================================================
//                          常 见 错 误 与 提 示
// ============================================================================
//
// 1. 只写了 let v = 后面空着（原题状态）：
//    → error: expected expression, found `(`
//    （let 后面必须有表达式）
//
// 2. 用方括号当 Vec 构造：
//        let v = [10, 20, 30, 40];
//    → 得到的是数组 [i32; 4]，不是 Vec<i32>，返回类型不匹配：
//      error[E0308]: mismatched types
//      expected `Vec<i32>`, found `[i32; 4]`
//
// 3. 用圆括号（当成元组）：
//        let v = (10, 20, 30, 40);
//    → 类型是 (i32, i32, i32, i32)，同样报 E0308
//
// 4. 少写感叹号：
//        let v = vec[10, 20, 30, 40];
//    → error[E0423]: expected function, found macro `vec`
//    （vec 是宏，必须写 vec!）
//
// 5. 用 Vec::new() 但忘了 push（得到空 Vec）：
//        let v = Vec::new();
//    → 编译通过（返回类型能推断出来），但测试失败：
//      left: [10, 20, 30, 40], right: []
//
// 6. 想用 push 但忘了 mut：
//        let v = Vec::new();
//        v.push(10);
//    → error[E0596]: cannot borrow `v` as mutable, as it is not declared as mutable
//      应为 let mut v = Vec::new();
//
// 7. 直接把 Vec 当数组索引比较，写成 assert_eq!(a, v)：
//    → error[E0277]: `Vec<i32>` and `[i32; 4]` cannot be compared directly
//      （要写成 v[..] 或 &v[..]，转成切片再比）
//
// 8. 忘记 --test（本题没有 main）：
//        rustc vecs1.rs
//    → error[E0601]: `main` function not found in crate
//
// ============================================================================
//                          小 结
// ============================================================================
//
// 本题你需要记住：
//   1. Vec<T> 是长度可变的“动态数组”，数据在堆上；
//   2. 创建方式：vec![元素列表] 宏，或 Vec::new() + push（需要 mut）；
//   3. vec![值; 个数] 可以快速造出“重复值”的 Vec；
//   4. 数组和 Vec 都能借成切片 &[T]，切片是两者比较/传参的公共类型。
//
// 一句话记忆：**定长用数组 [...]，可变长用 vec![...]，两者都能变成切片来比较。**
//
