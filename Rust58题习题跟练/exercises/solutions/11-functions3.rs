// ============================================================================
// 第 11 题 · functions3 —— 调用函数时，参数一个都不能少
// ----------------------------------------------------------------------------
// 题目类型：compile（把代码改到能编译通过就算过关）
// 课件位置：第 2 章 · 2.2.3 函数（函数调用与实参个数/类型）
// 难度：★☆☆☆☆
// 前置知识：functions2（参数必须写类型）、variables2（u32）
// ============================================================================
//
// 【题目要求】
// call_me 需要 1 个参数，但 main 里调用时什么也没传。
// 请把实参补上，让程序能编译并正常响铃。
//
// 原题代码（未完成，仅供对照）：
//     fn main() {
//         call_me();
//     }
//
//     fn call_me(num: u32) {
//         for i in 0..num {
//             println!("Ring! Call number {}", i + 1);
//         }
//     }
//
// 编译会报错：
//     error[E0061]: this function takes 1 argument but 0 arguments were supplied
//     （这个函数需要 1 个参数，但调用时提供了 0 个）
//
// 【解题思路】
// 1. 函数的参数列表是它和调用者之间的“约定”：我要求你给我 1 个 u32。
//    main 里写 `call_me()`，括号里空空的，只给了 0 个 → 违约 → E0061。
// 2. 补上一个 u32 类型的实参即可，比如 3：
//        call_me(3);
//    3 是整数字面量，编译器看到形参是 u32，就把它推断成 u32。
// 3. 运行后 num = 3，`for i in 0..3` 循环 3 次，打印 1、2、3。
// 4. 数字可以随便换：call_me(1) 只响 1 次，call_me(5) 响 5 次。
//
// ============================================================================
//                              知 识 铺 垫
// ============================================================================
//
// ● 形参（parameter）和实参（argument）
//       fn call_me(num: u32) { ... }    // num 叫形参：定义时的“占位符”
//       call_me(3);                      // 3 叫实参：调用时真正的值
//   调用时，实参会被“按位置”交给形参：第 1 个实参 → 第 1 个形参，
//   第 2 个实参 → 第 2 个形参，依此类推。
//   所以顺序很重要：`fn sub(a: i32, b: i32)` 里 sub(10, 3) 得到 7，
//   sub(3, 10) 得到 -7，完全不同的结果。
//
// ● 个数必须一致
//   Rust 不支持“默认参数”（不像 Python 可以给参数设默认值），
//   也不支持“可变参数”（不像 C 的 printf）。
//   因此：**定义了几个参数，调用时就必须给几个**。
//   少了 → E0061（本次的错误）；多了 → 同样 E0061，提示变成
//   "this function takes 1 argument but 2 arguments were supplied"。
//
// ● E0061 报错怎么读？
//       error[E0061]: this function takes 1 argument but 0 arguments were supplied
//     ├─ this function takes 1 argument ：函数声明需要 1 个参数
//     └─ but 0 arguments were supplied  ：实际只给了 0 个
//   编译器通常还会附一行 `help: provide the argument`，把正确的调用写给你看。
//
// ● 为什么不干脆把函数的参数删掉？
//   函数体里用到了 num（0..num），删掉形参 num 会引发新的错误
//   （cannot find value `num`）。而且“让函数知道响几次”本来就是设计意图，
//   正确做法是调用者把次数传进去。
//
// ● u32 与字面量 3
//   `3` 默认会推断成 i32，但如果上下文（这里是形参类型）要求 u32，
//   它就会变成 u32。这叫“类型推断跟着上下文走”。
//   想强制指定可以写 `3u32`，但本题没必要。
//
// ● 函数调用的值
//   call_me 没有返回值（返回类型是 ()），所以 `let x = call_me(3);` 里的 x
//   会是 ()，没什么用。有返回值的函数才可以把结果接住，见 functions4、functions5。
//
// ============================================================================
//                              参 考 答 案
// ============================================================================

fn main() {
    // 补上实参 3：函数要 1 个 u32，这里就给 1 个整数
    // 3 的类型会被推断为 u32（跟随形参类型）
    call_me(3);
}

// 这个函数是原题就有的，一个字都不用改
// 它接收一个 u32，然后响 num 次铃
fn call_me(num: u32) {
    // i 依次取 0、1、2（0..3 左闭右开，不含 3）
    for i in 0..num {
        // 打印编号时用 i + 1，让编号从 1 开始
        println!("Ring! Call number {}", i + 1);
    }
}

// ============================================================================
//                            逐 行 解 析
// ============================================================================
//
// call_me(3);
//   ├─ call_me ：函数名
//   ├─ (       ：实参列表开始
//   ├─ 3       ：第 1 个实参 → 交给形参 num
//   ├─ )       ：实参列表结束
//   └─ ;       ：语句结束
//
// fn call_me(num: u32) { ... }
//   └─ 形参 num 收到 3，函数体里所有 num 都等于 3
//
// for i in 0..num { println!("Ring! Call number {}", i + 1); }
//   第 1 轮：i=0 → 打印 Ring! Call number 1
//   第 2 轮：i=1 → 打印 Ring! Call number 2
//   第 3 轮：i=2 → 打印 Ring! Call number 3
//   i=3 时 3 < 3 不成立，循环结束
//
// ============================================================================
//                          常 见 错 误 与 提 示
// ============================================================================
//
// 1. 不传参数（= 原题状态）：
//        call_me();
//    → error[E0061]: this function takes 1 argument but 0 arguments were supplied
//
// 2. 传多了：
//        call_me(3, 4);
//    → error[E0061]: this function takes 1 argument but 2 arguments were supplied
//
// 3. 传了负数：
//        call_me(-3);
//    → error: cannot apply unary operator `-` to type `u32`
//      （u32 装不下负数；确实需要负数就改用 i32，并同步修改形参类型）
//
// 4. 传了字符串：
//        call_me("3");
//    → error[E0308]: mismatched types（期望 u32，实际是 &str）
//    字符串转数字要用 "3".parse::<u32>()（后续课程内容）。
//
// 5. 调用时漏了括号或逗号：
//        call_me;        // 不报错，但函数根本不会执行
//        call_me(3      // error: expected `)`, found `;`
//
// 6. 以为可以给参数默认值：
//        fn call_me(num: u32 = 3) { }   // ❌ Rust 没有默认参数
//    → error: expected type, found `=`
//
// ============================================================================
//                          小 结
// ============================================================================
//
// 本题你需要记住：
//   1. 调用函数要写“函数名(实参1, 实参2, ...)”；
//   2. 实参的个数、顺序、类型都要和形参对得上；
//   3. 个数不对会报 E0061，类型不对会报 E0308；
//   4. 整数字面量的类型会跟随上下文推断（3 可以是 u32）；
//   5. Rust 没有默认参数，也没有可变参数。
//
// 一句话记忆：**函数签名是合同，几个参数就得给几个，少一个都不行。**
//
