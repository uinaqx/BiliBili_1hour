// ============================================================================
// 第 38 题 · strings1 —— 返回 String：把借来的字面量变成自己的数据
// ----------------------------------------------------------------------------
// 题目类型：compile（把代码改到能编译通过就算过关）
// 课件位置：第 3 章 · 3.1 字符串与切片（String 与 &str 的区别、String::from）
// 难度：★★☆☆☆
// 前置知识：变量与函数返回值（functions4、functions5）、所有权与移动（move_semantics1）
// ============================================================================
//
// 【题目要求】
// 在不修改函数签名的前提下让代码编译通过。
// 也就是说 `fn current_favorite_color() -> String` 这一行必须原样保留，
// 只能改函数体。
//
// 原题代码（未完成，仅供对照）：
//     fn main() {
//         let answer = current_favorite_color();
//         println!("My current favorite color is {}", answer);
//     }
//
//     fn current_favorite_color() -> String {
//         "blue"
//     }
//
// 编译器会报：
//     error[E0308]: mismatched types
//       expected `String`, found `&str`
//
// 【解题思路】
// 1. 函数声明返回 `String`（拥有堆上数据的字符串），
//    但函数体最后一行 `"blue"` 是一个**字符串字面量**，它的类型是 `&'static str`
//    （指向程序二进制里一段只读文本的借用），不是 String。
// 2. Rust 不会偷偷帮你把 &str 变成 String（那需要分配堆内存，Rust 不喜欢隐式分配）。
//    所以必须显式转换。
// 3. 最直接的两种写法：
//        String::from("blue")
//        "blue".to_string()
//    两者都会在堆上新建一份 "blue"，返回类型正好是 String。
// 4. 函数体最后一行不要写分号：它的值就是函数的返回值（参考 functions5）。
//
// ============================================================================
//                              知 识 铺 垫
// ============================================================================
//
// ● Rust 里有两个常用的“字符串”类型
//   1. `&str` —— 字符串切片，读作“and str”，是**借用**来的文本视图。
//      它由两部分组成：一个指向文本首字节的指针 + 一个长度（这叫“胖指针”）。
//      它不拥有文本，不能扩容，文本放在哪里由别人决定。
//   2. `String` —— 拥有所有权的、可增长的字符串，文本存在**堆**上。
//      它由三部分组成：指针 + 长度 + 容量（capacity），可以 push_str 追加内容。
//
// ● 字符串字面量 `"blue"` 是什么类型？
//   类型是 `&'static str`：
//   - `&`      表示借用；
//   - `'static` 表示这份数据活得和整个程序一样久；
//   - `str`    表示一段 UTF-8 文本。
//   字面量的字节被直接编进可执行文件里（只读区），程序运行时不需要为它分配内存。
//   所以它天生就是“借来的”，不可能直接当成“自己拥有的 String”返回。
//
// ● 打个比方
//   `&str` 像“图书馆里一本书的页码索引”：告诉你内容在第几页、多长，
//   但书不是你的，你也不能往书里加页。
//   `String` 像“你自己复印了一本，还留了空白页”：书归你，可以随时往后加内容，
//   不要了要由你负责扔掉（Rust 会自动 drop）。
//
// ● 转换的几种写法（都合法）
//   String::from("blue")   // 调用 String 的关联函数 from
//   "blue".to_string()     // ToString 特征提供的方法
//   "blue".to_owned()      // ToOwned 特征提供的方法（&str → String）
//   "blue".into()          // Into 特征，靠返回值类型推断成 String
//   这些都会在堆上分配并复制一份文本，得到拥有所有权的 String。
//
// ● `String::from` 里的 `::` 是什么？
//   叫“路径分隔符”，表示“String 类型里的关联函数 from”。
//   关联函数类似其他语言的“静态方法”，用 `类型::函数名(...)` 调用，
//   不需要先有一个 String 实例。
//
// ● 为什么 println! 两种都能打印？
//   `{}` 需要 Display 特征。String 和 &str 都实现了 Display，所以都能直接打印。
//   本题的打印不是问题，问题只出在“返回值类型对不上”。
//
// ============================================================================
//                              参 考 答 案
// ============================================================================

fn main() {
    // answer 的类型由函数返回值决定，是 String（拥有堆上的 "blue"）
    let answer = current_favorite_color();
    // Display 打印：String 和 &str 都支持 {}
    println!("My current favorite color is {}", answer);
    // main 结束时 answer 离开作用域，String 的堆内存被自动释放（drop）
}

// 签名保持不变：返回 String（拥有所有权）
fn current_favorite_color() -> String {
    // 把 &'static str 转成 String：在堆上分配并复制 "blue"
    // 最后一行不加分号，这个 String 就是函数的返回值
    String::from("blue")
}

// ============================================================================
//                            详 细 解 析
// ============================================================================
//
// 1）`String::from("blue")` 内部发生了什么？
//    ① 在堆上申请一块能放下 4 个字节（b、l、u、e）的内存；
//    ② 把这 4 个字节从只读区复制过去；
//    ③ 返回一个 String，里面记录“指针、长度 4、容量（至少 4）”。
//    从此这份文本归返回值所有，函数返回时所有权移交给 main 里的 answer。
//
// 2）为什么不能直接写 `"blue"`？
//    因为 `"blue"` 的类型是 &str，而函数承诺返回 String，类型不匹配：
//        expected `String`, found `&str`
//    Rust 的规则是“类型必须严格匹配”，不会自动做“分配 + 复制”这种有代价的转换。
//
// 3）那能不能把签名改成 `-> &str`？
//    改成 `fn current_favorite_color() -> &str { "blue" }` 其实能编译
//    （字面量是 'static，活得很久），但题目明确要求**不修改函数签名**。
//    而且真实项目里返回值一旦改成借用，调用方就得关心“这份文本能活多久”，
//    所以“返回值需要独立存在”时，返回 String 是更常见的选择。
//
// 4）`to_string()` 和 `String::from()` 有区别吗？
//    结果一样，都是新建一个 String。区别在来源：
//    - String::from 走 From<&str> 实现；
//    - to_string 走 ToString 特征（任何实现了 Display 的类型都能 to_string）。
//    初学阶段任选一种，能读懂别人两种写法即可。
//
// 5）如果函数体写两行呢？
//        let s = String::from("blue");
//        s
//    也完全可以：s 被移动到返回值的位置。最后一行仍然不能加分号，
//    否则函数返回 ()，又会类型不匹配。
//
// 6）String 在内存里到底存了什么？（理解两种字符串的关键）
//    String 变量本身（在栈上）存三块信息：
//        ┌───────────┬───────────┬───────────┐
//        │ ptr 指针   │ len 长度   │ cap 容量   │
//        └─────┬─────┴───────────┴───────────┘
//              │
//              ▼
//        堆内存：b l u e（cap 个字节的空间，可以继续追加）
//
//    &str 只有两块信息：ptr + len。它不知道“这块内存还能写多长”，
//    也不负责释放，所以不能 push、不能扩容。
//    从 &str 变成 String，本质上是“新申请一块堆内存 + 复制内容 + 补上 cap”，
//    所以必须显式写转换方法，不能靠隐式规则完成。
//
// 7）转换之后，原来的字面量会怎样？
//    字面量 "blue" 仍然留在程序的只读数据区，不受影响；
//    String::from 只是复制了它的内容。两者各自独立、互不干扰。
//    这也是为什么修改 String 不会影响别处使用同一个字面量的代码。
//
// ============================================================================
//                          常 见 错 误 与 提 示
// ============================================================================
//
// 1. 不改函数体：
//    → error[E0308]: mismatched types
//       expected `String`, found `&str`
//
// 2. 在字面量前加 &：
//        &"blue"
//    → 类型是 &&str，错得更远：expected `String`, found `&&str`
//
// 3. 忘了括号：
//        "blue".to_string
//    → error[E0308]: expected `String`, found function item
//    （方法要调用必须加 `()`）
//
// 4. 写成 `String::from(blue)`（没加引号）：
//    → error[E0425]: cannot find value `blue` in this scope
//
// 5. 画蛇添足加 `&String::from("blue")`：
//    → expected `String`, found `&String`
//
// 6. 在最后一行加了分号：
//        String::from("blue");
//    → 函数返回 ()，error[E0308]: expected `String`, found `()`
//
// 7. 把返回类型改成 `&str`：
//    虽然可能编译通过，但违反了“不修改函数签名”的题目要求，
//    也不是本题想训练的“创建拥有所有权的 String”这一知识点。
//
// 8. 用 `return` 关键字时忘了返回值：
//        return;
//    → expected `String`, found `()`
//
// 9. 想用 `String + &str` 的方式返回但左边不是 String：
//        "blue" + ""
//    → error[E0369]: cannot add `&str` to `&str`
//    （+ 的左边必须是 String，右边才是 &str）
//
// 10. 以为 `format!("blue")` 和 `String::from("blue")` 有性能差别：
//     两者最终都会分配一个 String，初学阶段不用纠结，选可读性好的即可。
//
// ============================================================================
//                          小 结
// ============================================================================
//
// 本题你需要记住：
//   1. `"文字"` 的类型是 `&'static str`，是借用，不拥有内存；
//   2. `String` 拥有堆上的文本，可以增长，离开作用域自动释放；
//   3. `&str` 不会自动变成 `String`，要显式写 `String::from(...)` 或 `.to_string()`；
//   4. 函数最后一行不加分号，它的值就是返回值；
//   5. `类型::函数()` 是关联函数的调用方式。
//
// 一句话记忆：**字面量是“借来的书”，返回 String 就是“自己复印一本”。**
//
