// ============================================================================
// 第 35 题 · enums1 —— 用枚举表示“几种可能之一”
// ----------------------------------------------------------------------------
// 题目类型：compile（把代码改到能编译通过就算过关）
// 课件位置：第 3 章 · 3.4 枚举（3.4.1 定义枚举、无数据变体）
// 难度：★★☆☆☆
// 前置知识：会用 println! 和 {:?}（参考 intro1、variables1）；知道 struct 是“打包数据”（参考 structs1）
// ============================================================================
//
// 【题目要求】
// 原题的 enum Message 是空的，但 main 里却用了 Message::Quit、Message::Echo、
// Message::Move、Message::ChangeColor 四种值。请把 enum 补完整，让代码编译通过。
//
// 原题代码（未完成，仅供对照）：
//     #[derive(Debug)]
//     enum Message {
//         // TODO: define a few types of messages as used below
//     }
//
//     fn main() {
//         println!("{:?}", Message::Quit);
//         println!("{:?}", Message::Echo);
//         println!("{:?}", Message::Move);
//         println!("{:?}", Message::ChangeColor);
//     }
//
// 【解题思路】
// 1. 先看 main 里写了什么：Message::Quit 这种写法表示“从 Message 这个类型里
//    取出一个叫 Quit 的成员”。这种成员在 Rust 里叫“变体（variant）”。
// 2. 编译器只在 enum 的定义里找变体。原题定义是空的 `{ }`，所以它会报：
//        error[E0599]: no variant or associated item named `Quit` found for enum `Message`
// 3. 既然 main 用到了四个名字（Quit、Echo、Move、ChangeColor），就在 enum 里
//    把这四个名字都声明一遍。
// 4. 注意：这四个变体后面都**没有括号、也没有花括号**，说明它们不带任何数据，
//    这种变体叫“单元变体（unit variant）”，写法就是 `名字,`。
// 5. 每个变体之间用逗号分隔；最后一个变体后面的逗号可有可无（建议保留）。
//
// ============================================================================
//                              知 识 铺 垫
// ============================================================================
//
// ● 枚举（enum）是什么？
//   生活里的“单选题”：答案只能是 A、B、C、D 中的一个，不可能同时是 A 和 B。
//   enum 就是用来描述“一个值只能是这几种情况之一”的类型。
//   例如一个消息，要么是“退出”，要么是“回显”，要么是“移动”，要么是“改颜色”。
//
// ● 定义语法
//     enum 类型名 {
//         变体1,
//         变体2,
//         变体3,
//     }
//   - `enum` 是关键字（enumeration 的缩写）；
//   - 类型名和变体名都用“大驼峰”写法（Quit、ChangeColor），
//     这是 Rust 的命名习惯，不遵守只会警告不会报错；
//   - 变体之间用逗号 `,`，不是分号 `;`；
//   - 变体不需要写 `= 0` 这样的数字（Rust 的 enum 不是 C 那种整数常量）。
//
// ● 怎么“使用”一个变体？
//     Message::Quit
//   `::` 读作“路径分隔符”，意思类似“Message 类型下面的 Quit”。
//   注意这里是双冒号 `::`，不是结构体字段访问用的单点 `.`。
//
// ● 变体的三种“体型”（本题只用第一种，enums2 会用后两种）
//   1. 单元变体：不带数据            Quit
//   2. 元组变体：带若干个无名数据    Echo(String)、ChangeColor(u8, u8, u8)
//   3. 结构体变体：带若干有名数据    Move { x: i32, y: i32 }
//
// ● #[derive(Debug)] 是什么？
//   以 `#[...]` 开头的东西叫“属性（attribute）”，是给编译器的说明。
//   `derive(Debug)` 的意思是：请编译器自动帮我实现 Debug 这个特征（trait），
//   实现了 Debug 的类型才能用 `{:?}` 打印出来。
//   如果不写这一行，`println!("{:?}", ...)` 会报错：
//        error[E0277]: `Message` doesn't implement `Debug`
//
// ● `{}` 和 `{:?}` 的区别
//   `{}`  调用 Display，面向“给人看的漂亮输出”，不是所有类型都有；
//   `{:?}` 调用 Debug，面向“给程序员看的调试输出”，用 derive 就能自动获得。
//   对枚举来说，Debug 输出会直接印出变体的名字，比如 `Quit`。
//
// ============================================================================
//                              参 考 答 案
// ============================================================================

// 属性：让编译器自动为 Message 实现 Debug，这样 {:?} 才能打印
#[derive(Debug)]
enum Message {
    // 四个“单元变体”：只有名字，不携带任何数据
    Quit,        // 退出消息
    Echo,        // 回显消息
    Move,        // 移动消息
    ChangeColor, // 改变颜色消息
    // 末尾这个逗号可以省略；保留它以后再加变体更方便
}

fn main() {
    // `Message::Quit`：拼出一个“Message 类型的 Quit 变体”的值
    // `{:?}`        ：用 Debug 格式打印，枚举会显示变体名
    println!("{:?}", Message::Quit);

    // 同一个 enum 的不同变体，值的类型都是 Message
    println!("{:?}", Message::Echo);
    println!("{:?}", Message::Move);
    println!("{:?}", Message::ChangeColor);
}

// ============================================================================
//                            详 细 解 析
// ============================================================================
//
// 1）为什么四个变体都不带括号？
//    看 main 的写法：Message::Quit 后面没有 `(...)`，说明它不是函数调用；
//    如果定义成 `Quit(String)` 这种带数据的变体，那 main 里就必须写
//    `Message::Quit(String::from("..."))` 才能构造出值。
//    题目只写名字，所以定义成单元变体最合适。
//
// 2）枚举值在内存里长什么样？
//    一个 enum 变量同一时刻只保存“其中一个变体”。可以把它想象成一个贴了标签
//    的盒子：标签说明现在装的是哪一种，盒子大小按“最大的那个变体”来算。
//    本题四个变体都不带数据，所以 Message 只占一个很小的标签（通常是 1 字节）。
//
// 3）为什么不写 `Message::Quit = 0`？
//    C/Java 的枚举常常对应整数 0、1、2；Rust 的枚举是真正的“代数数据类型”，
//    变体是独立的值，不是数字常量。你也不能对 Message 做 `+ 1` 这种运算。
//
// 4）`let m = Message::Quit;` 合法吗？
//    合法。m 的类型就是 Message。但要注意：m 里存的是 Quit，它不“等于”字符串
//    "Quit"，也不等于 0；想知道它具体是哪个变体，要用 match（见 enums3）。
//
// 5）四个 println! 的输出分别是什么？
//    Debug 对单元变体的输出就是变体名本身：
//        Quit
//        Echo
//        Move
//        ChangeColor
//
// ============================================================================
//                          常 见 错 误 与 提 示
// ============================================================================
//
// 1. 忘了声明某个变体（比如漏了 ChangeColor）：
//    → error[E0599]: no variant or associated item named `ChangeColor` found
//      for enum `Message`
//
// 2. 变体之间写成分号：
//        Quit; Echo;
//    → error: expected `,`, found `;`
//
// 3. 用点号访问变体：
//        Message.Quit
//    → error[E0599] / expected value, found enum `Message`
//    （枚举变体用 `::`，单点 `.` 是访问结构体字段或调用方法用的）
//
// 4. 删掉了 #[derive(Debug)]：
//    → error[E0277]: `Message` doesn't implement `Debug`
//       help: consider annotating `Message` with `#[derive(Debug)]`
//
// 5. 用 `{}` 而不是 `{:?}` 打印：
//    → error[E0277]: `Message` doesn't implement `Display`
//    （Display 需要手写实现，本题没要求，直接用 {:?} 即可）
//
// 6. 变体名写成小写 `quit`：
//    → warning: variant `quit` should have an upper camel case name
//    虽然只是警告，但请养成大驼峰命名的习惯。
//
// 7. 把 derive 的括号写错，比如 `#[derive(Debug]`：
//    → error: expected `)`, found `]`
//
// ============================================================================
//                          小 结
// ============================================================================
//
// 本题你需要记住：
//   1. `enum 名字 { 变体1, 变体2, ... }` 定义枚举；
//   2. 变体用 `类型名::变体名` 访问；
//   3. 不带数据的变体叫单元变体，只写名字；
//   4. `#[derive(Debug)]` 让类型可以用 `{:?}` 打印；
//   5. 一个枚举值同一时刻只属于一个变体，这正是“几选一”的建模方式。
//
// 一句话记忆：**枚举 = 一张只能勾一个选项的单选题，选项用 `类型::变体` 表示。**
//
