// ============================================================================
// 第 04 题 · variables2 —— 先给变量一个值，再拿它去比较
// ----------------------------------------------------------------------------
// 题目类型：compile（把代码改到能编译通过就算过关）
// 课件位置：第 2 章 · 2.2.1 数值类型与类型推断（整型默认 i32）、2.1.1 变量绑定
// 难度：★☆☆☆☆
// 前置知识：variables1（let、i32）、intro1（if 不是必须的，本题顺带见到）
// ============================================================================
//
// 【题目要求】
// 让代码判断 x 是不是 10，并打印对应结果。原题里 x 只被“声明”了，没被“赋值”。
//
// 原题代码（未完成，仅供对照）：
//     fn main() {
//         let x;
//         if x == 10 {
//             println!("x is ten!");
//         } else {
//             println!("x is not ten!");
//         }
//     }
//
// 编译会报错：
//     error[E0381]: used binding `x` isn't initialized
//     （用到了变量 x，但它还没有被初始化）
//
// 【解题思路】
// 1. `let x;` 只做了“声明”：在编译器那里登记了一个名字 x，类型可以是 i32，
//    但**没有给它任何值**。此时 x 是一块“空着的格子”。
// 2. `if x == 10` 要拿 x 的值去和 10 比较，可是格子是空的，比不了 → E0381。
// 3. 解决办法：声明的时候就给值。`let x = 10;`
//    （写成 `let x: i32 = 10;` 也可以，等价的。）
// 4. 于是 x == 10 成立，程序打印 "x is ten!"。
//
// ============================================================================
//                              知 识 铺 垫
// ============================================================================
//
// ● 声明（declare）和初始化（initialize）是两件事
//     let x;          // 声明：有了名字，但还没有值
//     x = 10;         // 初始化：第一次把值放进去（这里是“赋值语句”）
//     let x = 10;     // 声明 + 初始化，一步到位（最常用）
//   在 Rust 里可以先声明后初始化，例如：
//       let x;
//       x = 10;
//       println!("{}", x);
//   这样是合法的，因为“使用 x 的那一刻”它已经有值了。
//   本题之所以不合法，是因为在 x 还空着的时候就用了它（顺序问题）。
//
// ● 为什么 Rust 不允许“用空变量”？
//   C 语言里 `int x;` 之后 x 是一个随机的垃圾值，用它参与比较会得到无法预测的
//   结果，这种 bug 极其难查（叫“未初始化读取”）。
//   Rust 直接在编译期拒绝：**变量必须先有值才能被读**。
//   这叫“确定性初始化”，是 Rust 内存安全的一部分。
//
// ● 类型推断（type inference）：为什么 `let x = 10;` 不用写类型？
//   编译器看到 10 这个整数，默认把它当成 **i32**（32 位有符号整数）。
//   i32 是 Rust 的“默认整数类型”，就像说“一个人”默认指成年人一样。
//   本题的 10 也是 i32，两边类型一致，比较合法。
//
// ● 整数家族速查（本节会遇到）
//     i8 / i16 / i32 / i64 / i128 / isize   有符号（i = integer，可负）
//     u8 / u16 / u32 / u64 / u128 / usize   无符号（u = unsigned，不可负）
//   数字后面的下划线只是给人看的：1_000_000 就是 1000000。
//   想显式指定类型，可以写 10i32，或者用类型标注：let x: i32 = 10;
//
// ● if / else 快速认识（第 4 章会展开）
//       if 条件 { 条件为真时执行 } else { 条件为假时执行 }
//   条件必须是 bool（true / false），不能像 C 那样写 if (x)。
//   `==` 是“判断相等”，注意是两个等号；一个等号 `=` 是赋值。
//
// ============================================================================
//                              参 考 答 案
// ============================================================================

fn main() {
    // 声明 x 并立刻赋初值 10，类型被推断为 i32（Rust 的默认整数类型）
    // 原题写的是 `let x;`（只有声明没有值），所以下面比较时读到空值报了 E0381
    let x = 10;

    // `if 条件 { ... } else { ... }`
    //   x == 10 是“判断相等”，结果是 bool（true 或 false）
    //   x 与 10 都是 i32，类型一致，比较合法
    if x == 10 {
        // 条件为 true 时执行这一行
        println!("x is ten!");
    } else {
        // 条件为 false 时执行这一行（本题不会走到这里）
        println!("x is not ten!");
    }
}

// ============================================================================
//                            逐 行 解 析
// ============================================================================
//
// let x = 10;
//   ├─ let    ：创建一个新的变量绑定
//   ├─ x      ：变量名
//   ├─ = 10   ：赋初值 10（不是“赋值语句”，而是绑定的一部分）
//   └─ ;      ：语句结束
//   类型推断：10 没有小数点、没有后缀 → 默认 i32
//
// if x == 10 { ... } else { ... }
//   ├─ if     ：条件分支关键字
//   ├─ x == 10：条件表达式，值是 true/false
//   ├─ { }    ：条件为真时执行的代码块
//   └─ else   ：否则执行另一个代码块
//
// println!("x is ten!");
//   └─ 打印 x is ten! 并换行
//
// ============================================================================
//                          常 见 错 误 与 提 示
// ============================================================================
//
// 1. 保持 `let x;` 不变（= 原题状态）：
//    → error[E0381]: used binding `x` isn't initialized
//
// 2. 把比较写成赋值：
//        if x = 10 {
//    → error[E0308]: mismatched types（if 需要 bool，而 x = 10 的类型是 ()）
//
// 3. 用字符串去和整数比：
//        let x = "10";
//        if x == 10 {
//    → error[E0308]: mismatched types（&str 和整数不能比较）
//
// 4. 用浮点数：
//        let x = 10.0;
//        if x == 10 {
//    → error[E0308]: mismatched types（f64 和 i32 不能直接比较）
//    想比的话两边都写 10.0。
//
// 5. 声明成别的整数类型再比也完全可以：
//        let x: u32 = 10;   // u32 和 i32 的 10 比较？
//    → 这里 x == 10 其实也合法，因为 10 这个字面量会“入乡随俗”地推断成 u32。
//    记住：**整数字面量的类型跟着上下文走**。
//
// ============================================================================
//                          小 结
// ============================================================================
//
// 本题你需要记住：
//   1. `let x;` 只是声明，变量还没有值；
//   2. Rust 禁止在变量没有值时读取它（E0381）；
//   3. 最省事的办法：声明时就赋值 `let x = 10;`；
//   4. 整数默认类型是 i32，整数字面量的类型会随上下文推断；
//   5. `==` 是比较，`=` 是赋值，if 的条件必须是 bool。
//
// 一句话记忆：**声明只是腾出格子，赋值才把东西放进去；空格子不许读。**
//
