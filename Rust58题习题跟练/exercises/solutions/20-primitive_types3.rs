// ============================================================================
// 第 20 题 · primitive_types3 —— 用 [值; 长度] 快速创建大数组
// ----------------------------------------------------------------------------
// 题目类型：compile（把代码补全到能编译通过、运行不 panic 就算过关）
// 课件位置：第 3 章 · 3.5 数组 [T; N] 与 [值; 长度] 初始化写法
// 难度：★★☆☆☆
// 前置知识：let 变量、if / else（if1）、整数类型（2.2.1）
// ============================================================================
//
// 【题目要求】
// 在原题留出的占位处创建一个**至少 100 个元素**的数组。
// 数组长度不够的话，程序会走 else 分支并主动 panic（崩溃）。
// 原题代码（未完成，仅供对照）：
//     fn main() {
//         let a = /* 原题此处是待填写的占位符 */
//
//         if a.len() >= 100 {
//             println!("Wow, that's a big array!");
//         } else {
//             println!("Meh, I eat arrays like that for breakfast.");
//             panic!("Array not big enough, more elements needed")
//         }
//     }
//
// 【解题思路】
// 1. 题目要“至少 100 个元素”，但显然不可能手动敲 100 个 0。
// 2. Rust 提供了一种“重复初始化”语法：
//        [值; 长度]
//    例如 `[0; 100]` 表示“100 个 0 组成的数组”。
// 3. 于是 a = [0; 100]，长度正好 100，a.len() >= 100 成立，
//    走 if 分支打印 "Wow, that's a big array!"。
// 4. 想更保险可以写 `[0; 128]` 或 `[0; 200]`，都符合“至少 100”的要求。
//
// ============================================================================
//                              知 识 铺 垫
// ============================================================================
//
// ● 数组（array）是什么？
//   let a = [1, 2, 3, 4, 5];
//   数组是“长度固定、元素类型相同、在内存中连续存放”的容器。
//   它的完整类型写作 [T; N]：
//     T = 元素类型，N = 元素个数（必须是编译期就能确定的常量）
//   比如 [i32; 5]、[char; 3]、[&str; 2]。
//
// ● 三种创建数组的写法
//     1) 逐个列出：   let a = [10, 20, 30];
//     2) 重复同一个值：[0; 100]        ← 本题要用这个
//     3) 先声明类型再给值：let a: [u8; 4] = [1, 2, 3, 4];
//   `[值; 长度]` 里的分号不能换成逗号，长度必须是无符号整数常量。
//
// ● 数组放在哪里？长度为什么必须编译期确定？
//   数组默认放在**栈（stack）**上，栈要求每块数据的大小在编译时已知，
//   所以 [T; N] 的 N 必须是常量。要“长度能变”的容器请用 Vec（第 24 题 vecs1）。
//   注意：`[0; n]` 里的 n 若是变量，会报 E0435（不是常量）。
//
// ● len() 方法
//     a.len()  → 元素个数，类型是 usize（无符号整数，专门表示长度/下标）
//   本题的 `a.len() >= 100` 就是拿这个数和 100 比较。
//   （usize 和 i32 比较？这里 100 会被推断成 usize，两边类型一致才能比较。）
//
// ● 元素类型是怎么推断出来的？
//   写 [0; 100] 时，元素的类型没写，编译器默认用 i32（整数默认类型）。
//   如果写 [0u8; 100]，元素类型就是 u8。本题两种都可以。
//
// ● `[0; 100]` 对元素类型有一个隐含要求：元素必须实现 Copy
//   因为要“复制”100 份。整数、bool、char、&str 都是 Copy；
//   String 不是 Copy，所以 `[String::from("hi"); 3]` 会报错。
//
// ● panic! 是什么？
//   panic! 是“主动让程序崩溃”的宏，用于遇到无法继续的错误。
//   本题在长度不足时会 panic，程序以非 0 状态退出并打印错误信息。
//   注意：只要数组够长，就不会执行到那一行。
//
// ● 如果数组不够长会怎样？
//   会先打印 "Meh, I eat arrays like that for breakfast."，然后 panic。
//   所以本题要“既编译通过、又运行不崩”，必须真的放够 100 个元素。
//
// ============================================================================
//                              参 考 答 案
// ============================================================================

fn main() {
    // [0; 100]：创建 100 个 0 组成的数组
    //   ├─ 0    ：每个元素的值（类型推断为 i32）
    //   ├─ ;    ：固定用分号分隔“值”和“长度”
    //   └─ 100  ：元素个数，必须是编译期常量
    // 等价于手写 100 个 0：let a = [0, 0, 0, ...];（显然不会有人这么干）
    let a = [0; 100];

    // a.len() 返回元素个数（usize 类型），这里是 100
    // 100 >= 100 成立 → 进入 if 分支
    if a.len() >= 100 {
        println!("Wow, that's a big array!");
    } else {
        // 长度不足时会走到这里：先打印一句吐槽，然后主动崩溃
        println!("Meh, I eat arrays like that for breakfast.");
        panic!("Array not big enough, more elements needed")
        // 注意：panic! 末尾没写分号，因为它在这里是“发散表达式”，
        // 类型是 !（never），永远不会正常返回。
    }
}

// ============================================================================
//                            逐 行 解 析
// ============================================================================
//
// let a = [0; 100];
//   ├─ let        ：声明变量
//   ├─ a          ：变量名
//   ├─ [0; 100]   ：数组字面量：100 个 0
//   └─ ;          ：语句结束
//   得到的类型是 [i32; 100]，占 400 字节（每个 i32 4 字节），放在栈上。
//
// a.len()
//   └─ 返回 usize 类型的 100；usize 是“指针大小”的无符号整数，常用来表示长度、下标。
//
// if a.len() >= 100 { ... } else { ... }
//   ├─ 条件成立 → 打印 Wow...
//   └─ 条件不成立 → 打印 Meh... 并 panic
//
// ============================================================================
//                          常 见 错 误 与 提 示
// ============================================================================
//
// 1. 只写 99 个（差一个）：
//        let a = [0; 99];
//    → 运行期 panic: Array not big enough, more elements needed
//
// 2. 用逗号代替分号：
//        let a = [0, 100];
//    → 编译通过，但这是“两个元素 0 和 100”的数组，长度只有 2，
//      运行时 panic（这是很容易踩的坑：符号错了不报编译错，只是逻辑错）
//
// 3. 长度写成变量：
//        let n = 100;  let a = [0; n];
//    → error[E0435]: attempt to use a non-constant value in a constant
//    （数组长度必须是编译期常量；要动态长度请用 Vec）
//
// 4. 元素类型不是 Copy：
//        let a = [String::from("x"); 100];
//    → error[E0277]: the trait bound `String: Copy` is not satisfied
//
// 5. 忘了分号：
//        let a = [0; 100]
//    → error: expected `;`, found `if`
//
// 6. 想要“看清元素个数”就把类型写死成更小的类型再堆很多元素：
//        let a = [0u8; 100];   // 也可以，100 个 u8 共 100 字节
//    类型不影响本题判定，只要 len() >= 100。
//
// ============================================================================
//                          小 结
// ============================================================================
//
// 本题你需要记住：
//   1. 数组类型是 [T; N]，长度固定、编译期已知、放栈上；
//   2. `[值; 长度]` 可以快速创建“同一个值重复 N 次”的数组；
//   3. len() 返回元素个数（usize）；
//   4. 需要可变长度时改用 Vec（下一批题目 vecs1 会讲）。
//
// 一句话记忆：**`[0; 100]` 就是“100 个 0”，分号左边是值、右边是个数。**
//
