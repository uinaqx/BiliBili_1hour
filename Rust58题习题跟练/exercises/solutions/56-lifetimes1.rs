// ============================================================================
// 第 56 题 · lifetimes1 —— 生命周期标注：给“借来的东西”标上期限
// ----------------------------------------------------------------------------
// 题目类型：compile（把代码改到能编译通过就算过关）
// 课件位置：第 6 章 · 6.2 生命周期（函数签名中的生命周期标注）
// 难度：★★★★☆
// 前置知识：引用与借用（第 30 题 move_semantics5）、&str（strings1）、泛型（第 48 题）
// ============================================================================
//
// 【题目要求】
// 让 longest 函数编译通过。它的功能是：比较两个字符串切片，返回较长的那个。
// 函数名、参数、函数体都不能改，只能补上生命周期标注。
//
// 原题代码（未完成，仅供对照）：
//     fn longest(x: &str, y: &str) -> &str {
//         if x.len() > y.len() {
//             x
//         } else {
//             y
//         }
//     }
//
// 编译器会报：
//     error[E0106]: missing lifetime specifier
//     help: this function's return type contains a borrowed value, but the
//           signature does not say whether it is borrowed from `x` or `y`
//
// 【解题思路】
// 1. 先读懂编译器的抱怨：返回值 `&str` 是个借用，
//    可它到底借自 x 还是借自 y？光看签名看不出来，编译器拒绝猜。
// 2. 解决办法：在函数名后加一个生命周期参数 `<'a>`，
//    并把两个参数和返回值都标成 `&'a str`：
//        fn longest<'a>(x: &'a str, y: &'a str) -> &'a str
// 3. 这句话的含义是：“x、y、返回值这三者，用的是同一个期限 'a；
//    返回的引用活不过 'a。”
// 4. 函数体一个字都不用改 —— 有了签名上的承诺，编译器就能做检查了。
//
// ============================================================================
//                              知 识 铺 垫
// ============================================================================
//
// ● 先复习：引用是“借来的”
//       let s = String::from("hello");   // s 是所有者
//       let r = &s;                      // r 借了 s 的地址，不拥有数据
//   借来的东西有个铁律：**借用不能比主人活得久**。
//   否则主人已经把数据释放了，你手里的引用就成了“悬垂引用（dangling reference）”，
//   指向一块已经不属于你的内存 —— C 语言里这是经典 bug 来源。
//   Rust 的借用检查器（borrow checker）会在编译期把这种代码全部拦下来。
//
// ● “生命周期（lifetime）”到底是什么？
//   它不是运行时的计时器，而是**编译期的一个名字**，
//   用来描述“这个引用从哪活到哪”。写成 `'a`（读作“tick a”或“生命周期 a”）。
//   你可以把它理解成“借书合同上的租期编号”：
//        'a 不是具体的日期，而是合同上的一个代号，
//        具体是哪段时间，由借用检查器根据调用现场自动填。
//   所以标注生命周期**不会**让任何东西活得更久，
//   它只是把你的意图写清楚，让编译器有据可查。这一点一定要记住。
//
// ● 为什么这里必须标注？
//   如果只有一个参数（一个输入引用），Rust 有“省略规则（elision）”：
//        fn f(x: &str) -> &str           // 自动理解为 fn f<'a>(x: &'a str) -> &'a str
//   但本题有**两个**输入引用，返回值可以来自 x 也可以来自 y，
//   省略规则失效，编译器无法推断，只能要求你手写。
//
// ● `<'a>` 和 `<T>` 长得一样，区别是什么？
//   尖括号里放的是“参数”。放 T 是类型参数，放 'a 是生命周期参数。
//   两者可以同时出现：
//        fn f<'a, T>(x: &'a T) -> &'a T
//   本题只有生命周期参数。
//
// ● 返回值 `'a` 到底选了哪个期限？
//   当两个参数都标成同一个 'a 时，'a 取的是**两者中较短的那个**
//   （准确说：'a 必须同时满足“不长于 x 的借用”和“不长于 y 的借用”）。
//   打个比方：你向两个人分别借了书，两本书的归还日期不同，
//   那么你只能承诺“在最晚归还日之前还”—— 取交集，也就是较短的那个。
//   （第 57 题 lifetimes2 就是踩在这个点上。）
//
// ● 函数体为什么不需要改？
//   签名已经承诺“返回值和 x、y 同属 'a”，
//   而 `if` 的两个分支分别返回 x、y，都满足这个承诺。
//   编译器检查通过，无需任何运行时操作 —— 生命周期完全是编译期概念，零开销。
//
// ============================================================================
//                              参 考 答 案
// ============================================================================

// <'a> 声明一个生命周期参数 'a
// x: &'a str —— x 是借用，期限为 'a
// y: &'a str —— y 也是借用，期限同为 'a
// -> &'a str —— 返回的引用也在这段期限内（不会比 x、y 活得更久）
fn longest<'a>(x: &'a str, y: &'a str) -> &'a str {
    // len() 返回字符串的字节长度（usize），比较大小
    if x.len() > y.len() {
        // 返回 x（类型 &'a str），与返回类型匹配
        x
    } else {
        // 否则返回 y（同样是 &'a str）
        y
    }
    // 注意：if/else 是表达式，两个分支的类型必须一致，这里都是 &'a str
}

fn main() {
    // string1 是一个拥有堆内存的 String
    let string1 = String::from("abcd");

    // string2 是字符串字面量，类型 &'static str（'static 表示“活到程序结束”）
    let string2 = "xyz";

    // as_str()：把 String 借成 &str（不复制、不转移所有权）
    // 传给 longest 之后，返回值的期限不会超过 string1、string2 中较短的那个
    let result = longest(string1.as_str(), string2);

    // result 在 string1、string2 都还活着的时候使用，完全合法
    println!("The longest string is '{}'", result);
}

// ============================================================================
//                            详 细 解 析
// ============================================================================
//
// 1）签名 `fn longest<'a>(x: &'a str, y: &'a str) -> &'a str` 怎么读？
//    读作：“对于任意一个期限 'a，接收两个至少活到 'a 的字符串切片，
//           返回一个最多活到 'a 的字符串切片。”
//    注意“至少/最多”这两个词：
//      - 参数要求“至少活到 'a”（活得比 'a 久没问题，可以缩短借用）；
//      - 返回值保证“最多活到 'a”（不会超出 'a，调用者可以放心按 'a 使用）。
//
// 2）'a 具体是多长？调用时才定。
//    在 main 里，调用点是 `longest(string1.as_str(), string2)`，
//    借用检查器会算出：string1 活到 main 结束，string2 是 'static（更久），
//    所以 'a 可以是“从调用点到 result 最后一次使用”这段。
//    'a 绝不会超过任何一个实参的存活范围。
//
// 3）为什么不能给返回值写两个不同的期限？
//    有人会想写 `-> &'a str` 之外的东西，比如 `-> &'b str`（第二个参数的期限）。
//    但函数体里可能返回 x（属于 'a）也可能返回 y（属于 'b），
//    编译器要求两个分支类型一致，所以只能取“共同的那段”，也就是 'a。
//    这也是为什么两个参数必须标成**同一个** 'a —— 让返回值的来源合法。
//
// 4）如果两个参数标成不同的生命周期呢？
//        fn longest<'a, 'b>(x: &'a str, y: &'b str) -> &'a str
//    意思是“返回值一定借自 x”。但函数体里 else 分支返回了 y，类型是 &'b str，
//    和 &'a str 不一定兼容，编译报错。所以本题的正确写法是共用一个 'a。
//
// 5）生命周期标注会影响性能吗？
//    完全不会。它只是给编译器看的“类型层面的注释”，编译后消失，
//    不产生任何运行时代码。Rust 的“零成本抽象”就是指这类东西。
//
// 6）'static 是什么？
//    一个特殊的生命周期，表示“整个程序运行期间都有效”。
//    字符串字面量 "xyz" 就存放在二进制的只读数据段里，所以是 &'static str。
//    平时不要随手把所有引用都标成 'static，那会限制调用者（要求数据永生）。
//
// 7）为什么 main 里要写 `string1.as_str()`？
//    longest 的参数是 &str，而 string1 是 String。
//    有两种写法：
//        longest(string1.as_str(), string2)   // 显式借用
//        longest(&string1, string2)           // 依赖解引用强制转换（&String → &str）
//    两者等价，原题用的是前者。
//
// ============================================================================
//                          常 见 错 误 与 提 示
// ============================================================================
//
// 1. 只给参数加生命周期，忘了返回值：
//        fn longest<'a>(x: &'a str, y: &'a str) -> &str
//    → error[E0106]: missing lifetime specifier
//      （多个输入时，返回值不能省略）
//
// 2. 声明了 <'a> 但没用上：
//        fn longest<'a>(x: &str, y: &str) -> &str
//    → error[E0106] 仍然报错，外加
//      warning: lifetime parameter `'a` never used
//
// 3. 把生命周期参数写成 <a> 或 <'a,>：
//    → 语法错误。生命周期必须以单引号开头，且不能当类型用。
//
// 4. 两个参数标成不同期限却返回第一个：
//    → error[E0621]/[E0308] 之类，返回 y 的分支类型不匹配
//
// 5. 试图用 'static 蒙过去：
//        fn longest(x: &'static str, y: &'static str) -> &'static str
//    → 本题能编译（因为两个实参一个是 String 借出的临时引用，会失败！）
//      实际会报：borrowed value does not live long enough
//      （String 的借用不是 'static，不要滥用 'static）
//
// 6. 以为生命周期能让变量活得更久：
//    不会。变量的存活时间由它所在的作用域决定，
//    标注只是“描述”，不是“延长”。
//
// ============================================================================
//                          小 结
// ============================================================================
//
// 本题你需要记住：
//   1. 生命周期参数写成 `'a`，声明位置在函数名后的尖括号里；
//   2. 多个输入引用时，返回值必须显式标注生命周期，编译器不会猜；
//   3. `x: &'a str, y: &'a str, -> &'a str` 的含义是“三者共用一个期限”；
//   4. 标注不改变程序行为，只是把“借用关系”写给编译器看；
//   5. 'a 取的是所有相关借用中**较短**的那个。
//
// 一句话记忆：**生命周期是借条上的期限代号：借来的东西，不能比主人活得久。**
//
