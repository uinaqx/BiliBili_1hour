// ============================================================================
// 第 45 题 · options1 —— 用 Option 表示“可能没有值”
// ----------------------------------------------------------------------------
// 题目类型：test（让 #[test] 测试通过就算过关）
// 课件位置：第 3 章 · 3.4.3 Option<T>；也涉及第 4 章 · 4.3 match
// 难度：★★☆☆☆
// 前置知识：枚举、match（参考 enums1~enums3）、函数返回值、整数类型 u16
// ============================================================================
//
// 【题目要求】
// 冰箱里的冰淇淋数量函数 maybe_icecream 需要补全：
//   - 晚上 10 点（22 点）之前，还剩 5 个；
//   - 22 点及以后到 23 点，已经被人吃光了，剩 0 个；
//   - 时间超过 23（比如 25 点）属于“无效时间”，要返回“没有信息”。
// 同时修复第二个测试 raw_value：把 Option 里的值取出来再比较。
//
// 原题代码（未完成，仅供对照）：
//     fn maybe_icecream(time_of_day: u16) -> Option<u16> {
//         // TODO: Complete the function body - remember to return an Option!
//         ???
//     }
//
//     #[test]
//     fn raw_value() {
//         let icecreams = maybe_icecream(12);
//         assert_eq!(icecreams, 5);   // ← Option<u16> 和整数 5 不能直接比
//     }
//
// 【解题思路】
// 1. 看返回值类型 `Option<u16>`：它只可能是两种东西之一
//        Some(数字)  —— 有值，值装在盒子里
//        None        —— 没值，空盒子
//    所以函数体每个分支都必须返回这两者之一，绝不能直接 `return 5;`。
// 2. 分三种情况，正好用 match 对 `time_of_day` 做模式匹配：
//        0..=21  → Some(5)    （0 点到 21 点：还有 5 个）
//        22..=23 → Some(0)    （22、23 点：被吃光了，但“确实知道是 0 个”）
//        _       → None       （其余，如 25 点：无法回答）
// 3. 第二个测试的毛病：`maybe_icecream(12)` 返回的是 `Option<u16>`，
//    拿它和裸整数 5 比较当然不等（类型都不一样）。
//    要先把盒子打开：`.unwrap()` 取出里面的值，再和 5 比。
// 4. 注意“0 个”和“不知道”是两件不同的事：剩 0 个是 Some(0)，
//    时间无效才是 None。这是 Option 存在的全部意义。
//
// ============================================================================
//                              知 识 铺 垫
// ============================================================================
//
// ● Option<T> 是什么？—— 一个“可能有、也可能没有”的盒子
//   标准库里的定义（简化版）长这样：
//       enum Option<T> {
//           Some(T),   // 装着类型 T 的值
//           None,      // 什么都没有
//       }
//   `T` 是“占位符”，叫泛型参数：Option<u16> 就是“装着 u16 的盒子”，
//   Option<String> 就是“装着 String 的盒子”。（泛型详见第 48 题 generics1）
//
// ● 打个比方
//   Option<T> 就像快递柜的一个格子：
//       Some(5) —— 格子里有一个包裹，包裹里是 5；
//       None    —— 格子是空的，但格子本身还在。
//   你永远不能“直接”拿到包裹，必须先确认格子里有没有东西（match / unwrap / if let）。
//   Rust 用这个设计彻底取代了 C/Java 里的“空指针 null”，
//   编译器会强制你处理“没有值”的情况，从根上避免空指针崩溃。
//
// ● Some / None 从哪来？
//   它们不需要 use 引入，是“预导入（prelude）”里的名字，任何文件都能直接用。
//   写 `Some(5)` 时，编译器会根据上下文推断这是 `Option<u16>`。
//
// ● match 是什么？
//   `match 值 { 模式 => 结果, ... }` 从上到下逐个比对模式，第一个匹配的分支被执行。
//   match 必须是“穷尽（exhaustive）”的：所有可能的情况都要写到，
//   否则编译器报 error[E0004]: non-exhaustive patterns。
//   `_` 是通配模式，意思是“其他所有情况”，相当于 default。
//
// ● u16 是什么？
//   16 位无符号整数，范围 0..=65535。用 u16 表示“小时”很自然（不会为负）。
//   所以 `time_of_day` 不可能为负，我们只需要考虑“太大”的情况。
//
// ● 几个“开盒子”的工具（后面题目会反复用）
//   match  Option   { Some(v) => ..., None => ... }   最安全，强制处理两种情况
//   if let Some(v) = opt { ... }                      只关心有值的情况（见第 46 题）
//   opt.unwrap()                                      有值就拿出来，是 None 就 panic
//   opt.unwrap_or(0)                                  有值拿出来，没有就用默认值 0
//   opt.is_some() / opt.is_none()                     只问“有没有”，不取值
//
// ============================================================================
//                              参 考 答 案
// ============================================================================

// 函数签名：接收一个 u16（24 小时制的“点”），返回 Option<u16>（可能没有答案）
fn maybe_icecream(time_of_day: u16) -> Option<u16> {
    // match 对 time_of_day 的值做分支判断
    match time_of_day {
        // `0..=21` 是“闭区间模式”，匹配 0、1、2 …… 一直到 21
        // 晚上 10 点（22 点）之前，冰箱里还有 5 个
        0..=21 => Some(5),

        // 22 点和 23 点：冰淇淋已经被吃光了
        // 注意返回的是 Some(0) 而不是 None —— “确定是 0 个”也是一种有效信息
        22..=23 => Some(0),

        // `_` 通配符：剩下的所有情况（24、25、100 ……）都是无效时间
        // 这时我们“无法回答”，返回空盒子 None
        _ => None,
    }
    // match 本身是一个表达式，它的值就是函数的返回值，
    // 所以这里不需要写 return，也不需要分号（最后不写分号 = 返回这个值）
}

#[cfg(test)]
mod tests {
    // `use super::*;` 把外层（父模块）的所有名字导入进来，
    // 这样测试里才能直接调用 maybe_icecream
    use super::*;

    #[test]
    fn check_icecream() {
        // 9 点：10 点之前 → 5 个
        assert_eq!(maybe_icecream(9), Some(5));
        // 10 点：仍然是 10 点之前（22 点才是晚上 10 点）→ 5 个
        assert_eq!(maybe_icecream(10), Some(5));
        // 23 点：被吃光 → Some(0)
        assert_eq!(maybe_icecream(23), Some(0));
        // 22 点：被吃光 → Some(0)
        assert_eq!(maybe_icecream(22), Some(0));
        // 25 点：不存在的时间 → 空盒子 None
        assert_eq!(maybe_icecream(25), None);
    }

    #[test]
    fn raw_value() {
        // unwrap()：把 Some 里的值取出来；如果遇到 None 就会 panic
        // 这里 12 点一定返回 Some(5)，所以 unwrap 是安全的
        let icecreams = maybe_icecream(12).unwrap();
        // 现在 icecreams 是 u16 的 5，可以和整数 5 比较了
        assert_eq!(icecreams, 5);
    }
}

// ============================================================================
//                            详 细 解 析
// ============================================================================
//
// 1）为什么 22 点和 23 点返回 Some(0)，而不是 None？
//    “冰箱里有 0 个冰淇淋”是一个确定的答案；
//    “25 点”根本不是一个合法的时间，我们无法给出答案。
//    Option 把这两种“没有”区分开了：
//        Some(0) —— 有答案，答案是 0
//        None    —— 压根没有答案
//    如果用 0 表示“无效”，调用者就分不清“真的是 0 个”还是“查询失败”，
//    这正是 C 语言用 -1 / NULL 表示错误的经典坑。
//
// 2）区间模式 0..=21 和 0..21 的区别？
//       0..=21  闭区间，包含 21（0,1,...,21 共 22 个值）
//       0..21   左闭右开，不包含 21（0,1,...,20）
//    本题 21 点还没到 22 点，应该返回 5，所以必须写 `..=`。
//
// 3）match 的检查到底有多严？
//    如果把 `_ => None` 删掉，编译器立刻报：
//        error[E0004]: non-exhaustive patterns: `24_u16..=u16::MAX` not covered
//    它在提醒你：“24 到 65535 这些情况你没处理！”
//    这就是“穷尽性检查”——Rust 不允许你漏掉任何一种可能。
//    反过来，如果你写了 `_`，编译器就不会再抱怨，但你要自己保证 `_` 的语义正确。
//
// 4）函数体最后为什么没有 return、没有分号？
//    Rust 的函数返回值 = 函数体最后一个表达式的值（不带分号）。
//    `match { ... }` 是表达式，它的每个分支都是表达式（Some(5) / None），
//    所以整个 match 的值就是函数的返回值。
//    如果写成 `match { ... };`（加了分号），它就变成语句，
//    函数返回值就变成 `()`，与 `Option<u16>` 不符，报 error[E0308]。
//
// 5）unwrap() 到底是什么？
//    它的实现大意是：
//        match self {
//            Some(v) => v,
//            None => panic!("called `Option::unwrap()` on a `None` value"),
//        }
//    也就是说：有值就给值，没值就让程序崩溃。
//    在测试里、或者你 100% 确定有值时可以用；
//    在生产代码里更推荐 `unwrap_or(默认值)`、`unwrap_or_else(...)`、`?` 运算符或 match。
//    更友好的写法是 `.expect("12 点应该有冰淇淋")`，崩溃信息里会带上你的说明。
//
// 6）为什么 assert_eq!(maybe_icecream(9), Some(5)) 里不用 unwrap？
//    因为 assert_eq! 要求两边类型相同，而 Some(5) 也是 Option<u16>，
//    两个 Option 可以直接比较（标准库为 Option 实现了 PartialEq）。
//    换句话说：比较“盒子”是可以的，但拿“盒子”和“盒子里的东西”比就不行。
//
// ============================================================================
//                          常 见 错 误 与 提 示
// ============================================================================
//
// 1. 直接返回数字，忘了包 Some：
//        fn maybe_icecream(t: u16) -> Option<u16> { 5 }
//    → error[E0308]: mismatched types
//      expected enum `Option<u16>`, found integer
//
// 2. 只写了 Some 分支，没写 None 分支：
//        match time_of_day { 0..=21 => Some(5), _ => Some(0) }
//    → 编译能过，但 maybe_icecream(25) 返回 Some(0)，测试 FAILED
//
// 3. 把 22 点之前的条件写成 `0..22`（漏掉 21）：
//    → maybe_icecream(21) 落到下一个分支，返回 Some(0)，语义错了
//      （本题测试没覆盖 21，但这是隐藏的逻辑错误）
//
// 4. raw_value 里忘了 unwrap：
//        assert_eq!(icecreams, 5);
//    → error[E0308]: mismatched types
//      expected enum `Option<u16>`, found integer
//    或者写成 assert_eq!(icecreams, Some(5)); 也能过，但题目要求“取出里面的值”。
//
// 5. 在 raw_value 里对 None 用 unwrap：
//    本题 12 点不会返回 None，但如果改成 maybe_icecream(99).unwrap()，
//    → 运行期 panic: called `Option::unwrap()` on a `None` value
//
// 6. 用 `if time_of_day < 22 { Some(5) }` 却忘了 else：
//    → error[E0308]: `if` may be missing an `else` clause
//    （if 是表达式，少一个分支就没有值可用；要么补 else，要么用 match）
//
// ============================================================================
//                          小 结
// ============================================================================
//
// 本题你需要记住：
//   1. Option<T> 只有两个变体：Some(值) 和 None，用它可以安全地表示“可能没有”；
//   2. 处理 Option 最正规的方式是 match，编译器会强制你写全所有分支；
//   3. “值为 0”和“没有值”是两码事，别用 0 当哨兵值；
//   4. unwrap() 是“强行开盒”，None 时会 panic，只在确定有值时使用。
//
// 一句话记忆：**Option 是快递柜：Some 里有包裹，None 是空格子，开柜前先看清楚。**
//
