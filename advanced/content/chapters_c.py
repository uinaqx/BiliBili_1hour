scene(c,'07-5','Mutex 与互斥访问','''
除了发消息，有时几项任务必须修改同一份数据。Mutex 可以规定，同一时刻只有拿到锁的一方进入受保护的修改过程。先在单线程里看它怎么用，这样不会同时混进线程调度的问题。

lock 成功后，会得到一个守卫。通过守卫读写里面的值，守卫离开作用域时，锁自动释放。画面特意用一对花括号把加分过程包起来，再在外面重新加锁读取。不要把锁拿得过久，也不要拿着同一个锁，又在同一条执行路径上等待自己重新取得它。锁解决的是有秩序地访问，不是把任何程序都自动变成既正确又高效的并发程序。
''','''
use std::sync::Mutex;
fn main() {
    let score = Mutex::new(80);
    {
        let mut guard = score.lock().unwrap();
        *guard += 5;
    }
    println!("{}", *score.lock().unwrap());
}
''','85\n',['lock 成功后取得守卫','通过守卫修改数据','守卫离开时自动解锁'],diagram='mutex')
