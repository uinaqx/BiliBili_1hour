BINARY='''int findIndex(const vector<int>& a, int target) {
    int lo=0, hi=static_cast<int>(a.size());
    while (lo < hi) {
        int mid=lo+(hi-lo)/2;
        if (a[mid] < target) lo=mid+1;
        else hi=mid;
    }
    if (lo < static_cast<int>(a.size())
        && a[lo] == target) return lo;
    return -1;
}'''
